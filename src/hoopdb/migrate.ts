/**
 * The release target gate, shared by the release plan, the operator plan and the
 * migrator (under its lock). Splits the schema steps, in migrator order (the upstream
 * lane, then the 96bulls lane), at the target: expectedPending = the pending steps up
 * to and including it, held = the pending steps after it. Fails closed when the tree
 * has no such step (release_target_unknown), when the target is already applied
 * (release_target_not_pending), or when a step of the target's own lane after it is
 * already applied, i.e. the target is below that lane's ledgered tail
 * (release_target_passed). Each lane is its own contiguous prefix (sequencePreflight,
 * ledger_gap, unchanged), so applied steps of the later lane are already done and
 * untouched.
 */
export function migrationTargetSplit(
  steps: { name: string; pending: boolean }[],
  target: string,
): { expectedPending: string[]; held: string[] } {
  const schema = steps.filter(
    (s) => s.name.startsWith("upstream:") || s.name.startsWith("96bulls:"),
  );
  const at = schema.findIndex((s) => s.name === target);
  if (at < 0)
    throw profileError("release_target_unknown", "the release target is not a schema step of this tree");
  if (!schema[at]!.pending)
    throw profileError("release_target_not_pending", "the release target is already applied");
  const lane = (name: string) => name.slice(0, name.indexOf(":") + 1);
  const after = schema.slice(at + 1);
  if (after.some((s) => !s.pending && lane(s.name) === lane(target)))
    throw profileError("release_target_passed", "a step after the release target is already applied");
  return {
    expectedPending: schema.slice(0, at + 1).filter((s) => s.pending).map((s) => s.name),
    held: after.filter((s) => s.pending).map((s) => s.name),
  };
}

/** Shared read-only preflight: release planning and apply enforce the same guards. */
async function migrationPreflight(client: MigrationClient, profile: MigrationProfile, schema: Step[]) {
  const physical = await readLedger(client);
  const stepShas = await stepSha256s(schema);
  // The release binding covers the rows exactly as stored, before any in-memory adoption.
  const ledgerSha256 = migrationLedgerSha256(physical);
  // Once, before every guard and reader below, through the one verdict readiness also
  // uses (resolveRenamedLedger): exact original-name rows of append-only renamed
  // migrations become their release names in memory only; any other alias state
  // (collision, wrong sha, missing repair, original sha under the release name) refuses.
  const renamed = resolveRenamedLedger(physical, (name) => stepShas.get(name));
  const renameAliases = renamed.adopted;
  for (const alias of renameAliases)
    log.info("adopted renamed migration ledger row", alias);
  const refusal = renamed.refusals[0];
  if (refusal) throw guardError(refusal.code, refusal.message);
  const ledger = renamed.effective;
  // A HoopDb built from the old vendored pin cannot be moved forward in place:
  // upstream changed 20261025000600 after it was applied there. Say so plainly.
  if ([...ledger.keys()].some((n) => n.startsWith("vendor:"))) {
    throw Object.assign(
      new Error(
        "96bulls: this HoopDb was built from the old vendored relayhistory-cloud pin; recreate it (local: `96bulls down <stage> --purge`, then `up`)",
      ),
      {
        code: "legacy_schema",
      },
    );
  }
  if (profile.mode === "rds")
    await (profile.rdsLayout === "separate-database"
      ? rdsSeparateOwnerPreflight(client)
      : rdsOwnerPreflight(client));
  const runtime = await runtimeRolePreflight(client, profile);
  // Durable function boundary gate, every non-local mode: the selected control must be
  // proven by the catalog. Only explicit local (Docker dev) mode is ungated.
  if (profile.mode !== "local") {
    const evidence = await functionBoundaryEvidence(
      client,
      profile.functionBoundary,
      profile.mode,
      profile.runtimeRole,
    );
    if (!evidence.satisfied)
      throw profileError(
        "function_boundary_unproven",
        `no catalog-proven function boundary (HOOPDB_FUNCTION_BOUNDARY_MODE): ${JSON.stringify(evidence)}; see the runbook "Function boundary"`,
      );
  }
  await cliHistoryPreflight(client, schema);
  await sequencePreflight(client, schema, ledger);
  // Adoptable-index steps (20261105044020, 20261105044040): an absent index on a populated table without the
  // opt-in refuses HERE, read-only, so the release plan goes red and a refused apply never
  // reaches the 'pending' readiness marker below.
  await adoptableIndexBuildPreflight(client, schema, ledger, {
    allowBlockingIndexBuild: profile.allowBlockingIndexBuild === true,
  });
  return { ledger, ledgerSha256, renameAliases, runtime };
}
/** Each step's file sha256, by step name. */
async function stepSha256s(steps: Step[]): Promise<Map<string, string>> {
  const shas = new Map<string, string>();
  for (const step of steps)
    shas.set(
      step.name,
      createHash("sha256").update(await readFile(step.path, "utf8")).digest("hex"),
    );
  return shas;
}
export function migrationLedgerSha256(ledger: Map<string, string>): string {
  return createHash("sha256").update(JSON.stringify([...ledger].sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0))).digest("hex");
}
/** Caller owns the READ ONLY transaction; never invokes bootstrap or schema SQL. */
export async function inspectMigrations(client: MigrationClient, profile: MigrationProfile) {
  if (profile.mode !== "supabase" || profile.shim || profile.bootstrap || !profile.verify)
    throw profileError("release_profile", "release inspection requires Supabase, verifier enabled, shim/bootstrap disabled");
  const steps = await schemaSteps();
  const { ledger, ledgerSha256, renameAliases } = await migrationPreflight(client, profile, steps);
  // The pending steps' SQL: the preview credits the EXECUTE grants they add (pending-added).
  const pendingSql = await Promise.all(steps.filter(s => !ledger.has(s.name)).map(s => readFile(s.path, "utf8")));
  const acl = await sessionsFunctionAclPreview(client, profile.runtimeRole, pendingSql);
  if (acl.function_acl_drift_extra.length || acl.function_acl_missing_refused.length)
    throw profileError("function_acl_drift", "release inspection refused ACL drift");
  // Prerequisites only, no provisioning. Authoritative migration/phase-2 SQL still
  // verifies the complete role contract, including memberships and effective grants.
  // Each role is accepted in its exact steady shape: the worker is NOLOGIN
  // with precisely the 2s marker, the verifier is bare with no settings, and
  // the consumer is bare OR operator-claimed (LOGIN with exactly the 60s
  // marker, nothing else). Once the writer is live, every later release
  // inspection must converge instead of refusing the claim.
  const roles = (await client.query<{rolname:string; login:boolean; attrs:boolean; settings:unknown; dbs:number[]|null}>(`
    SELECT rolname, r.rolcanlogin AS login,
      NOT (r.rolinherit OR r.rolsuper OR r.rolbypassrls OR r.rolcreatedb OR r.rolcreaterole OR r.rolreplication) AS attrs,
      (SELECT array_agg(s.setconfig) FROM pg_db_role_setting s WHERE s.setrole = r.oid) AS settings,
      (SELECT array_agg(s.setdatabase) FROM pg_db_role_setting s WHERE s.setrole = r.oid) AS dbs
      FROM pg_roles r WHERE rolname = ANY($1::text[])`,
    [["session_directory_search_worker", "session_token_verifier", "search_consumer_runtime"]])).rows;
  const byName = new Map(roles.map(r => [r.rolname, r]));
  // settings arrives as a nested array (array_agg over text[]); stringify so
  // node-pg and PGlite agree on the shape.
  const exact = (r: {settings:unknown; dbs:number[]|null} | undefined, marker: string) =>
    !!r && JSON.stringify(r.settings) === JSON.stringify([[marker]]) &&
    !!r.dbs && r.dbs.length === 1 && r.dbs[0] === 0;
  const worker = byName.get("session_directory_search_worker");
  const verifier = byName.get("session_token_verifier");
  const consumer = byName.get("search_consumer_runtime");
  const steady =
    !!worker && !worker.login && worker.attrs && exact(worker, "statement_timeout=2s") &&
    !!verifier && !verifier.login && verifier.attrs && !verifier.settings &&
    !!consumer && consumer.attrs &&
    ((!consumer.login && !consumer.settings) ||
      (consumer.login && exact(consumer, "statement_timeout=60s")));
  if (!steady)
    throw profileError("bootstrap_prerequisite", "operator-provisioned search/token/consumer roles absent or unsafe (worker carries exactly the 2s marker, verifier is bare, consumer is bare or operator-claimed with exactly the 60s marker)");
  const inventory = [];
  for (const step of steps) inventory.push({
    name: step.name,
    sha256: createHash("sha256").update(await readFile(step.path, "utf8")).digest("hex"),
    pending: !ledger.has(step.name),
  });
  return { generation: await generation(), ledgerSha256, inventory, acl, migrationRenameAliases: renameAliases };
}

/**
 * Applies the plan on one connection. Readiness marker (ROLE_VALIDATION_TABLE):
 *   1. under the advisory lock, before any step runs, the row is set to
 *      ('pending', <generation>): from here every reader is non-ready;
 *   2. only a successful phase 2, in the same transaction, sets it to 'pass' for the
 *      generation it validated. With a release target that holds steps, that is the
 *      generation of the bound target commit (targetBinding: the prefix steps plus that
 *      commit's own verifiers), never the full-tree one, and only after both this
 *      tree's verifiers and the target commit's have passed: an image built at the
 *      target commit reads it as ready, an image of the full tree stays schema_pending
 *      until a later run applies the held steps;
 *   3. any failure, crash or a disabled verifier (HOOPDB_ROLE_VERIFY=false) leaves
 *      it 'pending'. With the verifier disabled only an external verifier
 *      (supabase/bootstrap/session_directory_search_worker_mark_pass.sql) can pass it.
 */
export async function runMigrations(
  client: MigrationClient,
  opts: RunOptions = {},
): Promise<{ applied: number; skipped: number; held: string[] }> {
  let applied = 0;
  let skipped = 0;
  let held = new Set<string>();
  const profile = opts.profile ?? migrationProfile();
  // One migrator at a time; every marker transition happens while this lock is held.
  await client.query("SELECT pg_advisory_lock(961996, 1)");
  try {
    const steps = opts.steps ?? (await plan(profile));
    const schema = steps.filter(
      (st) => st.name.startsWith("upstream:") || st.name.startsWith("96bulls:"),
    );
    // Read-only preflight, all under the lock: nothing below writes until every check passes.
    const { ledger, ledgerSha256, runtime } = await migrationPreflight(client, profile, schema);
    if (opts.expectedLedgerSha256 !== undefined &&
        ledgerSha256 !== opts.expectedLedgerSha256)
      throw profileError("release_ledger_changed", "database ledger changed since the approved read-only plan");
    // Release target gate, still read-only and under the lock: the pending set is exactly
    // the approved one, and steps after the target are held (skipped below).
    if (
      opts.target !== undefined ||
      opts.expectedPending !== undefined ||
      opts.targetGeneration !== undefined ||
      opts.targetBinding !== undefined
    ) {
      if (opts.target === undefined)
        throw profileError("release_target_required", "expectedPending, targetGeneration and targetBinding require a release target");
      const split = migrationTargetSplit(
        schema.map((s) => ({ name: s.name, pending: !ledger.has(s.name) })),
        opts.target,
      );
      if (
        opts.expectedPending !== undefined &&
        (opts.expectedPending.length !== split.expectedPending.length ||
          opts.expectedPending.some((n, i) => n !== split.expectedPending[i]))
      )
        throw profileError("release_target_pending_changed", "pending steps up to the release target differ from the approved plan");
      held = new Set(split.held);
    }
    // The generation this run validates and marks PASS. No target binding: generation()
    // of this tree (unchanged). With a binding (required whenever steps are held): the
    // generation of the bound target commit, recomputed here, under the lock, from the
    // on-disk prefix (this plan's schema steps without the held ones) plus the target
    // commit's verifier digests; the manifest digest must equal the approved one, so a
    // prefix file changed on disk since the plan refuses before any write.
    const binding = opts.targetBinding;
    if (held.size && !binding)
      throw profileError("release_target_binding_required", "steps are held: the run needs the approved target commit binding");
    let targetVerify: Step[] = [];
    let gen: string;
    if (binding) {
      if (!steps.some((s) => s.name.startsWith("verify:")))
        throw profileError("release_target_verify_required", "a release target binding needs the in-process phase 2 verifiers");
      const names = RELEASE_TREE.verifiers.map((v) => v.name);
      if (
        binding.verifiers.length !== names.length ||
        binding.verifiers.some(
          (v, i) => v.name !== names[i] || typeof v.sql !== "string" || sha256Text(v.sql) !== v.sha256,
        )
      )
        throw profileError("release_target_manifest_changed", "the target commit's verifiers differ from their approved digests");
      const manifest: ReleaseManifest = {
        targetSha: binding.targetSha,
        target: opts.target!,
        steps: [...(await stepSha256s(schema.filter((s) => !held.has(s.name))))],
        verifiers: binding.verifiers.map((v) => [v.name, v.sha256]),
      };
      if (releaseManifestDigest(manifest) !== binding.manifestDigest)
        throw profileError("release_target_manifest_changed", "the prefix or target verifiers differ from the approved manifest");
      gen = manifestGeneration(manifest);
      // Nothing held: the target commit must compute this tree's own generation.
      if (!held.size && gen !== (await generation()))
        throw profileError("release_target_generation_changed", "nothing is held but the target commit's generation is not this tree's");
      targetVerify = binding.verifiers.map((v) => ({
        name: `verify:target:${v.name.slice("verify:".length)}`,
        path: `${binding.targetSha}:${RELEASE_TREE.verifiers.find((r) => r.name === v.name)!.path}`,
        sql: v.sql,
      }));
    } else gen = await generation();
    if (opts.targetGeneration !== undefined && opts.targetGeneration !== gen)
      throw profileError("release_target_generation_changed", "the target generation differs from the approved plan");
    // Phase 2 order: this tree's verifiers (in plan order), then the target commit's.
    const runSteps = [...steps, ...targetVerify];
    if (opts.beforeWrite) await opts.beforeWrite();
    await client.query("CREATE SCHEMA IF NOT EXISTS sessions");
    await client.query(`CREATE TABLE IF NOT EXISTS ${MIGRATION_LEDGER} (
      name text PRIMARY KEY,
      sha256 text NOT NULL,
      applied_at timestamptz NOT NULL DEFAULT now()
    )`);
    await client.query(`CREATE TABLE IF NOT EXISTS ${ROLE_VALIDATION_TABLE} (
      name text PRIMARY KEY,
      generation text NOT NULL,
      status text NOT NULL CHECK (status IN ('pending', 'pass')),
      updated_at timestamptz NOT NULL DEFAULT now()
    )`);
    await client.query(`REVOKE ALL ON ${ROLE_VALIDATION_TABLE} FROM PUBLIC`);
    // Bootstrap the readiness subset first. After every schema step, hardenAndCheck adds
    // the immutable application ACL and validates the complete catalog before PASS.
    if (runtime === "dedicated") {
      const grant = await client.query<{ sql: string }>(
        "SELECT format('GRANT USAGE ON SCHEMA sessions TO %I; GRANT SELECT ON %s, %s TO %I', $3::text, $1::text, $2::text, $3::text) AS sql",
        [MIGRATION_LEDGER, ROLE_VALIDATION_TABLE, profile.runtimeRole],
      );
      await client.query(grant.rows[0]!.sql);
    }
    // Pending first: committed before any migration can become visible.
    await client.query(MARKER_PENDING_SQL, [ROLE_VALIDATION_NAME, gen]);
    log.info("role validation pending", { reason: gen });
    // After the last migration, before phase 2 can mark PASS: the runtime role holds
    // exactly the approved grants against the full schema (e.g. no EXECUTE gained on a
    // function a migration just created).
    // Inside the validation transaction (with phase 2 and the PASS write): revoke PUBLIC
    // EXECUTE on every sessions function (idempotent; triggers still fire, PostgreSQL
    // does not check EXECUTE on a trigger function at fire time), then check the runtime
    // role against the full schema. Any failure rolls all of it back.
    // Held steps' SQL: the exact ACL manifest is the full tree's, so the drift check
    // skips only the manifest functions a held step creates and that do not exist yet
    // (sessionsFunctionAclDrift); every existing function is still compared exactly.
    const heldSql: string[] = [];
    for (const st of schema) if (held.has(st.name)) heldSql.push(await readFile(st.path, "utf8"));
    const hardenAndCheck = async () => {
      await client.query(
        "REVOKE EXECUTE ON ALL FUNCTIONS IN SCHEMA sessions FROM PUBLIC",
      );
      if (runtime !== "dedicated") return;
      await installRuntimeApplicationAcl(client, profile.runtimeRole);
      const violations = await runtimeRoleViolations(
        client,
        runtimeCfg(profile),
        RUNTIME_TABLES,
        "post",
      );
      if (violations.length)
        throw profileError(
          "runtime_role_unsafe",
          `HOOPDB_RUNTIME_ROLE ${profile.runtimeRole} is not least-privilege: ${violations.join(", ")}`,
        );
      // Every non-local boundary mode (global-default-revoke in selfhosted, cloudsql and rds,
      // event-trigger in supabase): every sessions function ACL must equal the committed
      // manifest plus the runtime application ACL exactly, or the whole validation
      // transaction (with phase 2 and PASS) rolls back and the marker stays pending.
      // Local (Docker dev) mode is unchanged: no check.
      const drift =
        profile.mode !== "local"
          ? await sessionsFunctionAclDrift(client, profile.runtimeRole, heldSql)
          : [];
      if (drift.length)
        throw profileError(
          "function_acl_drift",
          `sessions function ACLs differ from src/hoopdb/sessions-function-acl.json: ${drift.slice(0, 5).join("; ")}${drift.length > 5 ? `; and ${drift.length - 5} more` : ""}`,
        );
    };
    const bindDbMode = () =>
      client.query(
        "SELECT set_config('hoopdb.db_mode', $1, true), set_config('hoopdb.allow_blocking_index_build', $2, true)",
        [profile.mode, profile.allowBlockingIndexBuild === true ? "on" : "off"],
      );
    let postChecked = false;
    // The validation marker flips to 'pass' once, after every phase-2 verifier
    // has passed: only the last verify step does the UPDATE, so an earlier
    // failure can never leave a half-checked generation marked pass.
    const lastVerifyIndex = runSteps.reduce(
      (acc, s, i) => (s.name.startsWith("verify:") ? i : acc),
      -1,
    );
    for (const [stepIndex, step] of runSteps.entries()) {
      // Held steps (after the release target) are never applied or ledgered. Phase 2
      // still runs, against the prefix: this tree's fail-closed verifiers and hardening,
      // with the ACL manifest scoped to the prefix (heldSql), then the target commit's
      // verifiers (verify:target:*); PASS, for the target generation only (gen above),
      // is written by the last of them.
      if (held.has(step.name)) continue;
      const sql = step.sql ?? (await readFile(step.path, "utf8"));
      // The role checks (phase 1 bootstrap, phase 2 verify) run on every migrate, each in
      // its own transaction, and are never recorded in the ledger.
      if (
        step.name.startsWith("bootstrap:") ||
        step.name.startsWith("verify:")
      ) {
        const verify = step.name.startsWith("verify:");
        if (verify) postChecked = true;
        if (verify && opts.beforeVerify) await opts.beforeVerify();
        // The hardening takes AccessExclusiveLock (CREATE POLICY) on live tables, so
        // it can lose a deadlock to autovacuum (40P01, observed on the 462 release).
        // The whole transaction rolls back, so a bounded retry is safe.
        for (let attempt = 1; ; attempt++) {
          await client.query("BEGIN");
          try {
            await bindDbMode();
            if (verify) await hardenAndCheck();
            await client.query(sql);
            if (verify && stepIndex === lastVerifyIndex) {
              const passed = await client.query(
                `UPDATE ${ROLE_VALIDATION_TABLE} SET status = 'pass', updated_at = now()
                  WHERE name = $1 AND generation = $2 AND status = 'pending' RETURNING name`,
                [ROLE_VALIDATION_NAME, gen],
              );
              if (passed.rows.length !== 1)
                throw Object.assign(
                  new Error(
                    "96bulls: role validation marker was not pending for this generation",
                  ),
                  { code: "marker_lost" },
                );
            }
            await client.query("COMMIT");
            break;
          } catch (err) {
            await client.query("ROLLBACK");
            const code = (err as { code?: string }).code;
            if (code === "40P01" && attempt < ROLE_CHECK_DEADLOCK_ATTEMPTS) {
              log.warn("role check deadlocked; retrying", { reason: step.name, attempt });
              await new Promise((r) => setTimeout(r, attempt * 1000));
              continue;
            }
            log.error("role check failed", {
              reason: step.name,
              error_code: code ?? "role_check_failed",
            });
            throw err;
          }
        }
        log.info(verify ? "role validation passed" : "role check passed", {
          reason: verify ? gen : step.name,
        });
        continue;
      }
      const sha = createHash("sha256").update(sql).digest("hex");
      const seen = ledger.get(step.name);
      if (seen && migrationChecksumMatches(step.name, seen, sha)) {
        const alias = migrationChecksumAlias(step.name, seen, sha);
        if (alias) log.info("accepted historical migration checksum", alias);
        skipped += 1;
        continue;
      }
      if (seen && seen !== sha) {
        // Unreachable after sequencePreflight; kept as a second line of defense.
        throw new Error(
          `96bulls: migration ${step.name} changed after it was applied; add a new migration instead`,
        );
      }
      await client.query("BEGIN");
      try {
        await bindDbMode();
        await client.query(sql);
        await client.query(
          `INSERT INTO ${MIGRATION_LEDGER} (name, sha256) VALUES ($1, $2)`,
          [step.name, sha],
        );
        await client.query("COMMIT");
      } catch (err) {
        await client.query("ROLLBACK");
        log.error("migration failed", {
          reason: step.name,
          error_code: (err as { code?: string }).code ?? "migration_failed",
        });
        throw err;
      }
      applied += 1;
      log.info("migration applied", { reason: step.name });
    }
    if (held.size)
      log.warn("release target reached; steps held, validation bound to the target generation", {
        reason: gen,
        count: held.size,
      });
    if (!postChecked) {
      // In-process verifier off: the same hardening and runtime check, in one transaction.
      await client.query("BEGIN");
      try {
        await bindDbMode();
        await hardenAndCheck();
        await client.query("COMMIT");
      } catch (err) {
        await client.query("ROLLBACK");
        throw err;
      }
    }
    if (!steps.some((s) => s.name.startsWith("verify:")))
      log.info(
        "role validation left pending: in-process verifier disabled; an external verifier must pass it",
        { reason: gen },
      );
  } finally {
    await client
      .query("SELECT pg_advisory_unlock(961996, 1)")
      .catch(() => undefined);
  }
  log.info("hoopdb migrations complete", { count: applied, skipped });
  return { applied, skipped, held: [...held] };
}

const RUNTIME_TABLES = {
  ledger: MIGRATION_LEDGER,
  marker: ROLE_VALIDATION_TABLE,
};
const runtimeCfg = (p: MigrationProfile) => ({
  mode: p.mode,
  role: p.runtimeRole,
  ...(p.runtimeLogin === undefined ? {} : { login: p.runtimeLogin }),
  ...(p.workloadRole ? { workload: p.workloadRole } : {}),
  ...(p.rdsLayout ? { rdsLayout: p.rdsLayout } : {}),
});

/**
 * Install only the immutable trusted-backend ACL. Preflight has already rejected drift.
 * The policy is all-row by design because workers span tenants; the runtime role is a
 * service credential, never an end-user identity, and still has no ownership/BYPASSRLS.
 */
async function installRuntimeApplicationAcl(
  client: MigrationClient,
  role: string,
): Promise<void> {
  const catalog = runtimeApplicationAclCatalog();
  for (const [relation, privileges] of Object.entries(catalog.tables)) {
    const grant = await client.query<{ sql: string }>(
      "SELECT format('GRANT %s ON TABLE %s TO %I', $1::text, $2::regclass, $3::text) AS sql",
      [privileges.join(", "), relation, role],
    );
    await client.query(grant.rows[0]!.sql);
  }
  for (const sequence of catalog.sequences) {
    const grant = await client.query<{ sql: string }>(
      "SELECT format('GRANT USAGE ON SEQUENCE %s TO %I', $1::regclass, $2::text) AS sql",
      [sequence, role],
    );
    await client.query(grant.rows[0]!.sql);
  }
  for (const fn of catalog.functions) {
    const grant = await client.query<{ sql: string }>(
      "SELECT format('GRANT EXECUTE ON FUNCTION %s TO %I', $1::regprocedure, $2::text) AS sql",
      [fn, role],
    );
    await client.query(grant.rows[0]!.sql);
  }
  for (const relation of catalog.rlsTables) {
    const exists = await client.query<{ present: boolean }>(
      `SELECT EXISTS (SELECT 1 FROM pg_policy
        WHERE polrelid = $1::regclass AND polname = $2) AS present`,
      [relation, RUNTIME_APPLICATION_POLICY],
    );
    if (exists.rows[0]!.present) continue;
    const create = await client.query<{ sql: string }>(
      "SELECT format('CREATE POLICY %I ON %s AS PERMISSIVE FOR ALL TO %I USING (true) WITH CHECK (true)', $1::text, $2::regclass, $3::text) AS sql",
      [RUNTIME_APPLICATION_POLICY, relation, role],
    );
    await client.query(create.rows[0]!.sql);
  }
}

async function readLedger(
  client: MigrationClient,
): Promise<Map<string, string>> {
  const there = (
    await client.query<{ r: string | null }>(
      "SELECT to_regclass($1)::text AS r",
      [MIGRATION_LEDGER],
    )
  ).rows[0]?.r;
  if (!there) return new Map();
  return new Map(
    (
      await client.query<{ name: string; sha256: string }>(
        `SELECT name, sha256 FROM ${MIGRATION_LEDGER}`,
      )
    ).rows.map((r) => [r.name, r.sha256]),
  );
}

/**
 * The runtime role must exist and be dedicated: the migrator itself (owner-run) is
 * accepted only in local mode. A dedicated role must pass the exact least-privilege
 * allowlist (runtimeRoleViolations). Otherwise it fails closed before any write.
 */
async function runtimeRolePreflight(
  client: MigrationClient,
  profile: MigrationProfile,
): Promise<"owner" | "dedicated"> {
  const r = (
    await client.query<{ rolname: string; me: string }>(
      "SELECT rolname, current_user AS me FROM pg_roles WHERE rolname = $1",
      [profile.runtimeRole],
    )
  ).rows[0];
  if (!r)
    throw profileError(
      "runtime_role_missing",
      `HOOPDB_RUNTIME_ROLE ${profile.runtimeRole} does not exist; nothing was written`,
    );
  if (r.rolname === r.me) {
    if (profile.mode !== "local")
      throw profileError(
        "runtime_role_unsafe",
        `in ${profile.mode} mode the services need a dedicated runtime role, not the migration owner`,
      );
    return "owner";
  }
  if (r.rolname === ROLE_VALIDATION_NAME)
    throw profileError(
      "runtime_role_unsafe",
      "HOOPDB_RUNTIME_ROLE must not be the search Worker",
    );
  const violations = await runtimeRoleViolations(
    client,
    runtimeCfg(profile),
    RUNTIME_TABLES,
    "pre",
  );
  if (violations.length)
    throw profileError(
      "runtime_role_unsafe",
      `HOOPDB_RUNTIME_ROLE ${profile.runtimeRole} is not least-privilege: ${violations.join(", ")}`,
    );
  return "dedicated";
}

/**
 * rds mode only, read-only, before any write: the catalog must show the RDS shape the
 * mode's exceptions are written for: PostgreSQL 16+, and the migration owner
 * (current_user) is NOT a superuser, has CREATEROLE and is a member of rds_superuser;
 * AWS's fixed rdsadmin
 * exists, is SUPERUSER and is not the owner. Mode is configuration, so this keeps the
 * rds exceptions (rdsadmin excluded from creator coverage, the exact owner creator edge
 * on the runtime role) from being selected against a server that is not RDS-shaped.
 */
async function rdsOwnerPreflight(client: MigrationClient): Promise<void> {
  const r = (
    await client.query<{
      owner_super: boolean;
      owner_createrole: boolean;
      owner_rds_superuser: boolean;
      rdsadmin_super: boolean;
      server_version_num: number;
    }>(
      `SELECT me.rolsuper AS owner_super, me.rolcreaterole AS owner_createrole,
              EXISTS (SELECT 1 FROM pg_roles r
                       WHERE r.rolname = 'rds_superuser' AND pg_has_role(me.oid, r.oid, 'MEMBER')) AS owner_rds_superuser,
              current_setting('server_version_num')::int AS server_version_num,
              coalesce((SELECT a.rolsuper AND a.oid <> me.oid FROM pg_roles a WHERE a.rolname = 'rdsadmin'), false) AS rdsadmin_super
         FROM pg_roles me WHERE me.rolname = current_user`,
    )
  ).rows[0];
  if (
    !r ||
    r.owner_super ||
    !r.owner_createrole ||
    !r.owner_rds_superuser ||
    !r.rdsadmin_super ||
    r.server_version_num < 160000
  )
    throw profileError(
      "rds_profile_unproven",
      `rds mode needs PostgreSQL 16+, a non-superuser CREATEROLE rds_superuser member as migration owner and the fixed rdsadmin SUPERUSER: ${JSON.stringify(r ?? null)}; nothing was written`,
    );
}

/**
 * rds mode with HOOPDB_RDS_LAYOUT=separate-database (rds-activation/v1), read-only,
 * before any write.
 *
 * Why the master-owner preflight cannot be reused: it requires the migration owner to
 * be a CREATEROLE member of rds_superuser. That membership is how it proves the server
 * is RDS-shaped, and it is the identity the legacy rds_* bootstrap files run as. In the
 * separate-database layout, hoop must be neither (infra #107: the master is
 * provisioning-only; docs/shared-database-isolation.md section 2). So a plain hoop that
 * owns its database fails with rds_profile_unproven, on both owner_rds_superuser and
 * owner_createrole.
 *
 * What this preflight proves instead (each failure is rds_profile_unproven):
 *   - PostgreSQL 16+; session_user = current_user (no SET ROLE).
 *   - The owner is NOT SUPERUSER, CREATEROLE, CREATEDB, REPLICATION or BYPASSRLS.
 *   - The owner is a member of NO role (so not rds_superuser), and no role is a member
 *     of the owner (nobody can SET ROLE to it or inherit it).
 *   - RDS shape without membership: the fixed rdsadmin is SUPERUSER and is not the
 *     owner, and rds_superuser exists as NOLOGIN and not SUPERUSER.
 *   - The owner owns the current database and the sessions schema. The activation
 *     creates sessions, so a missing schema means the activation did not run.
 *   - The activation executor (hoopdb_activation_executor) no longer exists.
 * The rds function-boundary gate is unchanged: rds_superuser and the provisioner hold
 * exact defaults in this database (rds_activation/10), and rdsadmin stays the
 * excluded trust root.
 */
export async function rdsSeparateOwnerPreflight(client: MigrationClient): Promise<void> {
  const r = (
    await client.query<{
      server_version_num: number;
      same_session: boolean;
      owner_super: boolean;
      owner_createrole: boolean;
      owner_createdb: boolean;
      owner_replication: boolean;
      owner_bypassrls: boolean;
      owner_memberships: number;
      owner_members: number;
      rdsadmin_super: boolean;
      rds_superuser_shape: boolean;
      owns_database: boolean;
      owns_sessions: boolean;
      executor_present: boolean;
    }>(
      `SELECT current_setting('server_version_num')::int AS server_version_num,
              session_user = current_user AS same_session,
              me.rolsuper AS owner_super, me.rolcreaterole AS owner_createrole, me.rolcreatedb AS owner_createdb,
              me.rolreplication AS owner_replication, me.rolbypassrls AS owner_bypassrls,
              (SELECT count(*)::int FROM pg_catalog.pg_auth_members m WHERE m.member = me.oid) AS owner_memberships,
              (SELECT count(*)::int FROM pg_catalog.pg_auth_members m WHERE m.roleid = me.oid) AS owner_members,
              coalesce((SELECT a.rolsuper AND a.oid <> me.oid FROM pg_catalog.pg_roles a WHERE a.rolname = 'rdsadmin'), false) AS rdsadmin_super,
              coalesce((SELECT NOT s.rolsuper AND NOT s.rolcanlogin FROM pg_catalog.pg_roles s WHERE s.rolname = 'rds_superuser'), false) AS rds_superuser_shape,
              EXISTS (SELECT 1 FROM pg_catalog.pg_database d WHERE d.datname = current_database() AND d.datdba = me.oid) AS owns_database,
              EXISTS (SELECT 1 FROM pg_catalog.pg_namespace n WHERE n.nspname = 'sessions' AND n.nspowner = me.oid) AS owns_sessions,
              EXISTS (SELECT 1 FROM pg_catalog.pg_roles WHERE rolname = 'hoopdb_activation_executor') AS executor_present
         FROM pg_catalog.pg_roles me WHERE me.rolname = current_user`,
    )
  ).rows[0];
  const problems = !r
    ? ["owner role not found"]
    : [
        ...(r.server_version_num >= 160000 ? [] : ["PostgreSQL 16+ required"]),
        ...(r.same_session ? [] : ["session_user differs from current_user (SET ROLE)"]),
        ...(r.owner_super ? ["owner is SUPERUSER"] : []),
        ...(r.owner_createrole ? ["owner has CREATEROLE"] : []),
        ...(r.owner_createdb ? ["owner has CREATEDB"] : []),
        ...(r.owner_replication ? ["owner has REPLICATION"] : []),
        ...(r.owner_bypassrls ? ["owner has BYPASSRLS"] : []),
        ...(r.owner_memberships ? [`owner is a member of ${r.owner_memberships} role(s)`] : []),
        ...(r.owner_members ? [`owner has ${r.owner_members} member(s)`] : []),
        ...(r.rdsadmin_super ? [] : ["the fixed rdsadmin SUPERUSER was not proven"]),
        ...(r.rds_superuser_shape ? [] : ["rds_superuser (NOLOGIN, not SUPERUSER) was not proven"]),
        ...(r.owns_database ? [] : ["owner does not own the current database"]),
        ...(r.owns_sessions ? [] : ["owner does not own schema sessions (run rds-activation first)"]),
        ...(r.executor_present ? ["the activation executor hoopdb_activation_executor still exists"] : []),
      ];
  if (problems.length)
    throw profileError(
      "rds_profile_unproven",
      `rds separate-database layout needs a plain migration owner (member of no role, no CREATEROLE) that owns this database and sessions on an RDS-shaped server: ${problems.join("; ")}; nothing was written`,
    );
}

/**
 * Refuses, before any write, when Supabase's CLI history
 * (supabase_migrations.schema_migrations) records any of these migrations, or exists
 * but can't be read: `supabase db push` and this migrator must never both apply them
 * (mixed_migration_authority). See the runbook decision point.
 */
async function cliHistoryPreflight(
  client: MigrationClient,
  schema: Step[],
): Promise<void> {
  const reg = async (name: string) =>
    (
      await client.query<{ r: string | null }>(
        "SELECT to_regclass($1)::text AS r",
        [name],
      )
    ).rows[0]?.r ?? null;
  let cliHistory: string | null;
  try {
    cliHistory = await reg("supabase_migrations.schema_migrations");
  } catch (err) {
    // The schema exists but the migrator may not even look inside: it can't prove there
    // is no second authority.
    if ((err as { code?: string }).code === "42501")
      throw profileError(
        "mixed_migration_authority",
        "supabase_migrations exists but the migrator cannot read it; one authority only, see the runbook decision point",
      );
    throw err;
  }
  if (cliHistory) {
    const upstreamNames = new Set(
      schema.filter((st) => st.name.startsWith("upstream:")).map((st) => st.name),
    );
    // Renaming a released file must not hide a second migration authority: whenever
    // either name of a rename alias is in this plan, check both versions (from #396).
    for (const a of MIGRATION_RENAME_ALIASES)
      if (upstreamNames.has(a.migration) || upstreamNames.has(a.ledger_name)) {
        upstreamNames.add(a.migration);
        upstreamNames.add(a.ledger_name);
      }
    const versions = [
      ...new Set(
        [...upstreamNames].map((name) => name.slice("upstream:".length).split("_")[0]!),
      ),
    ].sort();
    let hit: { version: string }[];
    try {
      hit = (
        await client.query<{ version: string }>(
          "SELECT version FROM supabase_migrations.schema_migrations WHERE version = ANY($1::text[]) ORDER BY version",
          [versions],
        )
      ).rows;
    } catch (err) {
      // Present but unreadable by the migrator: it can't prove there is no second authority.
      if ((err as { code?: string }).code === "42501")
        throw profileError(
          "mixed_migration_authority",
          "supabase_migrations.schema_migrations exists but the migrator cannot read it; one authority only, see the runbook decision point",
        );
      throw err;
    }
    if (hit.length)
      throw profileError(
        "mixed_migration_authority",
        `supabase db push recorded ${hit.map((h) => h.version).join(", ")}; one authority only, see the runbook decision point`,
      );
  }
}

/** Read-only: does the ledger lack any migration this image would apply? */
/**
 * The SQL of every step the migrator would still run (no ledger row, or a recorded checksum
 * it would not skip), in step order; read-only. The ACL preview credits the EXECUTE grants
 * this SQL adds.
 */
export async function pendingMigrationSql(
  client: MigrationClient,
): Promise<string[]> {
  const steps = await schemaSteps();
  const has = await client.query<{ t: string | null }>(
    `SELECT to_regclass('${MIGRATION_LEDGER}')::text AS t`,
  );
  const done = has.rows[0]?.t
    ? new Map(
        (
          await client.query<{ name: string; sha256: string }>(
            `SELECT name, sha256 FROM ${MIGRATION_LEDGER}`,
          )
        ).rows.map((r) => [r.name, r.sha256]),
      )
    : new Map<string, string>();
  const shas = await stepSha256s(steps);
  const { effective } = resolveRenamedLedger(done, (name) => shas.get(name));
  // A recorded row counts as applied only with a checksum the migrator would skip.
  const pending = steps.filter((s) => {
    const seen = effective.get(s.name);
    return seen === undefined || !migrationChecksumMatches(s.name, seen, shas.get(s.name)!);
  });
  return Promise.all(pending.map((s) => readFile(s.path, "utf8")));
}

function migrationProfileMode(): FunctionBoundaryMode | undefined {
  const v = process.env.HOOPDB_FUNCTION_BOUNDARY_MODE;
  return v === "global-default-revoke" || v === "event-trigger" ? v : undefined;
}

export async function migrate(): Promise<{ applied: number; skipped: number }> {
  // Before any connection: an invalid profile fails here, having written nothing.
  const profile = migrationProfile();
  const db = openHoopDb();
  await waitForHoopDb(db);
  const client = await db.pool.connect();
  try {
    return await runMigrations(client, { profile });
  } finally {
    client.release();
    await db.end();
  }
}

/** Read-only: the checksum aliases and the rename adoptions the migrator would accept. */
async function checksumAliasEvidence(client: MigrationClient) {
  const there = (
    await client.query<{ r: string | null }>(
      "SELECT to_regclass($1)::text AS r",
      [MIGRATION_LEDGER],
    )
  ).rows[0]?.r;
  if (!there) return { checksum: [], rename: [] };
  const rows = (
    await client.query<{ name: string; sha256: string }>(
      `SELECT name, sha256 FROM ${MIGRATION_LEDGER}`,
    )
  ).rows;
  const actual = await stepSha256s(await schemaSteps());
  return {
    checksum: rows.flatMap((row) => {
      const alias = migrationChecksumAlias(
        row.name,
        row.sha256,
        actual.get(row.name) ?? "",
      );
      return alias ? [alias] : [];
    }),
    rename: resolveRenamedLedger(
      new Map(rows.map((r) => [r.name, r.sha256])),
      (name) => actual.get(name),
    ).adopted,
  };
}

