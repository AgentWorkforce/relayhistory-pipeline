/**
 * The database-mode contract. The migrator never infers the target from a hostname:
 * HOOPDB_DB_MODE is required and has no default.
 *   local       the Docker stack: plain Postgres, the migrator is its superuser.
 *   selfhosted  CNPG or another operator-controlled plain Postgres deployment.
 *   cloudsql    Google Cloud SQL: plain Postgres with Google's fixed platform superuser.
 *   rds         Amazon RDS for PostgreSQL (not Aurora): the migration owner is the
 *               non-superuser CREATEROLE master (a member of rds_superuser); the only
 *               superuser is AWS's fixed rdsadmin. The shim and the generic role
 *               bootstrap are refused (neither can run as a non-superuser); the operator
 *               runs the supabase/bootstrap/rds_*.sql files as the owner first.
 *   supabase    a Supabase project. The plain-Postgres role shim and the privileged
 *               role bootstrap are refused outright (supabase_shim.sql: "Never apply
 *               this to a Supabase project"); the roles are platform or operator steps.
 * HOOPDB_SUPABASE_SHIM must be set explicitly ("true" or "false") in local and
 * selfhosted and cloudsql mode, and may only be unset or "false" in supabase and rds mode.
 * HOOPDB_ROLE_BOOTSTRAP defaults to the shim choice and is likewise refused in supabase
 * mode. HOOPDB_RUNTIME_ROLE (required) names the role the services connect as: it gets
 * the exact application ACL in migrate-guards.ts plus read-only ledger/marker access.
 * Resolved before any connection; an invalid profile writes nothing anywhere.
 */
export type DbMode = "local" | "selfhosted" | "cloudsql" | "supabase" | "rds";
export interface MigrationProfile {
  mode: DbMode;
  shim: boolean;
  bootstrap: boolean;
  verify: boolean;
  runtimeRole: string;
  /** HOOPDB_RUNTIME_ROLE_LOGIN; required outside local mode (the role is dedicated there). */
  runtimeLogin?: boolean;
  /** HOOPDB_RUNTIME_WORKLOAD_ROLE: the one role allowed to be a member of the runtime role. */
  workloadRole?: string;
  /**
   * HOOPDB_FUNCTION_BOUNDARY_MODE: which durable function boundary the reviewed deployment
   * selects. Configuration, not a human approval: the gate passes only when the catalog
   * itself proves the selected control. Required outside local mode.
   */
  functionBoundary?: FunctionBoundaryMode;
  /**
   * HOOPDB_RDS_LAYOUT, rds mode only. "master-owner" (default, today's contract): the
   * migration owner is the RDS master, a CREATEROLE member of rds_superuser.
   * "separate-database" (rds-activation/v1, infra #107): the owner is a plain hoop that
   * owns its dedicated database and sessions, and is a member of no role. See
   * rdsSeparateOwnerPreflight and docs/rds-activation-executor.md.
   */
  rdsLayout?: RdsLayout;
  /**
   * HOOPDB_ALLOW_BLOCKING_INDEX_BUILD (default off): lets an index migration run a blocking
   * CREATE INDEX on a populated table instead of refusing. Bound per migration transaction as
   * hoopdb.allow_blocking_index_build (on/off); read by 20261105044020.
   */
  allowBlockingIndexBuild?: boolean;
}
export type RdsLayout = "master-owner" | "separate-database";

function profileError(code: string, message: string): Error {
  return Object.assign(new Error(`96bulls: ${message}`), { code });
}

function strictFlag(
  env: Record<string, string | undefined>,
  name: string,
): boolean | undefined {
  const v = env[name];
  if (v === undefined || v === "") return undefined;
  if (v === "1" || v.toLowerCase() === "true") return true;
  if (v === "0" || v.toLowerCase() === "false") return false;
  throw profileError(
    "db_profile_invalid",
    `${name} must be "true" or "false" (got "${v}")`,
  );
}

export function migrationProfile(
  env: Record<string, string | undefined> = process.env,
): MigrationProfile {
  const mode = env.HOOPDB_DB_MODE;
  if (
    mode !== "local" &&
    mode !== "selfhosted" &&
    mode !== "cloudsql" &&
    mode !== "supabase" &&
    mode !== "rds"
  )
    throw profileError(
      "db_mode_invalid",
      "HOOPDB_DB_MODE must be local, selfhosted, cloudsql, supabase or rds; there is no default",
    );
  const shim = strictFlag(env, "HOOPDB_SUPABASE_SHIM");
  const bootstrap = strictFlag(env, "HOOPDB_ROLE_BOOTSTRAP");
  const verify = strictFlag(env, "HOOPDB_ROLE_VERIFY") ?? true;
  if (mode !== "rds" && env.HOOPDB_RDS_LAYOUT)
    throw profileError(
      "db_profile_invalid",
      "HOOPDB_RDS_LAYOUT is only valid with HOOPDB_DB_MODE=rds",
    );
  if (mode === "supabase" && shim)
    throw profileError(
      "shim_forbidden",
      "the plain-Postgres role shim never runs in supabase mode",
    );
  if (mode === "supabase" && bootstrap)
    throw profileError(
      "bootstrap_forbidden",
      "the privileged role bootstrap never runs from the migrator in supabase mode",
    );
  // RDS: the master is not a superuser. The shim needs BYPASSRLS and the generic
  // bootstrap needs a superuser creator, so both are refused here rather than at the
  // first privileged statement; supabase/bootstrap/rds_migration_roles.sql replaces them.
  if (mode === "rds" && shim)
    throw profileError(
      "shim_forbidden",
      "the plain-Postgres role shim never runs in rds mode (use supabase/bootstrap/rds_migration_roles.sql)",
    );
  if (mode === "rds" && bootstrap)
    throw profileError(
      "bootstrap_forbidden",
      "the privileged role bootstrap never runs from the migrator in rds mode (use supabase/bootstrap/rds_migration_roles.sql)",
    );
  if (mode !== "supabase" && mode !== "rds" && shim === undefined)
    throw profileError(
      "shim_unset",
      `HOOPDB_SUPABASE_SHIM must be set explicitly in ${mode} mode`,
    );
  const ident = /^[A-Za-z_][A-Za-z0-9_$-]{0,62}$/;
  const runtimeRole = env.HOOPDB_RUNTIME_ROLE ?? "";
  if (!ident.test(runtimeRole))
    throw profileError(
      "runtime_role_unset",
      "HOOPDB_RUNTIME_ROLE must name the role the services connect as",
    );
  const runtimeLogin = strictFlag(env, "HOOPDB_RUNTIME_ROLE_LOGIN");
  if (mode !== "local" && runtimeLogin === undefined)
    throw profileError(
      "runtime_role_login_unset",
      `HOOPDB_RUNTIME_ROLE_LOGIN must be set explicitly in ${mode} mode`,
    );
  const workloadRole = env.HOOPDB_RUNTIME_WORKLOAD_ROLE || undefined;
  if (workloadRole !== undefined && !ident.test(workloadRole))
    throw profileError(
      "db_profile_invalid",
      "HOOPDB_RUNTIME_WORKLOAD_ROLE must be a role name",
    );
  // On RDS a workload edge could only be granted by the non-superuser master, which the
  // runtime-role allowlist refuses (its grantor must be a catalog-verified superuser).
  // Unsupported, so it is refused before any connection instead of at the gate.
  if (mode === "rds" && workloadRole !== undefined)
    throw profileError(
      "db_profile_invalid",
      "HOOPDB_RUNTIME_WORKLOAD_ROLE is not supported in rds mode; the runtime role must LOG IN itself",
    );
  if (env.HOOPDB_FUNCTION_BOUNDARY_APPROVED !== undefined)
    throw profileError(
      "db_profile_invalid",
      "HOOPDB_FUNCTION_BOUNDARY_APPROVED was renamed HOOPDB_FUNCTION_BOUNDARY_MODE (it selects a catalog-proven control, it is not an approval); remove it",
    );
  const fb = env.HOOPDB_FUNCTION_BOUNDARY_MODE || undefined;
  if (fb === "event-trigger" && mode !== "supabase")
    throw profileError(
      "function_boundary_mode_unsupported",
      "HOOPDB_FUNCTION_BOUNDARY_MODE=event-trigger is supported only with HOOPDB_DB_MODE=supabase (selfhosted, cloudsql and rds use global-default-revoke)",
    );
  if (
    fb !== undefined &&
    fb !== "global-default-revoke" &&
    fb !== "event-trigger"
  )
    throw profileError(
      "db_profile_invalid",
      "HOOPDB_FUNCTION_BOUNDARY_MODE must be global-default-revoke or (supabase only) event-trigger",
    );
  // Explicit opt-in only (strict true/false); unset or false keeps the refusal.
  const allowBlockingIndexBuild = strictFlag(env, "HOOPDB_ALLOW_BLOCKING_INDEX_BUILD");
  const runtime = {
    runtimeRole,
    ...(runtimeLogin === undefined ? {} : { runtimeLogin }),
    ...(workloadRole ? { workloadRole } : {}),
    ...(fb ? { functionBoundary: fb as FunctionBoundaryMode } : {}),
    ...(allowBlockingIndexBuild ? { allowBlockingIndexBuild: true } : {}),
  };
  if (mode === "supabase") {
    if (shim)
      throw profileError(
        "shim_forbidden",
        "the plain-Postgres role shim never runs in supabase mode",
      );
    if (bootstrap)
      throw profileError(
        "bootstrap_forbidden",
        "the privileged role bootstrap never runs from the migrator in supabase mode",
      );
    return { mode, shim: false, bootstrap: false, verify, ...runtime };
  }
  if (mode === "rds") {
    const layout = env.HOOPDB_RDS_LAYOUT || "master-owner";
    if (layout !== "master-owner" && layout !== "separate-database")
      throw profileError(
        "db_profile_invalid",
        `HOOPDB_RDS_LAYOUT must be master-owner or separate-database (got "${layout}")`,
      );
    return { mode, shim: false, bootstrap: false, verify, ...runtime, rdsLayout: layout };
  }
  if (shim === undefined)
    throw profileError(
      "shim_unset",
      `HOOPDB_SUPABASE_SHIM must be set explicitly in ${mode} mode`,
    );
  return { mode, shim, bootstrap: bootstrap ?? shim, verify, ...runtime };
}

async function schemaSteps(): Promise<Step[]> {
  const upstream = (await readdir(UPSTREAM_MIGRATIONS))
    .filter((f) => f.endsWith(".sql"))
    .sort();
  const ours = (await readdir(OURS)).filter((f) => f.endsWith(".sql")).sort();
  return [
    ...upstream.map((f) => ({
      name: `upstream:${f}`,
      path: join(UPSTREAM_MIGRATIONS, f),
    })),
    ...ours.map((f) => ({ name: `96bulls:${f}`, path: join(OURS, f) })),
  ];
}

export async function plan(profile: MigrationProfile): Promise<Step[]> {
  return [
    ...(profile.shim ? [{ name: "shim:supabase_roles", path: SHIM }] : []),
    // The bootstrap chain is single-sourced: session-bootstrap-chain.ts is
    // the one ordered list every applier (plan, proofs, fixtures, T0)
    // provisions before the migration chain.
    ...(profile.bootstrap
      ? [...SESSION_BOOTSTRAP_FILES].map((file) => ({
          name: `bootstrap:${file.split("/").pop()!.replace(/\.sql$/, "")}`,
          path: join(ROOT, file),
        }))
      : []),
    ...(await schemaSteps()),
    ...(profile.verify ? PHASE2_VERIFY.map((v) => ({ ...v })) : []),
  ];
}

