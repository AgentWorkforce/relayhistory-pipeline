import * as Effect from "effect/Effect";
import {
  assertBufferedGcRoleArn, bufferedGcBucketStatements, bufferedGcKeyStatements,
} from "../buffered-gc-policy.ts";
import {
  assertTranscriptStoreInputs, transcriptBucketPolicy, transcriptKeyPolicy, transcriptStoreStage,
  TRANSCRIPT_ACCOUNT_ID, TRANSCRIPT_REGION, TRANSCRIPT_STAGE,
} from "../transcript-store.ts";

const accountId = "111122223333", region = "us-east-1", bucketName = "synthetic-transcripts-111122223333";
const bucketArn = `arn:aws:s3:::${bucketName}`, roleArn = `arn:aws:iam::${accountId}:role/synthetic-buffered-gc`;
const eraserArn = `arn:aws:iam::${accountId}:user/synthetic-eraser`, keyArn = `arn:aws:kms:${region}:${accountId}:key/synthetic`;
const args = { accountId, region, bucketName, writerArn: "writer", srvWriterArn: "srv", readerArn: "reader" };
// Sanitized copy of the independently reviewed repair, rather than an expectation generated by production helpers.
const approved = JSON.parse(readFileSync(new URL("./fixtures/buffered-gc-resource-policies.json", import.meta.url), "utf8"));
const production = () => ({ accountId: TRANSCRIPT_ACCOUNT_ID, region: TRANSCRIPT_REGION, partition: "aws",
  transcriptStore: { bufferedGcRoleArn: `arn:aws:iam::${TRANSCRIPT_ACCOUNT_ID}:role/synthetic-buffered-gc` } });

type Statement = Record<string, any>;
const many = (value: any): any[] => Array.isArray(value) ? value : [value];
const glob = (pattern: string, value: string) => new RegExp("^" + pattern.replace(/[.+^${}()|[\]\\]/g, "\\$&").replaceAll("*", ".*").replaceAll("?", ".") + "$", "s").test(value);
function effects(statements: Statement[], action: string, resource: string, context: Record<string, string>) {
  return statements.filter(s => {
    if (s.Principal && s.Principal !== "*" && !many(s.Principal.AWS).includes(context["aws:PrincipalArn"])) return false;
    if (!many(s.Action).some(p => glob(p.toLowerCase(), action.toLowerCase()))) return false;
    if (s.Resource && !many(s.Resource).some(p => glob(p, resource))) return false;
    if (s.NotResource && many(s.NotResource).some(p => glob(p, resource))) return false;
    return Object.entries(s.Condition ?? {}).every(([operator, entries]) => Object.entries(entries as object).every(([key, value]) => {
      const expected = many(value), actual = context[key];
      if (operator === "StringLike") return actual !== undefined && expected.some(p => glob(p, actual));
      if (operator === "StringEquals" || operator === "ArnEquals") return expected.includes(actual);
      if (operator === "ArnNotEquals" || operator === "StringNotEquals") return !expected.includes(actual);
      if (operator === "Bool") return expected.includes(actual);
      if (operator === "Null") return String(actual === undefined) === value;
      if (operator === "StringNotEqualsIfExists") return actual === undefined || !expected.includes(actual);
      if (operator === "NumericLessThan") return actual !== undefined && Number(actual) < Number(value);
      throw new Error("unmodeled condition: " + operator);
    }));
  }).map(s => s.Effect);
}
const safe = { "aws:PrincipalArn": roleArn, "aws:SecureTransport": "true", "s3:TlsVersion": "1.3" };
const suffix = `m=srv_${"a".repeat(32)}/b=${"b".repeat(32)}-${"c".repeat(16)}-${"d".repeat(32)}.staged.ndjson.zst`;
const normal = `96bulls/o/buffered-batches/v1/ws=w/${suffix}`;

describe("buffered GC resource-policy continuity", () => {
  it("requires a same-account named role in production; missing or malformed input cannot revoke GC", () => {
    expect(() => assertTranscriptStoreInputs(TRANSCRIPT_STAGE, production())).not.toThrow();
    for (const bad of [undefined, null, false, "", "*", [roleArn], roleArn, `arn:aws:sts::${TRANSCRIPT_ACCOUNT_ID}:assumed-role/gc/session`, `arn:aws:iam::${TRANSCRIPT_ACCOUNT_ID}:user/gc`, `arn:aws:iam::${TRANSCRIPT_ACCOUNT_ID}:role/*`]) {
      const input = production();
      (input.transcriptStore as any).bufferedGcRoleArn = bad;
      expect(() => assertTranscriptStoreInputs(TRANSCRIPT_STAGE, input)).toThrow(/bufferedGcRoleArn/);
    }
    expect(() => assertBufferedGcRoleArn(`arn:aws:iam::${accountId}:role/service/gc`, accountId)).not.toThrow();
    expect(() => assertTranscriptStoreInputs("aws-proof", { accountId, region })).not.toThrow();
  });

  it("generates exactly the reviewed bounded GC key statements and all four bucket guards", () => {
    expect(bufferedGcKeyStatements({ accountId, region, bucketName, roleArn })).toEqual(approved.key);
    expect(bufferedGcBucketStatements({ accountId, bucketArn, roleArn })).toEqual(approved.bucket);
    const policy = transcriptBucketPolicy({ accountId, bucketArn, keyArn, eraserArn, bufferedGcRoleArn: roleArn });
    expect(policy.find(s => s.Sid === "OnlyTheEraserDeletes")).toEqual({ ...approved.deleteException, Action: approved.deleteException.Action, Resource: [approved.deleteException.Resource] });
  });

  it("preserves every existing reader, writer, eraser and pipeline statement; legacy pure helpers stay compatible", () => {
    const previousKey = transcriptKeyPolicy({ ...args, pipelineRoleArn: "pipeline" });
    const nextKey = transcriptKeyPolicy({ ...args, pipelineRoleArn: "pipeline", bufferedGcRoleArn: roleArn });
    expect(nextKey.Statement.slice(0, -2)).toEqual(previousKey.Statement);
    const cascade = transcriptKeyPolicy({ ...args, pipelineRoleArn: "(known after apply)", bufferedGcRoleArn: roleArn });
    expect(cascade.Statement.filter(s => s.Sid.startsWith("BufferedGc"))).toEqual(nextKey.Statement.filter(s => s.Sid.startsWith("BufferedGc")));
    const previousBucket = transcriptBucketPolicy({ bucketArn, keyArn, eraserArn });
    const nextBucket = transcriptBucketPolicy({ accountId, bucketArn, keyArn, eraserArn, bufferedGcRoleArn: roleArn });
    expect(nextBucket.slice(0, -4).map(s => s.Sid === "OnlyTheEraserDeletes" ? { ...s, Condition: { ArnNotEquals: { "aws:PrincipalArn": eraserArn } } } : s)).toEqual(previousBucket);
    expect(() => transcriptKeyPolicy({ ...args, bufferedGcRoleArn: "" })).toThrow();
    expect(() => transcriptBucketPolicy({ bucketArn, keyArn, eraserArn, bufferedGcRoleArn: roleArn })).toThrow();
  });

  it("denies plain deletes, outside deletes and every nested canonical family despite slash-matching globs", () => {
    const bucket = transcriptBucketPolicy({ accountId, bucketArn, keyArn, eraserArn, bufferedGcRoleArn: roleArn }) as Statement[];
    const key = bufferedGcKeyStatements({ accountId, region, bucketName, roleArn });
    expect(effects(bucket, "s3:DeleteObjectVersion", `${bucketArn}/${normal}`, safe)).not.toContain("Deny");
    expect(effects(bucket, "s3:DeleteObject", `${bucketArn}/${normal}`, safe)).toContain("Deny");
    expect(effects(bucket, "s3:DeleteObjectVersion", `${bucketArn}/outside`, safe)).toContain("Deny");
    for (const org of ["o", "o/nested", "buffered-batches"]) for (const generation of ["g", "g/nested", "buffered-batches"]) {
      const object = `96bulls/${org}/upload-generations/${generation}/buffered-batches/v1/ws=w/${suffix}`;
      for (const action of ["s3:GetObject", "s3:PutObject", "s3:DeleteObject", "s3:DeleteObjectVersion"])
        expect(effects(bucket, action, `${bucketArn}/${object}`, safe)).toContain("Deny");
      expect(effects(bucket, "s3:ListBucketVersions", bucketArn, { ...safe, "s3:prefix": object })).toContain("Deny");
      for (const action of ["kms:Decrypt", "kms:GenerateDataKey"]) expect(effects(key, action, keyArn, {
        ...safe, "kms:CallerAccount": accountId, "kms:ViaService": `s3.${region}.amazonaws.com`, "kms:EncryptionContext:aws:s3:arn": `${bucketArn}/${object}`,
      })).toContain("Deny");
    }
    for (const principal of [eraserArn, "another-reader", "pipeline"]) {
      const previous = transcriptBucketPolicy({ bucketArn, keyArn, eraserArn }) as Statement[];
      for (const action of ["s3:GetObject", "s3:PutObject", "s3:DeleteObject", "s3:DeleteObjectVersion"])
        expect(effects(bucket, action, `${bucketArn}/${normal}`, { ...safe, "aws:PrincipalArn": principal })).toEqual(effects(previous, action, `${bucketArn}/${normal}`, { ...safe, "aws:PrincipalArn": principal }));
    }
  });

  it("allows only object-context KMS use via the configured S3 region and account", () => {
    const key = bufferedGcKeyStatements({ accountId, region, bucketName, roleArn });
    const good = { ...safe, "kms:CallerAccount": accountId, "kms:ViaService": `s3.${region}.amazonaws.com`, "kms:EncryptionContext:aws:s3:arn": `${bucketArn}/${normal}` };
    for (const action of ["kms:Decrypt", "kms:GenerateDataKey"]) {
      expect(effects(key, action, keyArn, good)).toContain("Allow");
      for (const bad of [{ "kms:CallerAccount": "000000000000" }, { "kms:ViaService": "" }, { "kms:ViaService": "s3.other.amazonaws.com" }, { "kms:EncryptionContext:aws:s3:arn": bucketArn }])
        expect(effects(key, action, keyArn, { ...good, ...bad })).not.toContain("Allow");
    }
  });

  it("direct stage calls refuse a missing binding before requesting any provider", async () => {
    await expect(Effect.runPromise(transcriptStoreStage({ stage: TRANSCRIPT_STAGE, accountId, region, budgetUsd: 1, budgetEmail: "test@example.invalid", transcriptStore: {}, tags: () => ({}) }))).rejects.toThrow(/bufferedGcRoleArn/);
  });

  it("actual stage declaration wires the configured role into BOTH full policy documents without creating a GC runtime", () => {
    const modulePath = fileURLToPath(new URL("../transcript-store.ts", import.meta.url));
    const script = `import { mock } from 'bun:test'; import * as E from 'effect/Effect';
      const seen=[]; const factory=(type)=>(name,props)=>{seen.push({type,name,props});return E.succeed({userName:props.userName,userArn:'arn:aws:iam::${accountId}:user/'+props.userName,keyArn:'${keyArn}',keyId:'synthetic',bucketName:props.bucketName,trailName:props.trailName})};
      mock.module('@alchemy.run/aws',()=>({IAM:{User:factory('user')},KMS:{Key:factory('key'),Alias:factory('alias')},S3:{Bucket:factory('bucket')},CloudTrail:{Trail:factory('trail')},Budgets:{Budget:factory('budget')}}));
      const {transcriptStoreStage}=await import(${JSON.stringify(modulePath)});
      const config={stage:'synthetic',accountId:'${accountId}',region:'${region}',budgetUsd:1,budgetEmail:'test@example.invalid',transcriptStore:{bufferedGcRoleArn:'${roleArn}'},tags:()=>({})};
      await E.runPromise(transcriptStoreStage(config));const enabled=structuredClone(seen);seen.length=0;
      await E.runPromise(transcriptStoreStage({...config,transcriptStore:{}}));console.log(JSON.stringify({enabled,legacy:seen}));`;
    const result = spawnSync(process.execPath, ["--eval", script], { encoding: "utf8", env: { PATH: process.env.PATH }, timeout: 30_000 });
    expect(result.status).toBe(0);
    const { enabled: seen, legacy } = JSON.parse(result.stdout) as { enabled: { name: string; props: any; type: string }[]; legacy: { name: string; props: any }[] };
    expect(seen.find(r => r.name === "transcripts-key")!.props.policy.Statement.filter((s: any) => s.Sid.startsWith("BufferedGc"))).toEqual(bufferedGcKeyStatements({ accountId, region, bucketName: `96bulls-synthetic-transcripts-${accountId}`, roleArn }));
    const bucket = seen.find(r => r.name === "transcripts")!.props.policy;
    expect(bucket.filter((s: any) => s.Sid.startsWith("BufferedGc"))).toEqual(bufferedGcBucketStatements({ accountId, bucketArn: `arn:aws:s3:::96bulls-synthetic-transcripts-${accountId}`, roleArn }));
    expect(bucket.find((s: any) => s.Sid === "OnlyTheEraserDeletes").Condition.ArnNotEquals["aws:PrincipalArn"]).toContain(roleArn);
    expect(seen.some(r => r.type === "role" || r.type === "lambda")).toBe(false);
    expect(legacy.find(r => r.name === "transcripts-key")!.props.policy.Statement.some((s: any) => s.Sid.startsWith("BufferedGc"))).toBe(false);
    expect(legacy.find(r => r.name === "transcripts")!.props.policy.some((s: any) => s.Sid.startsWith("BufferedGc"))).toBe(false);
  });
});
