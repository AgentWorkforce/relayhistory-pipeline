async function rollback(ctx: LaneContext): Promise<Record<string, string>> {
  const previous = await ctx.read(PREVIOUS);
  const erase = provenanceEraseBody(previous);
  const fence = provenanceRetireFenceBody(previous);
  const checksum = createHash("sha256").update(ctx.sql).digest("hex");
  return { [ROLLBACK]: [
    "-- Generated by the selfhost-erase-search-text-rebuild lane. Reverse of 20261105044070: restores 20261105044050's",
    "-- exact sessions.ingest_selfhost_set_session_uploads and sessions.ingest_publication_retire_fence",
    "-- (owners, SECURITY DEFINER, ACLs and triggers unchanged).",
    "-- Refused (55000) unless 044070 is applied with this exact checksum (a repeat cannot recreate a removed function),",
    "-- and while a later migration is applied. Run as one transaction (psql -1 -v ON_ERROR_STOP=1).",
    "DO $rollback_guard$ DECLARE v_later boolean;v_sha text; BEGIN",
    " IF to_regclass('sessions.__96bulls_migrations')IS NULL",
    " THEN RAISE EXCEPTION USING ERRCODE='55000',MESSAGE='selfhost erase search_text rebuild: migration ledger required';END IF;",
    " EXECUTE 'SELECT EXISTS(SELECT 1 FROM sessions.__96bulls_migrations WHERE name LIKE \'\'upstream:%\'\' AND name COLLATE \"C\">\'\'" + NAME + "\'\')' INTO v_later;",
    " IF v_later THEN RAISE EXCEPTION USING ERRCODE='55000',MESSAGE='selfhost erase search_text rebuild: a later migration is applied; roll it back first';END IF;",
    " EXECUTE 'SELECT sha256 FROM sessions.__96bulls_migrations WHERE name=\'\'" + NAME + "\'\'' INTO v_sha;",
    " IF v_sha IS DISTINCT FROM '" + checksum + "'",
    " THEN RAISE EXCEPTION USING ERRCODE='55000',MESSAGE='selfhost erase search_text rebuild: own applied checksum required';END IF;",
    "END $rollback_guard$;",
    "-- 044050's erase function exactly as it replaced it.",
    erase,
    "-- 044050's retire trigger function exactly as it replaced it.",
    fence,
    "DELETE FROM sessions.__96bulls_migrations WHERE name='" + NAME + "';",
  ].join("\n") + "\n" };
}

