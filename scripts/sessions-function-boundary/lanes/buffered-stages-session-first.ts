import { createHash } from "node:crypto";
import type { LaneContext, LaneManifest } from "../types.ts";

const MIGRATION = "supabase/migrations/20261105044040_buffered_stages_session_first.sql";
const ORIGINAL = "supabase/migrations/20261105043700_owner_buffered_read.sql";
const ROLLBACK = "supabase/rollbacks/20261105044040_buffered_stages_session_first.down.sql";
const NAME = "upstream:20261105044040_buffered_stages_session_first.sql";
const LIST = "sessions.buffered_sessions_for(text,timestamp with time zone,text,text,integer,text,text,text,text,text,boolean,text)";
const STAGES = "sessions.buffered_session_stages_for(text,text,text,text,text,text,text,text,boolean,text)";

/** 043700's two exact reader functions, as CREATE OR REPLACE. */
export function originalReaderBodies(source: string): string[] {
  const pick = (re: RegExp) => {
    const m = source.match(re);
    if (!m) throw Error("buffered stages session-first rollback: exact 043700 body missing");
    return m[0].replace("CREATE FUNCTION", "CREATE OR REPLACE FUNCTION");
  };
  return [
    pick(/CREATE FUNCTION sessions\.buffered_sessions_for\([\s\S]*?END\n\$buffered_sessions\$;/),
    pick(/CREATE FUNCTION sessions\.buffered_session_stages_for\([\s\S]*?END\n\$buffered_stages\$;/),
  ];
}

async function rollback(ctx: LaneContext): Promise<Record<string, string>> {
  const bodies = originalReaderBodies(await ctx.read(ORIGINAL));
  const checksum = createHash("sha256").update(ctx.sql).digest("hex");
  return { [ROLLBACK]: [
    "-- Generated by the buffered-stages-session-first lane. Reverse of 20261105044040: restores 20261105043700's exact",
    "-- sessions.buffered_sessions_for and sessions.buffered_session_stages_for (owner, SECURITY DEFINER and ACL unchanged).",
    "-- ingest_claim_attempts_records_gin_idx is deliberately kept (harmless to 043700; a re-apply adopts it; drop it",
    "-- out of band with DROP INDEX CONCURRENTLY only if wanted). Refused (55000) unless 044040 is applied with this",
    "-- exact checksum, and while a later migration is applied. Run as one transaction (psql -1 -v ON_ERROR_STOP=1).",
    "DO $rollback_guard$ DECLARE v_later boolean;v_sha text; BEGIN",
    " IF to_regclass('sessions.__96bulls_migrations')IS NULL",
    " THEN RAISE EXCEPTION USING ERRCODE='55000',MESSAGE='buffered stages session-first: migration ledger required';END IF;",
    " EXECUTE 'SELECT EXISTS(SELECT 1 FROM sessions.__96bulls_migrations WHERE name LIKE \'\'upstream:%\'\' AND name COLLATE \"C\">\'\'" + NAME + "\'\')' INTO v_later;",
    " IF v_later THEN RAISE EXCEPTION USING ERRCODE='55000',MESSAGE='buffered stages session-first: a later migration is applied; roll it back first';END IF;",
    " EXECUTE 'SELECT sha256 FROM sessions.__96bulls_migrations WHERE name=\'\'" + NAME + "\'\'' INTO v_sha;",
    " IF v_sha IS DISTINCT FROM '" + checksum + "'",
    " THEN RAISE EXCEPTION USING ERRCODE='55000',MESSAGE='buffered stages session-first: own applied checksum required';END IF;",
    "END $rollback_guard$;",
    "-- 043700's functions exactly as it created them.",
    ...bodies,
    "DELETE FROM sessions.__96bulls_migrations WHERE name='" + NAME + "';",
  ].join("\n") + "\n" };
}

