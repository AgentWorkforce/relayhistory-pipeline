/** The pinned retained shape, read from the migration between its markers (one copy, shared with the down). */
export function replayManifestShape(sql: string): string {
  const a = sql.indexOf("-- replay manifest shape begin\n");
  const b = sql.indexOf("\n-- replay manifest shape end");
  if (a < 0 || b < a) throw Error("session erasure replay manifest: shape markers missing");
  return sql.slice(a + "-- replay manifest shape begin\n".length, b);
}

async function rollback(ctx: LaneContext): Promise<Record<string, string>> {
  const checksum = createHash("sha256").update(ctx.sql).digest("hex");
  const erase = await ctx.read(ERASE);
  const restored = Object.keys(REPLACES).flatMap((fn) => [`-- ${fn}: restored from ${ERASE}.`, lastBody(erase, fn)]);
  return { [ROLLBACK]: [
    "-- Generated by the session-erasure-replay-manifest lane. Reverse of 20261105062360: restores 050000's",
    "-- ingest_operator_erase_session and ingest_operator_erase_fence exactly and drops the captured fence body. An EMPTY",
    "-- manifest (no row in any of its four tables) is dropped entirely with its functions and the receipts binding",
    "-- constraint; a POPULATED one is KEPT as the immutable replay witness with its guards, digest and reader, and",
    "-- verified against the reviewed shape. Refused (55000) unless 062360 is applied with this exact checksum, and while a",
    "-- later upstream migration is applied. Code only: running it against any real database needs Khaliq's explicit OK.",
    "BEGIN;",
    "SET LOCAL lock_timeout='5s';",
    "SELECT pg_advisory_xact_lock(961996,1); -- same namespace as the real migrator; lifecycle functions take it SHARED",
    "-- The erase gate: no erase is mid-capture while the bodies change.",
    "SELECT pg_advisory_xact_lock(961996,50000);",
    "DO $rollback_guard$ DECLARE v_sha text; BEGIN",
    " IF to_regclass('sessions.__96bulls_migrations')IS NULL",
    " THEN RAISE EXCEPTION USING ERRCODE='55000',MESSAGE='session erasure replay manifest: migration ledger required';END IF;",
    " LOCK TABLE sessions.__96bulls_migrations IN SHARE ROW EXCLUSIVE MODE;",
    " IF EXISTS(SELECT 1 FROM sessions.__96bulls_migrations WHERE name LIKE 'upstream:%' AND name COLLATE \"C\">'" + NAME + "')",
    " THEN RAISE EXCEPTION USING ERRCODE='55000',MESSAGE='session erasure replay manifest: a later migration is applied; roll it back first';END IF;",
    " SELECT sha256 INTO v_sha FROM sessions.__96bulls_migrations WHERE name='" + NAME + "' FOR UPDATE;",
    " IF NOT FOUND OR v_sha IS DISTINCT FROM '" + checksum + "'",
    " THEN RAISE EXCEPTION USING ERRCODE='55000',MESSAGE='session erasure replay manifest: own applied checksum required';END IF;",
    "END $rollback_guard$;",
    ...restored,
    "DROP FUNCTION sessions.session_erasure_replay_fence(text,text,text,text,text[],uuid);",
    "DO $rollback_witness$ BEGIN",
    ` LOCK TABLE ${TABLES.map((t) => `sessions.${t}`).join(",")} IN SHARE MODE;`,
    ` IF ${TABLES.map((t) => `NOT EXISTS(SELECT 1 FROM sessions.${t})`).join(" AND ")} THEN`,
    // Through EXECUTE: a dropped table must not be named by a cached plan of this block.
    `  EXECUTE 'DROP TABLE ${TABLES.map((t) => `sessions.${t}`).join(",")}';`,
    ...WITNESS_FUNCTIONS.map((f) => `  EXECUTE 'DROP FUNCTION ${f}';`),
    "  ALTER TABLE sessions.session_erasure_receipts DROP CONSTRAINT session_erasure_receipts_request_binding;",
    " ELSIF sessions.session_erasure_replay_shape() IS DISTINCT FROM",
    replayManifestShape(ctx.sql),
    " THEN RAISE EXCEPTION USING ERRCODE='55000',MESSAGE='session erasure replay manifest: retained witness drifted; rolled back';",
    " END IF;",
    "END $rollback_witness$;",
    "-- Final assertion before the ledger row goes: no body carries a 062360 mark and the captured fence is gone.",
    "DO $rollback_verify$ BEGIN",
    " IF to_regprocedure('sessions.session_erasure_replay_fence(text,text,text,text,text[],uuid)') IS NOT NULL",
    "  OR EXISTS(SELECT 1 FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace WHERE n.nspname='sessions'",
    "   AND p.prosrc LIKE '%-- 062360 session erasure replay manifest%')",
    " THEN RAISE EXCEPTION USING ERRCODE='55000',MESSAGE='session erasure replay manifest: capture survived the down; rolled back';END IF;",
    "END $rollback_verify$;",
    "DELETE FROM sessions.__96bulls_migrations WHERE name='" + NAME + "' AND sha256='" + checksum + "';",
    "COMMIT;",
  ].join("\n") + "\n" };
}

