import { createHash } from "node:crypto";
import type { LaneContext, LaneManifest } from "../types.ts";

const MIGRATION = "supabase/migrations/20261105044050_selfhost_erase_short_summary_provenance.sql";
const PREVIOUS = "supabase/migrations/20261105044010_selfhost_erase_lock_fences.sql";
const ORIGINAL = "supabase/migrations/20261105043910_selfhost_session_selection_erase.sql";
const FENCE_ORIGINAL = "supabase/migrations/20261104060000_ingest_canonical_publication.sql";
const ROLLBACK = "supabase/rollbacks/20261105044050_selfhost_erase_short_summary_provenance.down.sql";
const NAME = "upstream:20261105044050_selfhost_erase_short_summary_provenance.sql";
