const FENCE = "sessions.ingest_publication_retire_fence()";

/** 044010's exact function (already CREATE OR REPLACE). */
export function lockFencesEraseBody(source: string): string {
  const m = source.match(/CREATE OR REPLACE FUNCTION sessions\.ingest_selfhost_set_session_uploads\(p jsonb\)[\s\S]*?END \$selfhost_selection\$;/);
  if (!m) throw Error("selfhost erase short-summary provenance rollback: exact 044010 body missing");
  return m[0];
}

/** 060000's exact retire trigger function, made CREATE OR REPLACE (its triggers, owner and ACL are kept). */
export function canonicalRetireFenceBody(source: string): string {
  const m = source.match(/CREATE FUNCTION sessions\.ingest_publication_retire_fence\(\) RETURNS trigger[\s\S]*?END \$retire\$;/);
  if (!m) throw Error("selfhost erase short-summary provenance rollback: exact 060000 retire fence body missing");
  return m[0].replace(/^CREATE FUNCTION/, "CREATE OR REPLACE FUNCTION");
}

async function rollback(ctx: LaneContext): Promise<Record<string, string>> {
  const erase = lockFencesEraseBody(await ctx.read(PREVIOUS));
  const fence = canonicalRetireFenceBody(await ctx.read(FENCE_ORIGINAL));
  const checksum = createHash("sha256").update(ctx.sql).digest("hex");
  return { [ROLLBACK]: [
    "-- Generated by the selfhost-erase-short-summary-provenance lane. Reverse of 20261105044050: restores 20261105044010's",
    "-- exact sessions.ingest_selfhost_set_session_uploads and 20261104060000's exact sessions.ingest_publication_retire_fence",
    "-- (owners, SECURITY DEFINER, ACLs and triggers unchanged).",
    "-- Refused (55000) unless 044050 is applied with this exact checksum (a repeat cannot recreate a removed function),",
    "-- and while a later migration is applied. Run as one transaction (psql -1 -v ON_ERROR_STOP=1).",
    "DO $rollback_guard$ DECLARE v_later boolean;v_sha text; BEGIN",
    " IF to_regclass('sessions.__96bulls_migrations')IS NULL",
    " THEN RAISE EXCEPTION USING ERRCODE='55000',MESSAGE='selfhost erase short-summary provenance: migration ledger required';END IF;",
    " EXECUTE 'SELECT EXISTS(SELECT 1 FROM sessions.__96bulls_migrations WHERE name LIKE \'\'upstream:%\'\' AND name COLLATE \"C\">\'\'" + NAME + "\'\')' INTO v_later;",
    " IF v_later THEN RAISE EXCEPTION USING ERRCODE='55000',MESSAGE='selfhost erase short-summary provenance: a later migration is applied; roll it back first';END IF;",
    " EXECUTE 'SELECT sha256 FROM sessions.__96bulls_migrations WHERE name=\'\'" + NAME + "\'\'' INTO v_sha;",
    " IF v_sha IS DISTINCT FROM '" + checksum + "'",
    " THEN RAISE EXCEPTION USING ERRCODE='55000',MESSAGE='selfhost erase short-summary provenance: own applied checksum required';END IF;",
    "END $rollback_guard$;",
    "-- 044010's function exactly as it replaced it.",
    erase,
    "-- 060000's retire trigger function exactly as it defined it.",
    fence,
    "DELETE FROM sessions.__96bulls_migrations WHERE name='" + NAME + "';",
  ].join("\n") + "\n" };
}

