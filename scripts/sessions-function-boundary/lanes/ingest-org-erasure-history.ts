/**
 * Lane: ingest-org-erasure-history (slot 062340, confirmed by layered-sessions-pipeline). The migration
 * supabase/migrations/20261105062340_ingest_org_erasure_history.sql owns the owner-only erasure-history functions
 * (guard, applied, coverage start, covers, recorder, truncate refusal, recording, bind) and replaces 062320's release
 * and status. ACLs unchanged (owner-only).
 *
 * The generated rollback restores 062320's release and status exactly, drops the 30 source triggers and the slot's
 * functions, records the end of coverage, keeps the three history tables with their guard as inert history (as 062320
 * keeps its own), resets readiness to pending, and removes its ledger row. It refuses while any hold is not released,
 * while a later slot is applied, and unless this exact checksum is applied.
 */
