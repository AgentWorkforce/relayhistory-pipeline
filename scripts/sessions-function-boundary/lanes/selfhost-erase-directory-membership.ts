/** 044070's exact erase function (already CREATE OR REPLACE). */
export function searchTextRebuildEraseBody(source: string): string {
  const m = source.match(/CREATE OR REPLACE FUNCTION sessions\.ingest_selfhost_set_session_uploads\(p jsonb\)[\s\S]*?END \$selfhost_selection\$;/);
  if (!m) throw Error("selfhost erase directory membership rollback: exact 044070 erase body missing");
  return m[0];
}

async function rollback(ctx: LaneContext): Promise<Record<string, string>> {
  const erase = searchTextRebuildEraseBody(await ctx.read(PREVIOUS));
  const checksum = createHash("sha256").update(ctx.sql).digest("hex");
  return { [ROLLBACK]: [
    "-- Generated by the selfhost-erase-directory-membership lane (#566). Reverse of 20261105057030: restores 20261105044070's",
    "-- exact sessions.ingest_selfhost_set_session_uploads (owner, SECURITY DEFINER, search_path and ACL unchanged).",
    "-- Membership rows the 057030 erase already deleted are not recreated; the projector rebuilds membership from live pointers.",
    "-- Refused (55000) unless 057030 is applied with this exact checksum (a repeat cannot restore an already restored body),",
    "-- and while a later migration is applied. Run as one transaction (psql -1 -v ON_ERROR_STOP=1). Never applied by this",
    "-- lane: applying it to any real database needs Khaliq's separate, explicit OK.",
    "DO $rollback_guard$ DECLARE v_later boolean;v_sha text; BEGIN",
    " IF to_regclass('sessions.__96bulls_migrations')IS NULL",
    " THEN RAISE EXCEPTION USING ERRCODE='55000',MESSAGE='selfhost erase directory membership: migration ledger required';END IF;",
    " EXECUTE 'SELECT EXISTS(SELECT 1 FROM sessions.__96bulls_migrations WHERE name LIKE \'\'upstream:%\'\' AND name COLLATE \"C\">\'\'" + NAME + "\'\')' INTO v_later;",
    " IF v_later THEN RAISE EXCEPTION USING ERRCODE='55000',MESSAGE='selfhost erase directory membership: a later migration is applied; roll it back first';END IF;",
    " EXECUTE 'SELECT sha256 FROM sessions.__96bulls_migrations WHERE name=\'\'" + NAME + "\'\'' INTO v_sha;",
    " IF v_sha IS DISTINCT FROM '" + checksum + "'",
    " THEN RAISE EXCEPTION USING ERRCODE='55000',MESSAGE='selfhost erase directory membership: own applied checksum required';END IF;",
    "END $rollback_guard$;",
    "-- 20261105044070's function exactly.",
    erase,
    "DELETE FROM sessions.__96bulls_migrations WHERE name='" + NAME + "';",
  ].join("\n") + "\n" };
}

