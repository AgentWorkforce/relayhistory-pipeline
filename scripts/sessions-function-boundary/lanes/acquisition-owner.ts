/** The exact prior definition, as CREATE OR REPLACE (060000 created its bodies with plain CREATE FUNCTION). */
function priorBody(source: string, name: string, tag: string): string {
  const re = new RegExp(`^CREATE (?:OR REPLACE )?FUNCTION sessions\\.${name}\\(`, "gm");
  const starts = [...source.matchAll(re)].map((m) => m.index!);
  if (starts.length !== 1) throw Error(`acquisition rollback: expected one prior ${name} body, found ${starts.length}`);
  const start = starts[0]!;
  const open = source.indexOf(tag, start);
  const close = source.indexOf(tag, open + tag.length);
  const end = source.indexOf(";", close);
  if (open < 0 || close < 0 || end !== close + tag.length) throw Error(`acquisition rollback: ${name} body is not delimited by ${tag}`);
  return source.slice(start, end + 1).replace(/^CREATE FUNCTION /, "CREATE OR REPLACE FUNCTION ");
}

async function rollback(ctx: LaneContext): Promise<Record<string, string>> {
  const checksum = createHash("sha256").update(ctx.sql).digest("hex");
  const bodies: string[] = [];
  for (const [sig, path, name, tag] of HOOKS) {
    bodies.push(`-- ${sig}: restored from ${path}.`, priorBody(await ctx.read(path), name, tag));
  }
  const sql = [
    "-- Generated by the acquisition-owner lane. Only a DORMANT installation may be removed: the hooks flag",
    "-- (sessions.ingest_acquisition_hooks_switch.enabled) and the install switch are off and",
    "-- no enrollment, owner, grant, revoke or operation was ever recorded, and no head or attempt carries an",
    "-- acquisition value. Once anything was enrolled or installed, the owner rows are the fence (design §4.6) and",
    "-- the operational rollback is the switch off plus no new enrollment; this file then refuses (55000).",
    "-- Explicit transaction: guard, marker fence, restores, drops and ledger removal are atomic.",
    "-- On an error the caller must ROLLBACK (or disconnect); nothing is committed.",
    "BEGIN;",
    "SELECT pg_advisory_xact_lock(961996,1); -- same namespace as the real migrator",
    "DO $rollback_guard$ DECLARE v_sha text; BEGIN",
    " IF to_regclass('sessions.__96bulls_migrations')IS NULL OR to_regclass('sessions.__96bulls_role_validation')IS NULL",
    " THEN RAISE EXCEPTION USING ERRCODE='55000',MESSAGE='acquisition: migration ledger/marker required';END IF;",
    " LOCK TABLE sessions.__96bulls_migrations IN SHARE ROW EXCLUSIVE MODE;",
    " IF EXISTS(SELECT 1 FROM sessions.__96bulls_migrations WHERE name LIKE 'upstream:%' AND name COLLATE \"C\">'" + NAME + "')",
    " THEN RAISE EXCEPTION USING ERRCODE='55000',MESSAGE='acquisition: a later migration is applied; roll it back first';END IF;",
    " SELECT sha256 INTO v_sha FROM sessions.__96bulls_migrations WHERE name='" + NAME + "' FOR UPDATE;",
    " IF NOT FOUND OR v_sha<>'" + checksum + "'",
    " THEN RAISE EXCEPTION USING ERRCODE='55000',MESSAGE='acquisition: own applied checksum required';END IF;",
    " LOCK TABLE sessions.ingest_acquisition_switch,sessions.ingest_acquisition_hooks_switch,",
    "  sessions.ingest_acquisition_enrollment_gate,sessions.ingest_acquisition_enrollment,",
    "  sessions.ingest_acquisition_owners,sessions.ingest_acquisition_grants,sessions.ingest_acquisition_grant_origins,",
    "  sessions.ingest_acquisition_revoked_grants,sessions.ingest_acquisition_revoked_lineages,sessions.ingest_acquisition_operations",
    "  IN ACCESS EXCLUSIVE MODE;",
    " IF EXISTS(SELECT 1 FROM sessions.ingest_acquisition_switch WHERE install_enabled)",
    "  OR EXISTS(SELECT 1 FROM sessions.ingest_acquisition_hooks_switch WHERE enabled)",
    "  OR EXISTS(SELECT 1 FROM sessions.ingest_acquisition_enrollment) OR EXISTS(SELECT 1 FROM sessions.ingest_acquisition_owners)",
    "  OR EXISTS(SELECT 1 FROM sessions.ingest_acquisition_grants) OR EXISTS(SELECT 1 FROM sessions.ingest_acquisition_grant_origins)",
    "  OR EXISTS(SELECT 1 FROM sessions.ingest_acquisition_revoked_grants) OR EXISTS(SELECT 1 FROM sessions.ingest_acquisition_revoked_lineages)",
    "  OR EXISTS(SELECT 1 FROM sessions.ingest_acquisition_operations)",
    "  OR EXISTS(SELECT 1 FROM sessions.ingest_publication_heads WHERE acquisition_epoch<>0)",
    "  OR EXISTS(SELECT 1 FROM sessions.ingest_claim_attempts WHERE acquisition<>'[]'::jsonb)",
    " THEN RAISE EXCEPTION USING ERRCODE='55000',MESSAGE='acquisition: enabled, enrolled or installed state exists; disable instead of rolling back';END IF;",
    " UPDATE sessions.__96bulls_role_validation SET status='pending',updated_at=clock_timestamp() WHERE name='session_directory_search_worker';",
    " IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE='55000',MESSAGE='acquisition: validation marker required';END IF;",
    "END $rollback_guard$;",
    ...bodies,
    "DROP FUNCTION " + [...ctx.defined].filter((s) => !HOOKS.some(([h]) => h === s)).reverse().join(",\n ") + ";",
    "DROP TABLE sessions.ingest_acquisition_operations,sessions.ingest_acquisition_revoked_lineages,sessions.ingest_acquisition_revoked_grants,",
    " sessions.ingest_acquisition_grant_origins,sessions.ingest_acquisition_grants,sessions.ingest_acquisition_owners,",
    " sessions.ingest_acquisition_enrollment,sessions.ingest_acquisition_enrollment_gate,sessions.ingest_acquisition_hooks_switch,",
    " sessions.ingest_acquisition_switch;",
    "ALTER TABLE sessions.ingest_publication_heads DROP COLUMN acquisition_epoch;",
    "ALTER TABLE sessions.ingest_claim_attempts DROP COLUMN acquisition;",
    "-- The schema USAGE this migration granted the control role goes with it (the role itself is kept).",
    "REVOKE USAGE ON SCHEMA sessions FROM bulls96_acquisition_installer;",
    "DELETE FROM sessions.__96bulls_migrations WHERE name='" + NAME + "' AND sha256='" + checksum + "';",
    "-- The NOLOGIN role bulls96_acquisition_installer is KEPT, as every lane keeps its cluster roles (033000).",
    "COMMIT;",
  ].join("\n") + "\n";
  return { [ROLLBACK]: sql };
}

