/** The exact 058010 ingest_lock_fences body (CREATE OR REPLACE there; owner/ACL stay unchanged). */
export function originalBodies(source: string): string[] {
  const m = source.match(/CREATE OR REPLACE FUNCTION sessions\.ingest_lock_fences\(p_org text,p_ws text,p_user text\)[\s\S]*?\n\$lock\$;/);
  if (!m) throw Error("origin claim fence rollback: exact prior ingest_lock_fences body missing");
  return [m[0]];
}

