/**
 * Lane: operator per-session erase, upload-path fence check (slot 050010). Two owner-only functions: the fence
 * extension the three replaced ingest functions call, and the SECURITY DEFINER session_index trigger function
 * (granted to no role). ingest_claim_batch_mode, ingest_commit_buffered_batch and ingest_commit_batch are
 * replaced with 043850's bodies plus one call each; their owners and ACLs are kept. Also generates the
 * rollback, which restores each replaced body byte-for-byte from 043850.
 */
import { createHash } from "node:crypto";
import type { LaneContext, LaneManifest } from "../types.ts";

const MIGRATION = "supabase/migrations/20261105050010_operator_session_erase_fence_check.sql";
const ORIGINAL = "supabase/migrations/20261105043850_ingest_acquisition_owner.sql";
const ROLLBACK = "supabase/rollbacks/20261105050010_operator_session_erase_fence_check.down.sql";
const NAME = "upstream:20261105050010_operator_session_erase_fence_check.sql";

/** [signature, function name, dollar tag, SECURITY DEFINER] of every replaced function, in restore order. */
const HOOKS: readonly (readonly [string, string, string, boolean])[] = [
  ["sessions.ingest_claim_batch_mode(jsonb,text)", "ingest_claim_batch_mode", "$claim$", false],
  ["sessions.ingest_commit_buffered_batch(jsonb)", "ingest_commit_buffered_batch", "$bcommit$", true],
  ["sessions.ingest_commit_batch(jsonb)", "ingest_commit_batch", "$commit$", true],
];

/** 043850's exact definition of one function (already CREATE OR REPLACE there). */
export function originalBody(source: string, name: string, tag: string): string {
  const re = new RegExp(`^CREATE OR REPLACE FUNCTION sessions\\.${name}\\(`, "gm");
  const starts = [...source.matchAll(re)].map((m) => m.index!);
  if (starts.length !== 1) throw Error(`erase fence check rollback: expected one 043850 ${name} body, found ${starts.length}`);
  const open = source.indexOf(tag, starts[0]!);
  const close = source.indexOf(tag, open + tag.length);
  const end = source.indexOf(";", close);
  if (open < 0 || close < 0 || end !== close + tag.length) throw Error(`erase fence check rollback: ${name} body is not delimited by ${tag}`);
  return source.slice(starts[0]!, end + 1);
}

async function rollback(ctx: LaneContext): Promise<Record<string, string>> {
  const source = await ctx.read(ORIGINAL);
  const checksum = createHash("sha256").update(ctx.sql).digest("hex");
  const bodies: string[] = [];
  for (const [sig, name, tag] of HOOKS) bodies.push(`-- ${sig}: restored from ${ORIGINAL}.`, originalBody(source, name, tag));
  return { [ROLLBACK]: [
    "-- Generated by the operator-session-erase-fence-check lane. Reverse of 20261105050010: restores 20261105043850's",
    "-- exact ingest_claim_batch_mode, ingest_commit_buffered_batch and ingest_commit_batch (owners, SECURITY DEFINER",
    "-- and ACLs unchanged), drops the session_index trigger and the two fence-check functions. The fences themselves",
    "-- are 050000's and stay. Refused (55000) unless 050010 is applied with this exact checksum, and while a later",
    "-- migration is applied. Run as one transaction (psql -1 -v ON_ERROR_STOP=1).",
    "DO $rollback_guard$ DECLARE v_later boolean;v_sha text; BEGIN",
    " IF to_regclass('sessions.__96bulls_migrations')IS NULL",
    " THEN RAISE EXCEPTION USING ERRCODE='55000',MESSAGE='operator erase fence check: migration ledger required';END IF;",
    " EXECUTE 'SELECT EXISTS(SELECT 1 FROM sessions.__96bulls_migrations WHERE name LIKE \'\'upstream:%\'\' AND name COLLATE \"C\">\'\'" + NAME + "\'\')' INTO v_later;",
    " IF v_later THEN RAISE EXCEPTION USING ERRCODE='55000',MESSAGE='operator erase fence check: a later migration is applied; roll it back first';END IF;",
    " EXECUTE 'SELECT sha256 FROM sessions.__96bulls_migrations WHERE name=\'\'" + NAME + "\'\'' INTO v_sha;",
    " IF v_sha IS DISTINCT FROM '" + checksum + "'",
    " THEN RAISE EXCEPTION USING ERRCODE='55000',MESSAGE='operator erase fence check: own applied checksum required';END IF;",
    " IF EXISTS(SELECT 1 FROM sessions.session_erasure_fences) THEN",
    "  RAISE EXCEPTION USING ERRCODE='55000',MESSAGE='operator erase fence check: erase fences exist; refusing to remove enforcement';END IF;",
    "END $rollback_guard$;",
    ...bodies,
    "DROP TRIGGER ingest_erase_fence_directory_guard ON sessions.session_directory;",
    "DROP TRIGGER ingest_erase_fence_directory_lock ON sessions.session_directory;",
    "DROP TRIGGER ingest_erase_fence_index_guard ON sessions.session_index;",
    "DROP TRIGGER ingest_erase_fence_index_lock ON sessions.session_index;",
    "DROP FUNCTION " + [...ctx.defined].filter((s) => !HOOKS.some(([h]) => h === s)).reverse().join(",\n ") + ";",
    "DELETE FROM sessions.__96bulls_migrations WHERE name='" + NAME + "';",
  ].join("\n") + "\n" };
}

