    " END IF;",
    "END $rollback_guard$;",
    "DROP TABLE sessions.session_erasure_events, sessions.session_erasure_receipts, sessions.session_erasure_fences;",
    "DROP SEQUENCE sessions.session_erasure_writer_epoch;",
