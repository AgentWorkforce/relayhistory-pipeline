/**
 * Replacement-only lane (slot 059000): sessions.ingest_publication_prepare and sessions.ingest_publication_publish
 * admit storage provider 'gcs' as well as 's3' (NULL and every other provider still refused; publish also requires
 * the landed provider to equal the prepared pointer row's). Owner and ACL stay as landed. Also generates the
 * rollback, which restores prepare's 060000 body and publish's 043850 body exactly.
 */
import { createHash } from "node:crypto";
import type { LaneContext, LaneManifest } from "../types.ts";

const MIGRATION = "supabase/migrations/20261105059000_ingest_publication_gcs_provider.sql";
const PREPARE_SOURCE = "supabase/migrations/20261104060000_ingest_canonical_publication.sql";
const PUBLISH_SOURCE = "supabase/migrations/20261105043850_ingest_acquisition_owner.sql";
const ROLLBACK = "supabase/rollbacks/20261105059000_ingest_publication_gcs_provider.down.sql";
const NAME = "upstream:20261105059000_ingest_publication_gcs_provider.sql";
const PREPARE = "sessions.ingest_publication_prepare(jsonb)";
const PUBLISH = "sessions.ingest_publication_publish(jsonb)";

/** 060000's exact prepare body, as CREATE OR REPLACE. */
export function canonicalPublicationPrepareBody(source: string): string {
  const m = source.match(/CREATE FUNCTION sessions\.ingest_publication_prepare\(p jsonb\)[\s\S]*?END \$prepare\$;/g);
  if (m?.length !== 1) throw Error("publication gcs provider rollback: exact 060000 prepare body missing");
  return "CREATE OR REPLACE" + m[0].slice("CREATE".length);
}

/** 043850's exact publish body (already CREATE OR REPLACE). */
export function acquisitionOwnerPublishBody(source: string): string {
  const m = source.match(/CREATE OR REPLACE FUNCTION sessions\.ingest_publication_publish\(p jsonb\)[\s\S]*?END \$publish\$;/g);
  if (m?.length !== 1) throw Error("publication gcs provider rollback: exact 043850 publish body missing");
  return m[0];
}

async function rollback(ctx: LaneContext): Promise<Record<string, string>> {
  const prepare = canonicalPublicationPrepareBody(await ctx.read(PREPARE_SOURCE));
  const publish = acquisitionOwnerPublishBody(await ctx.read(PUBLISH_SOURCE));
  const checksum = createHash("sha256").update(ctx.sql).digest("hex");
  return { [ROLLBACK]: [
    "-- Generated by the publication-gcs-provider lane. Reverse of 20261105059000: restores 20261104060000's exact",
    "-- sessions.ingest_publication_prepare and 20261105043850's exact sessions.ingest_publication_publish (owner,",
    "-- SECURITY DEFINER, search_path and ACL unchanged). Rows and messages already published with provider 'gcs' stay;",
    "-- after this rollback a 'gcs' install can no longer publish.",
    "-- Refused (55000) unless 059000 is applied with this exact checksum (a repeat cannot restore already restored bodies),",
    "-- and while a later migration is applied. Run as one transaction (psql -1 -v ON_ERROR_STOP=1). Never applied by this",
    "-- lane: applying it to any real database needs Khaliq's separate, explicit OK.",
    "DO $rollback_guard$ DECLARE v_later boolean;v_sha text; BEGIN",
    " IF to_regclass('sessions.__96bulls_migrations')IS NULL",
    " THEN RAISE EXCEPTION USING ERRCODE='55000',MESSAGE='publication gcs provider: migration ledger required';END IF;",
    " EXECUTE 'SELECT EXISTS(SELECT 1 FROM sessions.__96bulls_migrations WHERE name LIKE \'\'upstream:%\'\' AND name COLLATE \"C\">\'\'" + NAME + "\'\')' INTO v_later;",
    " IF v_later THEN RAISE EXCEPTION USING ERRCODE='55000',MESSAGE='publication gcs provider: a later migration is applied; roll it back first';END IF;",
    " EXECUTE 'SELECT sha256 FROM sessions.__96bulls_migrations WHERE name=\'\'" + NAME + "\'\'' INTO v_sha;",
    " IF v_sha IS DISTINCT FROM '" + checksum + "'",
    " THEN RAISE EXCEPTION USING ERRCODE='55000',MESSAGE='publication gcs provider: own applied checksum required';END IF;",
    "END $rollback_guard$;",
    "-- 20261104060000's prepare exactly.",
    prepare,
    "-- 20261105043850's publish exactly.",
    publish,
    "DELETE FROM sessions.__96bulls_migrations WHERE name='" + NAME + "';",
  ].join("\n") + "\n" };
}

export const publicationGcsProvider: LaneManifest = {
  lane: "publication-gcs-provider",
  owner: "fix/gcs-publication-provider (slot 059000)",
  migration: MIGRATION,
  prefixes: [],
  grantSources: [],
  functions: {},
  replaces: {
    [PREPARE]: { secdef: true, original: PREPARE_SOURCE },
    [PUBLISH]: { secdef: true, original: PREPARE_SOURCE },
  },
  extraOutputs: rollback,
};
