async function rollback(ctx: LaneContext): Promise<Record<string, string>> {
  const sql = [
    "-- Generated by the babysitter-retention lane. Only an installation that never registered a bucket may be",
    "-- removed: a registered bucket is an S3 object that only this registry knows to erase, and once an erase",
    "-- is recorded the registry and its audit are the proof of what was deleted and when.",
    "-- Operational rollback is sessions.babysitter_retention_configure('{\"enabled\":false,\"dryRun\":true}')",
    "-- plus the Worker/sweeper flags off; it RETAINS the registry and audit.",
    "DO $rollback_guard$ DECLARE v_later boolean; BEGIN",
    " IF EXISTS(SELECT 1 FROM sessions.babysitter_retention_objects)",
    "  OR EXISTS(SELECT 1 FROM sessions.babysitter_retention_audit WHERE action='erased')",
    " THEN RAISE EXCEPTION USING ERRCODE='55000',MESSAGE='babysitter retention: registered buckets exist; disable instead of rolling back';END IF;",
    " IF to_regclass('sessions.__96bulls_migrations')IS NOT NULL THEN",
    "  EXECUTE 'SELECT EXISTS(SELECT 1 FROM sessions.__96bulls_migrations WHERE name LIKE ''upstream:%'' AND name COLLATE \"C\">''" + NAME + "'')' INTO v_later;",
    "  IF v_later THEN RAISE EXCEPTION USING ERRCODE='55000',MESSAGE='babysitter retention: a later migration is applied; roll it back first';END IF;",
    " END IF;",
    "END $rollback_guard$;",
    "DROP TRIGGER babysitter_retention_audit_append_only ON sessions.babysitter_retention_audit;",
    "DROP FUNCTION " + [...ctx.defined].reverse().join(",\n ") + ";",
    "DROP TABLE sessions.babysitter_retention_audit,sessions.babysitter_retention_objects,sessions.babysitter_retention_settings;",
    "DO $ledger$ BEGIN",
    " IF to_regclass('sessions.__96bulls_migrations')IS NOT NULL THEN",
    "  DELETE FROM sessions.__96bulls_migrations WHERE name='" + NAME + "';",
    " END IF;",
    "END $ledger$;",
    "-- The NOLOGIN role bulls96_babysitter_retention is KEPT, as every lane keeps its cluster roles (033000):",
    "-- roles are cluster-wide (another database of the cluster may hold its grants), they are provisioned",
    "-- by the role bootstrap rather than by this migration, and the next migrate reapplies this step",
    "-- against the same role. With this migration gone it can execute nothing in this database.",
  ].join("\n") + "\n";
  return { [ROLLBACK]: sql };
}

