/** Generate the model-role policy from the existing reviewed ingest bare-role
 * bootstrap/effective-privilege verifier, plus the ONE model capability registry.
 * SQL deployment/build boundary requires a standalone psql verifier. No I/O
 * beyond source files, no DB/cloud calls, and --check never mutates sources. */
import{readFile,writeFile}from"node:fs/promises";
import{MODEL_WORKER_ROLE,MODEL_WORKER_FUNCTIONS}from"../src/shared/model-worker-contract.ts";
const root=new URL("../",import.meta.url),read=(p:string)=>readFile(new URL(p,root),"utf8");
const bootstrap=await read("supabase/bootstrap/session_ingest_roles.sql"),verifier=await read("supabase/bootstrap/session_ingest_verify.sql");
const stamp="-- GENERATED by scripts/sync-history-model-role.ts from the reviewed ingest role policy +\n-- src/shared/model-worker-contract.ts. Source proposal only; no LOGIN/password provisioning.\n";
let b=bootstrap.slice(bootstrap.indexOf("DO $bootstrap$"));
if(!b.startsWith("DO $bootstrap$")||!b.includes("ARRAY['bulls96_session_ingest', 'bulls96_session_ingest_seeder']")||!b.includes("(v_name = 'bulls96_session_ingest_seeder' AND r.rolcanlogin)"))throw Error("model_bootstrap_policy_drift");
b=b.replace("ARRAY['bulls96_session_ingest', 'bulls96_session_ingest_seeder']",JSON.stringify([MODEL_WORKER_ROLE]).replace('["',"ARRAY['").replace('"]',"']").replaceAll('","',"','"))
 .replace("(v_name = 'bulls96_session_ingest_seeder' AND r.rolcanlogin)","false")
 .replaceAll("or the seeder can log in","or its role policy differs");
const array=verifier.match(/v_allowed text\[\] := ARRAY\[[\s\S]*?\]::text\[\];/);
if(!array||array.length!==1)throw Error("model_verifier_policy_drift");
let v=verifier.replace(array[0],"v_allowed text[] := ARRAY[\n"+MODEL_WORKER_FUNCTIONS.map(f=>" '"+f+"'").join(",\n")+"\n ]::text[];")
 .replaceAll("bulls96_session_ingest",MODEL_WORKER_ROLE).replaceAll("session ingest","session model");
const outputs={"supabase/bootstrap/session_history_model_worker.sql":stamp+b,"supabase/bootstrap/session_history_model_verify.sql":stamp+v};
let drift=false;
for(const[p,out]of Object.entries(outputs)){
 let old:string|undefined;try{old=await read(p)}catch{}
 if(old===out)continue;
 if(process.argv.includes("--check")){console.error("model role drift: "+p);drift=true;}
 else await writeFile(new URL(p,root),out);
}
if(drift)process.exitCode=1;else console.log(JSON.stringify({role:MODEL_WORKER_ROLE,functions:MODEL_WORKER_FUNCTIONS.length,tableGrants:0}));
