-- SLOT 044090. Ingest claim sessions, PR 2 of 2: the claim-sessions reader v2 for the owner buffered readers
-- (sessions.buffered_sessions_for and sessions.buffered_session_stages_for), a commit-time accepted_at refresh,
-- and the reader switch. DEFAULT OFF.
--
-- Why: 044040 made the detail session-first through the records GIN, but the list still reads every buffered
-- batch of the user from the outbox to build one page, and the detail's containment is a GIN probe across
-- tenants. 044080 built sessions.ingest_claim_sessions (one row per claim and string (source, session_id) pair of
-- its records, tenant columns copied, accepted_at = the batch's committed_at). This slot lets both readers use it.
--
-- The switch: sessions.ingest_claim_sessions_policy.read_enabled (new, default false). The readers use v2 only
-- while read_enabled AND write_enabled AND backfill_complete_at IS NOT NULL (a plain read of the policy row); a
-- CHECK refuses read_enabled without the other two, and the replaced policy guard clears read_enabled on every
-- write_enabled change (the same change already clears completion). Gate off, each reader runs 044040's query
-- unchanged (one extra policy read). The public signatures, SECURITY DEFINER, search_path, STABLE and the
-- grants are unchanged (CREATE OR REPLACE keeps the ACL).
--
-- Identity: gate on, each reader returns the same rows, order and cursor as 044040 on the same snapshot.
-- Every judgement CTE (stg, grp, ...) is per stage, except ctl which is global, and a stage can keep session S
-- only if its claim's records hold S as JSON strings, which is exactly when the side table has (claim, S) once
-- the backfill is complete and the writer is on. So 044040's query restricted to the claims of a set of
-- sessions gives those sessions' exact rows. The list then walks the side rows in accepted_at DESC (an exact
-- top-k; see the comment in the function), the detail joins the session's side rows to its claims and keeps
-- the containment as a recheck. claim-sessions-reader.pglite.test.ts compares v2 with 044040 row for row.
-- Known divergences, both needing hand-corrupted data or a hand-deleted side row: a claim whose records carry
-- a non-string source or session_id (jsonb_to_recordset reads it as text, the side table skips it), and a
-- malformed buffered stage of a session outside the page (044040 may raise on it; v2 never reads it).
--
-- accepted_at refresh: a claim is written before its batch commits, so the 044080 writer usually stores NULL.
-- An AFTER UPDATE trigger on sessions.ingest_batches sets the batch's side rows to NEW.committed_at when the
-- batch becomes committed (every commit path sets state and committed_at in one UPDATE; committed_at never
-- changes afterwards, batches are never deleted or uncommitted). Fast-path batches are inserted committed and
-- their claims come after (FK), so the writer reads committed_at directly. The refresh does nothing while
-- write_enabled is false and never raises: any error is swallowed (one subtransaction per enabled commit), and
-- the list's pre-pass evaluates every session that has a NULL accepted_at under a committed batch, so a missed
-- refresh costs time, never a row.
--
-- Complexity (gate on): list = the owner's side rows newer than the page's last row (plus one chunk, growing
-- 4x from 4*limit) and the stages of the sessions they name, plus the owner's NULL-accepted rows of committed
-- batches; worst case (many recent sessions hidden or published) it degrades towards the whole claim history.
-- Detail = the session's side rows (btree) instead of a GIN probe.
--
-- No index is added. sessions.buffered_search_gate_for (043890) also uses records @>, but as a per-claim check
-- on a claim it already holds, not a lookup of a session's claims; it is unchanged.
-- Down path: supabase/rollbacks/20261105044090_claim_sessions_reader.down.sql (generated by
-- scripts/sessions-function-boundary/lanes/ingest-claim-sessions-reader.ts).
-- Code only: applying this to any real database, and setting read_enabled, need Khaliq's separate, explicit OK.
SET LOCAL lock_timeout='5s';

DO $claim_sessions_reader_creator$
DECLARE me oid;
BEGIN
 SELECT oid INTO STRICT me FROM pg_roles WHERE rolname=current_user;
 IF (SELECT count(*) FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace
   WHERE n.nspname='sessions' AND c.relkind='r'
    AND c.relname IN('ingest_batches','ingest_claim_sessions','ingest_claim_sessions_policy')
    AND c.relowner=me)<>3
  OR EXISTS(SELECT 1 FROM pg_attribute WHERE attrelid='sessions.ingest_claim_sessions_policy'::regclass
             AND attname='read_enabled' AND NOT attisdropped)
  OR to_regprocedure('sessions.ingest_batch_claim_sessions_refresh()') IS NOT NULL THEN
  RAISE EXCEPTION USING ERRCODE='55000',MESSAGE='claim sessions reader: requires the owner of the claim-session tables and no prior reader objects';END IF;
END $claim_sessions_reader_creator$;

-- The reader switch. No index: the policy has one row.
ALTER TABLE sessions.ingest_claim_sessions_policy
 ADD COLUMN read_enabled boolean NOT NULL DEFAULT false,
 ADD CONSTRAINT ingest_claim_sessions_policy_read_check
  CHECK(NOT read_enabled OR (write_enabled AND backfill_complete_at IS NOT NULL));

-- 044080's guard, plus: any write_enabled change also clears read_enabled (the side table is no longer known
-- complete). Same language, volatility, search_path and owner-only ACL (CREATE OR REPLACE keeps it).
CREATE OR REPLACE FUNCTION sessions.ingest_claim_sessions_policy_guard() RETURNS trigger
LANGUAGE plpgsql VOLATILE SET search_path=pg_catalog,pg_temp AS $claim_sessions_policy$
BEGIN
 IF TG_LEVEL='STATEMENT' THEN
  IF EXISTS(SELECT 1 FROM sessions.ingest_claim_sessions_policy AS p WHERE NOT p.write_enabled) THEN
   LOCK TABLE sessions.ingest_claim_attempts IN SHARE MODE;
  END IF;
  RETURN NULL;
 END IF;
 IF TG_OP<>'UPDATE' THEN RAISE EXCEPTION USING ERRCODE='55000',MESSAGE='ingest claim sessions: the policy row is never deleted';END IF;
 IF NEW.write_enabled IS DISTINCT FROM OLD.write_enabled THEN
  NEW.backfill_cursor:=NULL;NEW.backfill_complete_at:=NULL;NEW.read_enabled:=false;
  IF NEW.write_enabled THEN LOCK TABLE sessions.ingest_claim_attempts IN SHARE MODE;END IF;
 END IF;
 NEW.updated_at:=clock_timestamp();
 RETURN NEW;
END $claim_sessions_policy$;

-- The commit-time accepted_at refresh (owner only; not SECURITY DEFINER, like the 044080 writer: commits run
-- inside the owner's SECURITY DEFINER ingest functions). Claims of the batch by ingest_claim_attempts_batch_idx,
-- side rows by their primary key prefix.
CREATE FUNCTION sessions.ingest_batch_claim_sessions_refresh() RETURNS trigger
LANGUAGE plpgsql VOLATILE SET search_path=pg_catalog,pg_temp AS $claim_sessions_refresh$
DECLARE v_enabled boolean;
BEGIN
 BEGIN
  SELECT p.write_enabled INTO v_enabled FROM sessions.ingest_claim_sessions_policy AS p WHERE p.singleton;
  IF NOT coalesce(v_enabled,false) THEN RETURN NULL;END IF;
  UPDATE sessions.ingest_claim_sessions AS cs SET accepted_at=NEW.committed_at
    FROM sessions.ingest_claim_attempts AS a
   WHERE a.org_id=NEW.org_id AND a.workspace_id=NEW.workspace_id AND a.origin_id=NEW.origin_id AND a.batch_id=NEW.batch_id
     AND cs.claim_token=a.claim_token
     AND cs.org_id=NEW.org_id AND cs.workspace_id=NEW.workspace_id AND cs.origin_id=NEW.origin_id AND cs.batch_id=NEW.batch_id
     AND cs.accepted_at IS DISTINCT FROM NEW.committed_at;
 EXCEPTION WHEN OTHERS THEN
  -- Never break a commit. The row stays NULL and the list's pre-pass evaluates its session.
  RETURN NULL;
 END;
 RETURN NULL;
END $claim_sessions_refresh$;
CREATE TRIGGER ingest_batch_claim_sessions_refresh AFTER UPDATE OF state,committed_at ON sessions.ingest_batches
 FOR EACH ROW WHEN(NEW.state='committed' AND (OLD.state IS DISTINCT FROM 'committed' OR OLD.committed_at IS DISTINCT FROM NEW.committed_at))
 EXECUTE FUNCTION sessions.ingest_batch_claim_sessions_refresh();

REVOKE ALL ON FUNCTION sessions.ingest_batch_claim_sessions_refresh()
 FROM PUBLIC,anon,authenticated,service_role,bulls96_session_ingest,bulls96_session_ingest_seeder;
-- Strip EXECUTE from every other grantee present at creation (default privileges): owner only.
DO $claim_sessions_refresh_revoke$
DECLARE v_grantee text;
BEGIN
 FOR v_grantee IN
  SELECT r.rolname FROM pg_proc AS p
   CROSS JOIN LATERAL aclexplode(coalesce(p.proacl,acldefault('f',p.proowner))) AS a
   JOIN pg_roles AS r ON r.oid=a.grantee
  WHERE p.oid='sessions.ingest_batch_claim_sessions_refresh()'::regprocedure
    AND a.privilege_type='EXECUTE' AND a.grantee<>p.proowner
 LOOP
  EXECUTE format('REVOKE ALL ON FUNCTION sessions.ingest_batch_claim_sessions_refresh() FROM %I',v_grantee);
 END LOOP;
END $claim_sessions_refresh_revoke$;

-- The readers: 044040's bodies, with the gate and the v2 branch after the open check.
CREATE OR REPLACE FUNCTION sessions.buffered_sessions_for(
  p_workspace text, p_cursor_ts timestamptz, p_cursor_session text, p_cursor_source text, p_limit integer,
  p_cutover_epoch text, p_head_epoch text, p_head_version text, p_head_digest text, p_head_kind text,
  p_head_pending boolean, p_privacy_baseline_sha256 text
)
RETURNS TABLE(source text, session_id text, first_ts timestamptz, last_ts timestamptz,
              stage_count integer, bytes bigint, user_id text, admission_epoch text, admission_version text)
LANGUAGE plpgsql STABLE SECURITY DEFINER
SET search_path = pg_catalog, sessions, pg_temp AS $buffered_sessions$
#variable_conflict use_column
DECLARE
  v_org text;
  v_ws text;
  v_user text;
  v_open boolean;
  v_adm_epoch text;
  v_adm_version bigint;
  v_limit integer := least(greatest(coalesce(p_limit, 50), 1), 100);
  -- 044090 (claim-sessions reader v2; used only while the policy gate is on).
  v_v2 boolean;
  v_hi timestamptz;
  v_lo timestamptz;
  v_first boolean := true;
  v_done boolean := false;
  v_n integer;
  v_chunk integer;
  v_new_src text[];
  v_new_ses text[];
  v_seen_src text[] := '{}';
  v_seen_ses text[] := '{}';
  e_src text[];
  e_ses text[];
  e_first timestamptz[];
  e_last timestamptz[];
  e_cnt integer[];
  e_bytes bigint[];
  r_src text[] := '{}';
  r_ses text[] := '{}';
  r_first timestamptz[] := '{}';
  r_last timestamptz[] := '{}';
  r_cnt integer[] := '{}';
  r_bytes bigint[] := '{}';
BEGIN
  SELECT sc.org_id, sc.workspace_id, sc.user_id, sc.gate_open, sc.admission_epoch, sc.admission_version
    INTO STRICT v_org, v_ws, v_user, v_open, v_adm_epoch, v_adm_version
    FROM sessions.owner_buffered_read_scope(p_workspace, p_cutover_epoch, p_head_epoch, p_head_version,
                                              p_head_digest, p_head_kind, p_head_pending,
                                              p_privacy_baseline_sha256) AS sc;
  IF (p_cursor_ts IS NULL) <> (p_cursor_session IS NULL) OR (p_cursor_ts IS NULL) <> (p_cursor_source IS NULL) THEN
    RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'owner buffered read: cursor needs ts, session and source together';
  END IF;
  IF NOT v_open THEN
    RETURN;
  END IF;
  -- 044090: the claim-sessions reader gate, a plain read of the policy row (no lock). On only when the reader
  -- switch, the writer and a completed backfill are all set (the policy CHECK enforces the same).
  SELECT coalesce(bool_or(cp.read_enabled AND cp.write_enabled AND cp.backfill_complete_at IS NOT NULL), false)
    INTO v_v2
    FROM sessions.ingest_claim_sessions_policy AS cp
   WHERE cp.singleton;
  IF v_v2 THEN
    -- 044090 v2: an exact top-k walk over the side table instead of the whole outbox. Same judgement, same rows,
    -- order and cursor as the 044040 query below (claim-sessions-reader.pglite.test.ts compares them).
    --
    -- Why it is exact. A session's row depends only on the stages whose claim records hold it (every judgement
    -- CTE is per stage; ctl is global), so a session is evaluated exactly by reading the claims its side rows
    -- name (the backfill made the side table complete; the writer keeps it so). Its last_ts is the latest
    -- committed_at of a kept stage, and every such stage's claim has a side row whose accepted_at is that
    -- batch's committed_at (the writer or the commit refresh sets it; committed_at never changes once set), or
    -- a NULL accepted_at under a committed batch (a refresh that was skipped or failed). So:
    --  1. Every session with such a NULL row is evaluated first (normally none).
    --  2. Side rows are walked in accepted_at DESC (ingest_claim_sessions_accepted_idx), at or below the cursor
    --     time, in chunks that grow 4x and always finish their lowest level v_lo. Each newly seen session is
    --     evaluated exactly, over all of its claims.
    --  3. A session not yet seen has every side row below v_lo, so its last_ts < v_lo. Once v_limit evaluated
    --     sessions pass the cursor with last_ts >= v_lo, no unseen session can rank among the first v_limit;
    --     the walk stops there (or when the rows run out).
    -- The page is then the same cursor filter, ORDER BY and LIMIT over the evaluated rows.
    -- Cost: the side rows at or above the page's last row (plus one chunk) and the stages of the sessions they
    -- name, not the owner's outbox.
    v_hi := coalesce(p_cursor_ts, 'infinity'::timestamptz);
    v_chunk := 4 * v_limit;
    SELECT coalesce(array_agg(z.source), '{}'), coalesce(array_agg(z.session_id), '{}')
      INTO v_new_src, v_new_ses
      FROM (SELECT DISTINCT cs.source, cs.session_id
              FROM sessions.ingest_claim_sessions AS cs
              JOIN sessions.ingest_batches AS bq
                ON bq.org_id = cs.org_id AND bq.workspace_id = cs.workspace_id AND bq.origin_id = cs.origin_id
               AND bq.batch_id = cs.batch_id
             WHERE cs.org_id = v_org AND cs.workspace_id = v_ws AND cs.user_id = v_user
               AND cs.accepted_at IS NULL AND bq.state = 'committed') AS z;
    LOOP
      IF cardinality(v_new_src) > 0 THEN
        -- The keep-predicate below is 044040's list block (kept at its indentation so a test can compare it):
        -- only stg's driving FROM/WHERE head and its comment differ.
  -- keep-predicate:begin (identical in buffered_sessions_for and buffered_session_stages_for except
  -- stg's driving FROM/WHERE head and its comment, which 044040 makes session-first in the detail;
  -- src/session-ingest/__tests__/owner-buffered-read.pglite.test.ts asserts it)
  WITH ctl AS MATERIALIZED (
    SELECT (SELECT count(*) FROM sessions.upload_resets AS ur
             WHERE ur.org_id = v_org AND ur.workspace_id = v_ws AND ur.user_id = v_user) AS resets,
           EXISTS (SELECT 1 FROM sessions.ingest_lazy_policy AS lp WHERE lp.singleton) AS lazy,
           (SELECT ck.control_epoch FROM sessions.ingest_receipt_seat_clock AS ck WHERE ck.singleton) AS clock_epoch,
           (SELECT ck.source_identity_sha256 FROM sessions.ingest_receipt_seat_clock AS ck WHERE ck.singleton) AS clock_identity,
           (SELECT lp.source_identity_sha256 FROM sessions.ingest_lazy_policy AS lp WHERE lp.singleton) AS pol_identity,
           (SELECT lp.control_epoch FROM sessions.ingest_lazy_policy AS lp WHERE lp.singleton) AS pol_epoch
  ), stg AS MATERIALIZED (
    -- The active, acknowledged, unredacted stage of each buffered batch of this user. Outbox,
    -- stage, attempt and batch identities are equal; the stage reset_epoch equals the user's
    -- upload_resets count (gc_kept). 044090 (gate on): driven from the claims that hold one of this round's
    -- candidate sessions (sessions.ingest_claim_sessions, a semi-join: a claim holding two candidates is read
    -- once), then the claim's stages, the outbox row that has one of them active, and the batch.
    -- ADMISSION WITNESS: the version is source_control_version on the stage's ORIGINAL claim
    -- attempt; the epoch is not stored on the claim and is derived from the immutable
    -- ingest_lazy_policy.control_epoch, valid only when the claim's source_identity_sha256 is
    -- the policy's. A NULL version, NULL identity, a mismatch or no policy hides the stage.
    -- The pair must equal the gate's required (v_adm_epoch, v_adm_version): no control of
    -- any kind since admission. GC ORIGINAL CLAIM: every ancestor of a GC replacement stage
    -- (parent_stage_token chain, bounded at 64) carries this same claim_token, so a
    -- replacement can never lend a newer claim's admission. RULE 5(c): the claim's admission
    -- reset epoch is set, and no upload_resets row of the user is at or after the batch's
    -- acceptance (committed_at); a reset at or after acceptance hides the stage even when the
    -- count check above still matches.
    SELECT s.stage_token, s.claim_token, s.origin_id, s.batch_id, s.stage_key, s.stage_sha256, s.stage_bytes,
           s.group_ordinals, s.reset_epoch, a.records, a.epochs, a.reset_epoch AS a_reset,
           b.committed_at AS accepted_at, a.source_control_version AS adm_version, ctl.pol_epoch AS adm_epoch
      FROM sessions.ingest_claim_attempts AS a
      JOIN sessions.ingest_stage_intents AS s ON a.claim_token = s.claim_token
      JOIN sessions.ingest_buffer_outbox AS o ON s.stage_token = o.active_stage_token
      JOIN sessions.ingest_batches AS b
        ON b.org_id = o.org_id AND b.workspace_id = o.workspace_id AND b.origin_id = o.origin_id AND b.batch_id = o.batch_id
     CROSS JOIN ctl
     WHERE a.claim_token IN (SELECT cs.claim_token
                               FROM sessions.ingest_claim_sessions AS cs
                               JOIN unnest(v_new_src, v_new_ses) AS cq(source, session_id)
                                 ON cs.source = cq.source AND cs.session_id = cq.session_id
                              WHERE cs.org_id = v_org AND cs.workspace_id = v_ws AND cs.user_id = v_user)
       AND o.org_id = v_org AND o.workspace_id = v_ws AND o.user_id = v_user AND o.state = 'buffered'
       AND s.receipt_state = 'acknowledged' AND s.cleanup_state <> 'redacted'
       AND ROW(s.org_id, s.workspace_id, s.user_id, s.origin_id, s.batch_id, s.digest)
           = ROW(o.org_id, o.workspace_id, o.user_id, o.origin_id, o.batch_id, o.digest)
       AND ROW(a.org_id, a.workspace_id, a.user_id, a.origin_id, a.batch_id, a.digest, a.reset_epoch)
           IS NOT DISTINCT FROM ROW(s.org_id, s.workspace_id, s.user_id, s.origin_id, s.batch_id, s.digest, s.reset_epoch)
       AND b.user_id = v_user AND b.digest = o.digest AND b.state = 'committed' AND b.publication_state = 'buffered'
       AND b.committed_at IS NOT NULL
       AND jsonb_typeof(a.records) = 'array' AND jsonb_typeof(a.epochs) = 'array'
       AND jsonb_typeof(s.group_ordinals) = 'array'
       AND ctl.resets = s.reset_epoch
       AND a.reset_epoch IS NOT NULL
       AND NOT EXISTS (SELECT 1 FROM sessions.upload_resets AS ur
                        WHERE ur.org_id = v_org AND ur.workspace_id = v_ws AND ur.user_id = v_user
                          AND (ur.reset_at IS NULL OR ur.reset_at >= b.committed_at))
       AND a.source_control_version IS NOT NULL AND a.source_identity_sha256 IS NOT NULL
       AND ctl.pol_identity IS NOT NULL AND ctl.pol_epoch IS NOT NULL
       AND a.source_identity_sha256 = ctl.pol_identity
       AND ctl.pol_epoch = v_adm_epoch AND a.source_control_version = v_adm_version
       AND NOT EXISTS (
         WITH RECURSIVE anc(claim_token, parent_stage_token, depth) AS (
           SELECT p.claim_token, p.parent_stage_token, 1
             FROM sessions.ingest_stage_intents AS p WHERE p.stage_token = s.parent_stage_token
           UNION ALL
           SELECT p.claim_token, p.parent_stage_token, an.depth + 1
             FROM anc AS an JOIN sessions.ingest_stage_intents AS p ON p.stage_token = an.parent_stage_token
            WHERE an.depth < 64)
         SELECT 1 FROM anc
          WHERE anc.claim_token IS DISTINCT FROM s.claim_token
             OR (anc.depth >= 64 AND anc.parent_stage_token IS NOT NULL))
  ), grp AS (
    -- One row per (stage, object group index, original claim ordinal).
    SELECT st.stage_token, (g.idx - 1)::integer AS group_index, (e.value::text)::integer AS ord
      FROM stg AS st
     CROSS JOIN LATERAL jsonb_array_elements(st.group_ordinals) WITH ORDINALITY AS g(value, idx)
     CROSS JOIN LATERAL jsonb_array_elements(CASE WHEN jsonb_typeof(g.value) = 'array' THEN g.value ELSE '[null]'::jsonb END) AS e(value)
     WHERE jsonb_typeof(e.value) = 'number' AND e.value::text ~ '^(0|[1-9][0-9]{0,2})$'
  ), bad_stage AS MATERIALIZED (
    -- gc_kept refuses malformed groups and duplicate ordinals: such a stage is never shown.
    -- 044040: MATERIALIZED, so it is computed once. Inlined (043700), judged's NOT EXISTS re-ran it for every
    -- (stage, ordinal) row: O(stages^2 x groups), the list's dominant cost on a large backlog.
    SELECT st.stage_token
      FROM stg AS st
     WHERE EXISTS (SELECT 1 FROM jsonb_array_elements(st.group_ordinals) AS g(value)
                    WHERE jsonb_typeof(g.value) IS DISTINCT FROM 'array' OR jsonb_array_length(g.value) = 0
                       OR EXISTS (SELECT 1 FROM jsonb_array_elements(g.value) AS e(value)
                                   WHERE jsonb_typeof(e.value) IS DISTINCT FROM 'number'
                                      OR e.value::text !~ '^(0|[1-9][0-9]{0,2})$'))
        -- 044040: one hashed pass over grp instead of a correlated group-by per stage (was O(stages x groups)).
        OR st.stage_token IN (SELECT g2.stage_token FROM grp AS g2 GROUP BY g2.stage_token, g2.ord HAVING count(*) > 1)
  ), rec AS (
    SELECT st.stage_token, r.ord, r.source, r.session_id, r.record_id, r.revision, r.digest
      FROM stg AS st
     CROSS JOIN LATERAL jsonb_to_recordset(st.records)
           AS r(ord integer, source text, session_id text, record_id text, revision bigint, digest text)
  ), recn AS (
    -- A duplicate original ordinal makes every record of that ordinal unusable (gc_kept 55000).
    -- 044040: a window count over (stage, ord) instead of a correlated count per record (was O(records^2)).
    -- A NULL ord equals nothing, so the old count was 0 for it: excluded here too.
    SELECT w.stage_token, w.ord, w.source, w.session_id, w.record_id, w.revision, w.digest
      FROM (SELECT rc.*, count(*) OVER (PARTITION BY rc.stage_token, rc.ord) AS n FROM rec AS rc) AS w
     WHERE w.ord IS NOT NULL AND w.n = 1
  ), ev AS (
    SELECT st.stage_token, x.source, x.session_id, min(x.epoch) AS epoch, max(x.epoch) AS epoch_max,
           min(x.reset_epoch) AS reset_epoch, max(x.reset_epoch) AS reset_max, count(*) AS n
      FROM stg AS st
     CROSS JOIN LATERAL jsonb_to_recordset(st.epochs) AS x(source text, session_id text, epoch bigint, reset_epoch bigint)
     GROUP BY st.stage_token, x.source, x.session_id
  ), judged AS (
    SELECT gr.stage_token, gr.group_index, gr.ord, rc.source, rc.session_id,
           -- ingest_attempt_fenced: an epoch entry exists, the fence version, the per-session
           -- reset epoch and upload_deletions (a missing or ambiguous entry is not live).
           coalesce(rc.session_id IS NOT NULL AND ev.n IS NOT NULL
            AND ev.epoch = ev.epoch_max AND ev.reset_epoch = ev.reset_max
            AND coalesce(fv.epoch, 0) = ev.epoch AND ctl.resets = ev.reset_epoch
            AND NOT EXISTS (SELECT 1 FROM sessions.upload_deletions AS d
                             WHERE d.org_id = v_org AND d.workspace_id = v_ws AND d.user_id = v_user
                               AND d.origin_id = st.origin_id AND d.source = rc.source AND d.session_id = rc.session_id)
            -- RULE 5(a)/(b): a frozen source deletion or an upload_deletions entry of this
            -- (user, source, session) under ANY origin hides the record (stricter than the GC's
            -- exact-origin check above).
            AND rc.source IS NOT NULL
            AND NOT EXISTS (SELECT 1 FROM sessions.ingest_frozen_source_deletions AS fd
                             WHERE fd.org_id = v_org AND fd.workspace_id = v_ws AND fd.user_id = v_user
                               AND fd.source = rc.source AND fd.session_id = rc.session_id)
            AND NOT EXISTS (SELECT 1 FROM sessions.upload_deletions AS d2
                             WHERE d2.org_id = v_org AND d2.workspace_id = v_ws AND d2.user_id = v_user
                               AND d2.source = rc.source AND d2.session_id = rc.session_id)
            -- ingest_buffer_gc_ordinals ACK branch (lazy-current policy present): the native
            -- slot's current owner is the caller, with the same seat/digest/revision/session.
            AND (NOT ctl.lazy OR EXISTS (
              SELECT 1 FROM sessions.ingest_lazy_ack_decisions AS ad
                JOIN sessions.ingest_lazy_native_slots AS ns ON ns.key_sha256 = ad.native_key_sha256
               WHERE ad.claim_token = st.claim_token AND ad.ord = gr.ord AND ad.body_accepted
                 AND ad.source_control_version = st.adm_version
                 AND rc.record_id IS NOT NULL AND rc.source IS NOT NULL AND rc.revision > 0
                 AND rc.digest ~ '^[0-9a-f]{64}$' AND ev.n = 1 AND ev.epoch >= 0 AND ev.reset_epoch = st.a_reset
                 AND ad.candidate_key_sha256 = encode(sha256(convert_to(jsonb_build_array('buffer-first-ack-seat-v1',
                       ctl.clock_epoch, ctl.clock_identity, v_org, v_ws, v_user, st.origin_id, rc.record_id,
                       rc.revision::text, st.a_reset::text, rc.source, rc.session_id, ev.epoch::text)::text, 'UTF8')), 'hex')
                 AND ad.candidate_digest = rc.digest AND ad.reset_epoch = st.a_reset AND ad.fence_epoch = ev.epoch
                 AND ns.org_id = v_org AND ns.workspace_id = v_ws AND ns.origin_id = st.origin_id
                 AND ns.record_id = rc.record_id AND ns.current_owner = v_user
                 AND ns.current_seat_key = ad.seat_key_sha256 AND ns.current_digest = ad.candidate_digest
                 AND ns.current_revision = rc.revision
                 AND ns.current_source IS NOT DISTINCT FROM rc.source
                 AND ns.current_session IS NOT DISTINCT FROM rc.session_id)), false) AS live
      FROM grp AS gr
      JOIN stg AS st ON st.stage_token = gr.stage_token
     CROSS JOIN ctl
      LEFT JOIN recn AS rc ON rc.stage_token = gr.stage_token AND rc.ord = gr.ord
      LEFT JOIN ev ON ev.stage_token = gr.stage_token AND ev.source = rc.source AND ev.session_id = rc.session_id
      LEFT JOIN sessions.ingest_fence_versions AS fv
        ON fv.org_id = v_org AND fv.workspace_id = v_ws AND fv.user_id = v_user AND fv.origin_id = st.origin_id
       AND fv.source = rc.source AND fv.session_id = rc.session_id
     WHERE NOT EXISTS (SELECT 1 FROM bad_stage AS bs WHERE bs.stage_token = gr.stage_token)
  ), kept AS (
    -- A group is shown only when every ordinal resolves to a record of ONE non-null session.
    -- Outside lazy mode the whole group must be live (gc_kept keeps or drops whole groups); in
    -- lazy mode each live ordinal counts (gc_ordinals keeps per ordinal).
    SELECT j.stage_token, j.group_index, min(j.source) AS source, min(j.session_id) AS session_id,
           array_agg(j.ord ORDER BY j.ord) FILTER (WHERE j.live) AS ords
      FROM judged AS j CROSS JOIN ctl
     GROUP BY j.stage_token, j.group_index, ctl.lazy
    HAVING count(j.session_id) = count(*) AND count(j.source) = count(*)
       AND count(DISTINCT j.source) = 1 AND count(DISTINCT j.session_id) = 1
       AND count(*) FILTER (WHERE j.live) > 0
       AND (ctl.lazy OR count(*) FILTER (WHERE j.live) = count(*))
  )
  -- keep-predicate:end
  , per_session AS (
    -- 044040: a kept stage is a stg row, so its bytes and acceptance are read back by primary key from the
    -- same stage and batch rows stg selected (identical values, one snapshot). 043700 joined the stg CTE,
    -- which has no index: the planner's small estimate for kept made that a nested loop, O(stages^2).
    -- 044090: only this round's candidates. Every judgement CTE above is per stage (ctl is global), and every
    -- stage that can keep a candidate is read (its claim holds the candidate), so their values are exact.
    SELECT k.source, k.session_id, min(bb.committed_at) AS first_ts, max(bb.committed_at) AS last_ts,
           count(*)::integer AS stage_count, sum(si.stage_bytes)::bigint AS bytes
      FROM (SELECT DISTINCT k0.stage_token, k0.source, k0.session_id FROM kept AS k0) AS k
      JOIN sessions.ingest_stage_intents AS si ON si.stage_token = k.stage_token
      JOIN sessions.ingest_batches AS bb
        ON bb.org_id = si.org_id AND bb.workspace_id = si.workspace_id AND bb.origin_id = si.origin_id
       AND bb.batch_id = si.batch_id
     WHERE NOT EXISTS (
       SELECT 1 FROM sessions.ingest_publication_heads AS ph
        WHERE ph.org_id = v_org AND ph.workspace_id = v_ws AND ph.user_id = v_user
          AND ph.source = k.source AND ph.session_id = k.session_id
          AND (ph.state = 'live' OR ph.current_key IS NOT NULL))
       AND (k.source, k.session_id) IN (SELECT cq.source, cq.session_id
                                         FROM unnest(v_new_src, v_new_ses) AS cq(source, session_id))
     GROUP BY k.source, k.session_id
  )
  SELECT array_agg(ps.source), array_agg(ps.session_id), array_agg(ps.first_ts), array_agg(ps.last_ts),
         array_agg(ps.stage_count), array_agg(ps.bytes)
    INTO e_src, e_ses, e_first, e_last, e_cnt, e_bytes
    FROM per_session AS ps;
        r_src := r_src || coalesce(e_src, '{}');
        r_ses := r_ses || coalesce(e_ses, '{}');
        r_first := r_first || coalesce(e_first, '{}');
        r_last := r_last || coalesce(e_last, '{}');
        r_cnt := r_cnt || coalesce(e_cnt, '{}');
        r_bytes := r_bytes || coalesce(e_bytes, '{}');
        v_seen_src := v_seen_src || v_new_src;
        v_seen_ses := v_seen_ses || v_new_ses;
      END IF;
      EXIT WHEN v_done;
      IF v_lo IS NOT NULL THEN
        EXIT WHEN (SELECT count(*)
                     FROM unnest(r_last, r_src, r_ses) AS q(last_ts, source, session_id)
                    WHERE q.last_ts >= v_lo
                      AND (p_cursor_ts IS NULL
                           OR q.last_ts < p_cursor_ts
                           OR (q.last_ts = p_cursor_ts AND (q.session_id COLLATE "C", q.source COLLATE "C")
                                                           > (p_cursor_session COLLATE "C", p_cursor_source COLLATE "C"))))
                  >= v_limit;
        v_hi := v_lo;
        v_first := false;
        v_chunk := least(v_chunk * 4, 65536);
      END IF;
      -- The next chunk: its lowest accepted_at becomes v_lo. The first round includes the cursor level itself;
      -- later rounds start strictly below the level already finished (the <= bound keeps the index range closed).
      SELECT min(z.accepted_at), count(*)::integer
        INTO v_lo, v_n
        FROM (SELECT cs.accepted_at
                FROM sessions.ingest_claim_sessions AS cs
               WHERE cs.org_id = v_org AND cs.workspace_id = v_ws AND cs.user_id = v_user
                 AND cs.accepted_at <= v_hi AND (v_first OR cs.accepted_at < v_hi)
               ORDER BY cs.accepted_at DESC NULLS LAST
               LIMIT v_chunk) AS z;
      EXIT WHEN v_n = 0;
      v_done := v_n < v_chunk;
      -- Every session with a side row in [v_lo, v_hi] (the whole v_lo level), not evaluated yet.
      SELECT coalesce(array_agg(z.source), '{}'), coalesce(array_agg(z.session_id), '{}')
        INTO v_new_src, v_new_ses
        FROM (SELECT DISTINCT cs.source, cs.session_id
                FROM sessions.ingest_claim_sessions AS cs
               WHERE cs.org_id = v_org AND cs.workspace_id = v_ws AND cs.user_id = v_user
                 AND cs.accepted_at >= v_lo AND cs.accepted_at <= v_hi AND (v_first OR cs.accepted_at < v_hi)) AS z
       WHERE NOT EXISTS (SELECT 1 FROM unnest(v_seen_src, v_seen_ses) AS q(source, session_id)
                          WHERE q.source = z.source AND q.session_id = z.session_id);
    END LOOP;
    RETURN QUERY
    SELECT ps.source, ps.session_id, ps.first_ts, ps.last_ts, ps.stage_count, ps.bytes, v_user,
           v_adm_epoch, v_adm_version::text
      FROM unnest(r_src, r_ses, r_first, r_last, r_cnt, r_bytes)
           AS ps(source, session_id, first_ts, last_ts, stage_count, bytes)
     WHERE p_cursor_ts IS NULL
        OR ps.last_ts < p_cursor_ts
        OR (ps.last_ts = p_cursor_ts AND (ps.session_id COLLATE "C", ps.source COLLATE "C")
                                        > (p_cursor_session COLLATE "C", p_cursor_source COLLATE "C"))
     ORDER BY ps.last_ts DESC, ps.session_id COLLATE "C", ps.source COLLATE "C"
     LIMIT v_limit;
    RETURN;
  END IF;
  -- Gate off: 044040's query, unchanged.
  RETURN QUERY
  -- keep-predicate:begin (identical in buffered_sessions_for and buffered_session_stages_for except
  -- stg's driving FROM/WHERE head and its comment, which 044040 makes session-first in the detail;
  -- src/session-ingest/__tests__/owner-buffered-read.pglite.test.ts asserts it)
  WITH ctl AS MATERIALIZED (
    SELECT (SELECT count(*) FROM sessions.upload_resets AS ur
             WHERE ur.org_id = v_org AND ur.workspace_id = v_ws AND ur.user_id = v_user) AS resets,
           EXISTS (SELECT 1 FROM sessions.ingest_lazy_policy AS lp WHERE lp.singleton) AS lazy,
           (SELECT ck.control_epoch FROM sessions.ingest_receipt_seat_clock AS ck WHERE ck.singleton) AS clock_epoch,
           (SELECT ck.source_identity_sha256 FROM sessions.ingest_receipt_seat_clock AS ck WHERE ck.singleton) AS clock_identity,
           (SELECT lp.source_identity_sha256 FROM sessions.ingest_lazy_policy AS lp WHERE lp.singleton) AS pol_identity,
           (SELECT lp.control_epoch FROM sessions.ingest_lazy_policy AS lp WHERE lp.singleton) AS pol_epoch
  ), stg AS MATERIALIZED (
    -- The active, acknowledged, unredacted stage of each buffered batch of this user. Outbox,
    -- stage, attempt and batch identities are equal; the stage reset_epoch equals the user's
    -- upload_resets count (gc_kept). The list reads every buffered batch of the user, driven from the outbox.
    -- ADMISSION WITNESS: the version is source_control_version on the stage's ORIGINAL claim
    -- attempt; the epoch is not stored on the claim and is derived from the immutable
    -- ingest_lazy_policy.control_epoch, valid only when the claim's source_identity_sha256 is
    -- the policy's. A NULL version, NULL identity, a mismatch or no policy hides the stage.
    -- The pair must equal the gate's required (v_adm_epoch, v_adm_version): no control of
    -- any kind since admission. GC ORIGINAL CLAIM: every ancestor of a GC replacement stage
    -- (parent_stage_token chain, bounded at 64) carries this same claim_token, so a
    -- replacement can never lend a newer claim's admission. RULE 5(c): the claim's admission
    -- reset epoch is set, and no upload_resets row of the user is at or after the batch's
    -- acceptance (committed_at); a reset at or after acceptance hides the stage even when the
    -- count check above still matches.
    SELECT s.stage_token, s.claim_token, s.origin_id, s.batch_id, s.stage_key, s.stage_sha256, s.stage_bytes,
           s.group_ordinals, s.reset_epoch, a.records, a.epochs, a.reset_epoch AS a_reset,
           b.committed_at AS accepted_at, a.source_control_version AS adm_version, ctl.pol_epoch AS adm_epoch
      FROM sessions.ingest_buffer_outbox AS o
      JOIN sessions.ingest_stage_intents AS s ON s.stage_token = o.active_stage_token
      JOIN sessions.ingest_claim_attempts AS a ON a.claim_token = s.claim_token
      JOIN sessions.ingest_batches AS b
        ON b.org_id = o.org_id AND b.workspace_id = o.workspace_id AND b.origin_id = o.origin_id AND b.batch_id = o.batch_id
     CROSS JOIN ctl
     WHERE o.org_id = v_org AND o.workspace_id = v_ws AND o.user_id = v_user AND o.state = 'buffered'
       AND s.receipt_state = 'acknowledged' AND s.cleanup_state <> 'redacted'
       AND ROW(s.org_id, s.workspace_id, s.user_id, s.origin_id, s.batch_id, s.digest)
           = ROW(o.org_id, o.workspace_id, o.user_id, o.origin_id, o.batch_id, o.digest)
       AND ROW(a.org_id, a.workspace_id, a.user_id, a.origin_id, a.batch_id, a.digest, a.reset_epoch)
           IS NOT DISTINCT FROM ROW(s.org_id, s.workspace_id, s.user_id, s.origin_id, s.batch_id, s.digest, s.reset_epoch)
       AND b.user_id = v_user AND b.digest = o.digest AND b.state = 'committed' AND b.publication_state = 'buffered'
       AND b.committed_at IS NOT NULL
       AND jsonb_typeof(a.records) = 'array' AND jsonb_typeof(a.epochs) = 'array'
       AND jsonb_typeof(s.group_ordinals) = 'array'
       AND ctl.resets = s.reset_epoch
       AND a.reset_epoch IS NOT NULL
       AND NOT EXISTS (SELECT 1 FROM sessions.upload_resets AS ur
                        WHERE ur.org_id = v_org AND ur.workspace_id = v_ws AND ur.user_id = v_user
                          AND (ur.reset_at IS NULL OR ur.reset_at >= b.committed_at))
       AND a.source_control_version IS NOT NULL AND a.source_identity_sha256 IS NOT NULL
       AND ctl.pol_identity IS NOT NULL AND ctl.pol_epoch IS NOT NULL
       AND a.source_identity_sha256 = ctl.pol_identity
       AND ctl.pol_epoch = v_adm_epoch AND a.source_control_version = v_adm_version
       AND NOT EXISTS (
         WITH RECURSIVE anc(claim_token, parent_stage_token, depth) AS (
           SELECT p.claim_token, p.parent_stage_token, 1
             FROM sessions.ingest_stage_intents AS p WHERE p.stage_token = s.parent_stage_token
           UNION ALL
           SELECT p.claim_token, p.parent_stage_token, an.depth + 1
             FROM anc AS an JOIN sessions.ingest_stage_intents AS p ON p.stage_token = an.parent_stage_token
            WHERE an.depth < 64)
         SELECT 1 FROM anc
          WHERE anc.claim_token IS DISTINCT FROM s.claim_token
             OR (anc.depth >= 64 AND anc.parent_stage_token IS NOT NULL))
  ), grp AS (
    -- One row per (stage, object group index, original claim ordinal).
    SELECT st.stage_token, (g.idx - 1)::integer AS group_index, (e.value::text)::integer AS ord
      FROM stg AS st
     CROSS JOIN LATERAL jsonb_array_elements(st.group_ordinals) WITH ORDINALITY AS g(value, idx)
     CROSS JOIN LATERAL jsonb_array_elements(CASE WHEN jsonb_typeof(g.value) = 'array' THEN g.value ELSE '[null]'::jsonb END) AS e(value)
     WHERE jsonb_typeof(e.value) = 'number' AND e.value::text ~ '^(0|[1-9][0-9]{0,2})$'
  ), bad_stage AS MATERIALIZED (
    -- gc_kept refuses malformed groups and duplicate ordinals: such a stage is never shown.
    -- 044040: MATERIALIZED, so it is computed once. Inlined (043700), judged's NOT EXISTS re-ran it for every
    -- (stage, ordinal) row: O(stages^2 x groups), the list's dominant cost on a large backlog.
    SELECT st.stage_token
      FROM stg AS st
     WHERE EXISTS (SELECT 1 FROM jsonb_array_elements(st.group_ordinals) AS g(value)
                    WHERE jsonb_typeof(g.value) IS DISTINCT FROM 'array' OR jsonb_array_length(g.value) = 0
                       OR EXISTS (SELECT 1 FROM jsonb_array_elements(g.value) AS e(value)
                                   WHERE jsonb_typeof(e.value) IS DISTINCT FROM 'number'
                                      OR e.value::text !~ '^(0|[1-9][0-9]{0,2})$'))
        -- 044040: one hashed pass over grp instead of a correlated group-by per stage (was O(stages x groups)).
        OR st.stage_token IN (SELECT g2.stage_token FROM grp AS g2 GROUP BY g2.stage_token, g2.ord HAVING count(*) > 1)
  ), rec AS (
    SELECT st.stage_token, r.ord, r.source, r.session_id, r.record_id, r.revision, r.digest
      FROM stg AS st
     CROSS JOIN LATERAL jsonb_to_recordset(st.records)
           AS r(ord integer, source text, session_id text, record_id text, revision bigint, digest text)
  ), recn AS (
    -- A duplicate original ordinal makes every record of that ordinal unusable (gc_kept 55000).
    -- 044040: a window count over (stage, ord) instead of a correlated count per record (was O(records^2)).
    -- A NULL ord equals nothing, so the old count was 0 for it: excluded here too.
    SELECT w.stage_token, w.ord, w.source, w.session_id, w.record_id, w.revision, w.digest
      FROM (SELECT rc.*, count(*) OVER (PARTITION BY rc.stage_token, rc.ord) AS n FROM rec AS rc) AS w
     WHERE w.ord IS NOT NULL AND w.n = 1
  ), ev AS (
    SELECT st.stage_token, x.source, x.session_id, min(x.epoch) AS epoch, max(x.epoch) AS epoch_max,
           min(x.reset_epoch) AS reset_epoch, max(x.reset_epoch) AS reset_max, count(*) AS n
      FROM stg AS st
     CROSS JOIN LATERAL jsonb_to_recordset(st.epochs) AS x(source text, session_id text, epoch bigint, reset_epoch bigint)
     GROUP BY st.stage_token, x.source, x.session_id
  ), judged AS (
    SELECT gr.stage_token, gr.group_index, gr.ord, rc.source, rc.session_id,
           -- ingest_attempt_fenced: an epoch entry exists, the fence version, the per-session
           -- reset epoch and upload_deletions (a missing or ambiguous entry is not live).
           coalesce(rc.session_id IS NOT NULL AND ev.n IS NOT NULL
            AND ev.epoch = ev.epoch_max AND ev.reset_epoch = ev.reset_max
            AND coalesce(fv.epoch, 0) = ev.epoch AND ctl.resets = ev.reset_epoch
            AND NOT EXISTS (SELECT 1 FROM sessions.upload_deletions AS d
                             WHERE d.org_id = v_org AND d.workspace_id = v_ws AND d.user_id = v_user
                               AND d.origin_id = st.origin_id AND d.source = rc.source AND d.session_id = rc.session_id)
            -- RULE 5(a)/(b): a frozen source deletion or an upload_deletions entry of this
            -- (user, source, session) under ANY origin hides the record (stricter than the GC's
            -- exact-origin check above).
            AND rc.source IS NOT NULL
            AND NOT EXISTS (SELECT 1 FROM sessions.ingest_frozen_source_deletions AS fd
                             WHERE fd.org_id = v_org AND fd.workspace_id = v_ws AND fd.user_id = v_user
                               AND fd.source = rc.source AND fd.session_id = rc.session_id)
            AND NOT EXISTS (SELECT 1 FROM sessions.upload_deletions AS d2
                             WHERE d2.org_id = v_org AND d2.workspace_id = v_ws AND d2.user_id = v_user
                               AND d2.source = rc.source AND d2.session_id = rc.session_id)
            -- ingest_buffer_gc_ordinals ACK branch (lazy-current policy present): the native
            -- slot's current owner is the caller, with the same seat/digest/revision/session.
            AND (NOT ctl.lazy OR EXISTS (
              SELECT 1 FROM sessions.ingest_lazy_ack_decisions AS ad
                JOIN sessions.ingest_lazy_native_slots AS ns ON ns.key_sha256 = ad.native_key_sha256
               WHERE ad.claim_token = st.claim_token AND ad.ord = gr.ord AND ad.body_accepted
                 AND ad.source_control_version = st.adm_version
                 AND rc.record_id IS NOT NULL AND rc.source IS NOT NULL AND rc.revision > 0
                 AND rc.digest ~ '^[0-9a-f]{64}$' AND ev.n = 1 AND ev.epoch >= 0 AND ev.reset_epoch = st.a_reset
                 AND ad.candidate_key_sha256 = encode(sha256(convert_to(jsonb_build_array('buffer-first-ack-seat-v1',
                       ctl.clock_epoch, ctl.clock_identity, v_org, v_ws, v_user, st.origin_id, rc.record_id,
                       rc.revision::text, st.a_reset::text, rc.source, rc.session_id, ev.epoch::text)::text, 'UTF8')), 'hex')
                 AND ad.candidate_digest = rc.digest AND ad.reset_epoch = st.a_reset AND ad.fence_epoch = ev.epoch
                 AND ns.org_id = v_org AND ns.workspace_id = v_ws AND ns.origin_id = st.origin_id
                 AND ns.record_id = rc.record_id AND ns.current_owner = v_user
                 AND ns.current_seat_key = ad.seat_key_sha256 AND ns.current_digest = ad.candidate_digest
                 AND ns.current_revision = rc.revision
                 AND ns.current_source IS NOT DISTINCT FROM rc.source
                 AND ns.current_session IS NOT DISTINCT FROM rc.session_id)), false) AS live
      FROM grp AS gr
      JOIN stg AS st ON st.stage_token = gr.stage_token
     CROSS JOIN ctl
      LEFT JOIN recn AS rc ON rc.stage_token = gr.stage_token AND rc.ord = gr.ord
      LEFT JOIN ev ON ev.stage_token = gr.stage_token AND ev.source = rc.source AND ev.session_id = rc.session_id
      LEFT JOIN sessions.ingest_fence_versions AS fv
        ON fv.org_id = v_org AND fv.workspace_id = v_ws AND fv.user_id = v_user AND fv.origin_id = st.origin_id
       AND fv.source = rc.source AND fv.session_id = rc.session_id
     WHERE NOT EXISTS (SELECT 1 FROM bad_stage AS bs WHERE bs.stage_token = gr.stage_token)
  ), kept AS (
    -- A group is shown only when every ordinal resolves to a record of ONE non-null session.
    -- Outside lazy mode the whole group must be live (gc_kept keeps or drops whole groups); in
    -- lazy mode each live ordinal counts (gc_ordinals keeps per ordinal).
    SELECT j.stage_token, j.group_index, min(j.source) AS source, min(j.session_id) AS session_id,
           array_agg(j.ord ORDER BY j.ord) FILTER (WHERE j.live) AS ords
      FROM judged AS j CROSS JOIN ctl
     GROUP BY j.stage_token, j.group_index, ctl.lazy
    HAVING count(j.session_id) = count(*) AND count(j.source) = count(*)
       AND count(DISTINCT j.source) = 1 AND count(DISTINCT j.session_id) = 1
       AND count(*) FILTER (WHERE j.live) > 0
       AND (ctl.lazy OR count(*) FILTER (WHERE j.live) = count(*))
  )
  -- keep-predicate:end
  , per_session AS (
    -- 044040: a kept stage is a stg row, so its bytes and acceptance are read back by primary key from the
    -- same stage and batch rows stg selected (identical values, one snapshot). 043700 joined the stg CTE,
    -- which has no index: the planner's small estimate for kept made that a nested loop, O(stages^2).
    SELECT k.source, k.session_id, min(bb.committed_at) AS first_ts, max(bb.committed_at) AS last_ts,
           count(*)::integer AS stage_count, sum(si.stage_bytes)::bigint AS bytes
      FROM (SELECT DISTINCT k0.stage_token, k0.source, k0.session_id FROM kept AS k0) AS k
      JOIN sessions.ingest_stage_intents AS si ON si.stage_token = k.stage_token
      JOIN sessions.ingest_batches AS bb
        ON bb.org_id = si.org_id AND bb.workspace_id = si.workspace_id AND bb.origin_id = si.origin_id
       AND bb.batch_id = si.batch_id
     WHERE NOT EXISTS (
       SELECT 1 FROM sessions.ingest_publication_heads AS ph
        WHERE ph.org_id = v_org AND ph.workspace_id = v_ws AND ph.user_id = v_user
          AND ph.source = k.source AND ph.session_id = k.session_id
          AND (ph.state = 'live' OR ph.current_key IS NOT NULL))
     GROUP BY k.source, k.session_id
  )
  SELECT ps.source, ps.session_id, ps.first_ts, ps.last_ts, ps.stage_count, ps.bytes, v_user,
         v_adm_epoch, v_adm_version::text
    FROM per_session AS ps
   WHERE p_cursor_ts IS NULL
      OR ps.last_ts < p_cursor_ts
      OR (ps.last_ts = p_cursor_ts AND (ps.session_id COLLATE "C", ps.source COLLATE "C")
                                      > (p_cursor_session COLLATE "C", p_cursor_source COLLATE "C"))
   ORDER BY ps.last_ts DESC, ps.session_id COLLATE "C", ps.source COLLATE "C"
   LIMIT v_limit;
END
$buffered_sessions$;

CREATE OR REPLACE FUNCTION sessions.buffered_session_stages_for(
  p_workspace text, p_source text, p_session_id text,
  p_cutover_epoch text, p_head_epoch text, p_head_version text, p_head_digest text, p_head_kind text,
  p_head_pending boolean, p_privacy_baseline_sha256 text
)
RETURNS TABLE(batch_id text, stage_key text, stage_sha256 text, stage_bytes bigint,
              group_indexes integer[], group_ordinals jsonb, kept_ordinals integer[], reset_epoch bigint,
              accepted_at timestamptz,
              admission_epoch text, admission_version text)
LANGUAGE plpgsql STABLE SECURITY DEFINER
SET search_path = pg_catalog, sessions, pg_temp AS $buffered_stages$
#variable_conflict use_column
DECLARE
  v_org text;
  v_ws text;
  v_user text;
  v_open boolean;
  v_adm_epoch text;
  v_adm_version bigint;
  v_source text := p_source;
  v_session text := p_session_id;
  v_v2 boolean; -- 044090: the claim-sessions reader gate
BEGIN
  SELECT sc.org_id, sc.workspace_id, sc.user_id, sc.gate_open, sc.admission_epoch, sc.admission_version
    INTO STRICT v_org, v_ws, v_user, v_open, v_adm_epoch, v_adm_version
    FROM sessions.owner_buffered_read_scope(p_workspace, p_cutover_epoch, p_head_epoch, p_head_version,
                                              p_head_digest, p_head_kind, p_head_pending,
                                              p_privacy_baseline_sha256) AS sc;
  IF v_source IS NULL OR char_length(v_source) NOT BETWEEN 1 AND 64
     OR v_session IS NULL OR char_length(v_session) NOT BETWEEN 1 AND 255 THEN
