-- Slot 20261105050020. Agent-name prefix matching for the read API's session list
-- (READ_API_AGENT_MATCH, default off). Code only: merge-only under the schema-window freeze;
-- applying this to any real database needs Khaliq's separate, explicit OK.
--
--   1. sessions.list_session_directory_for(<the 16 arguments of 20261105034000>, p_agent_match text):
--      a new overload. 034000's 16-argument function is untouched and keeps serving the
--      exact match. No argument of the overload has a DEFAULT, on purpose: PostgreSQL
--      forbids a required p_agent_match after defaulted arguments, and a default on it
--      would make every 16-argument named call ambiguous between the two overloads. So a
--      caller names all 17 arguments, and only a call naming p_agent_match reaches it.
--        'exact'   034000's semantics exactly (lower(btrim) membership in session_directory_agents).
--        'prefix'  agent_name_normalized LIKE lower(btrim(p_agent)) || '%', with \, % and _
--                  escaped; needs 3 meaningful characters (session_directory_search_query)
--                  and at most 5000 candidate (session, agent) rows in the workspace.
--      Errors: as 034000, plus 22023 for an agent_match other than exact/prefix, a prefix
--      without an agent or under 3 meaningful characters, and 54000 agent_prefix_too_broad
--      (as search_session_directory, 20261030020000).
--   2. session_directory_agents_prefix_idx: a text_pattern_ops index on
--      session_directory_agents, which the prefix range and the candidate budget walk
--      (session_directory_agents_recent_idx is default-collation ordered and cannot serve a
--      LIKE range). Adopt or create, as 20261105044020: an existing index of that name is
--      adopted only with exactly the expected definition, valid and ready; an absent one is
--      built only on an empty table, or with hoopdb.allow_blocking_index_build=on; on a
--      populated table build it out of band with CREATE INDEX CONCURRENTLY first.
--
-- Rollback: supabase/rollbacks/20261105050020_session_directory_agent_match.down.sql
-- (generated by the read-api-agent-match function-boundary lane).
CREATE FUNCTION sessions.list_session_directory_for(
  p_workspace_id text,
  p_sources text[],
  p_not_sources text[],
  p_project_contains text,
  p_user_ids text[],
  p_agent text,
  p_last_ts_after timestamptz,
  p_last_ts_before timestamptz,
  p_first_ts_after timestamptz,
  p_first_ts_before timestamptz,
  p_session_harnesses text[],
  p_session_ids text[],
  p_cursor_last_activity_at timestamptz,
  p_cursor_session_id text,
  p_cursor_harness text,
  p_limit integer,
  p_agent_match text
)
RETURNS TABLE (
  org_id text, workspace_id text, harness text, session_id text,
  created_at timestamptz, last_activity_at timestamptz,
  title text, task_title text, agent_names text[], project_id text,
  project_key text, project_key_method text, git_repo text, git_branch text,
  initial_commit text, originator text, agent_version text, models text[],
  state text, event_count bigint, input_tokens bigint, output_tokens bigint,
  cost_usd_micros bigint, machine_ids text[], user_ids text[],
  parent_session_ids text[], child_session_count integer,
  short_summary text, short_summary_generated_at timestamptz,
  catalog_projected_at timestamptz, projected_at timestamptz
)
LANGUAGE plpgsql STABLE SECURITY DEFINER
SET search_path = pg_catalog, sessions, pg_temp AS $list_match$
DECLARE
  v_org text;
  v_sources text[];
  v_not_sources text[];
  v_users text[];
  v_agent text;
  v_project text;
  v_has_cursor boolean;
  v_agent_arg text;
  v_sql text;
  v_candidates bigint;
  v_enable_seqscan text;
  v_enable_bitmapscan text;
  v_enable_sort text;
BEGIN
  IF p_workspace_id IS NULL THEN
    RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'session list: workspace is required';
  END IF;
  -- Role guard and tenant pin; refuses (42501) before any value is read.
  v_org := sessions.session_directory_read_api_scope(p_workspace_id);

  IF p_limit IS NULL OR p_limit < 1 OR p_limit > 200 THEN
    RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'session list: limit must be 1 to 200';
  END IF;
  IF (p_session_harnesses IS NULL) <> (p_session_ids IS NULL)
     OR (p_session_ids IS NOT NULL AND (
          cardinality(p_session_ids) NOT BETWEEN 1 AND 200
          OR cardinality(p_session_harnesses) <> cardinality(p_session_ids)
          OR EXISTS (SELECT 1 FROM unnest(p_session_harnesses, p_session_ids) AS k(h, s)
                      WHERE h IS NULL OR h !~ '^[a-z0-9][a-z0-9._-]{0,63}$'
                         OR s IS NULL OR char_length(s) NOT BETWEEN 1 AND 255))) THEN
    RAISE EXCEPTION USING ERRCODE = '22023',
      MESSAGE = 'session list: session keys must be 1 to 200 (harness, session id) pairs';
  END IF;
  IF p_sources IS NOT NULL AND cardinality(p_sources) > 0 THEN
    IF cardinality(p_sources) > 16 OR EXISTS (
         SELECT 1 FROM unnest(p_sources) AS s(v)
          WHERE v IS NULL OR v !~ '^[a-z0-9][a-z0-9._-]{0,63}$') THEN
      RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'session list: sources must be 1 to 16 valid harness names';
    END IF;
    SELECT array_agg(DISTINCT v) INTO v_sources FROM unnest(p_sources) AS s(v);
  END IF;
  IF p_not_sources IS NOT NULL AND cardinality(p_not_sources) > 0 THEN
    IF cardinality(p_not_sources) > 16 OR EXISTS (
         SELECT 1 FROM unnest(p_not_sources) AS s(v)
          WHERE v IS NULL OR v !~ '^[a-z0-9][a-z0-9._-]{0,63}$') THEN
      RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'session list: not_sources must be 1 to 16 valid harness names';
    END IF;
    SELECT array_agg(DISTINCT v) INTO v_not_sources FROM unnest(p_not_sources) AS s(v);
  END IF;
  IF p_user_ids IS NOT NULL AND cardinality(p_user_ids) > 0 THEN
    IF cardinality(p_user_ids) > 20 OR EXISTS (
         SELECT 1 FROM unnest(p_user_ids) AS u(v)
          WHERE v IS NULL OR char_length(v) NOT BETWEEN 1 AND 255) THEN
      RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'session list: users must be 1 to 20 ids of 1 to 255 characters';
    END IF;
    SELECT array_agg(DISTINCT v) INTO v_users FROM unnest(p_user_ids) AS u(v);
  END IF;
  IF p_agent_match IS NULL OR p_agent_match NOT IN ('exact', 'prefix') THEN
    RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'session list: agent_match must be exact or prefix';
  END IF;
  IF p_agent_match = 'prefix' AND p_agent IS NULL THEN
    RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'session list: agent_match prefix needs an agent';
  END IF;
  IF p_agent IS NOT NULL THEN
    v_agent := lower(btrim(p_agent));
    IF v_agent = '' OR char_length(v_agent) > 200 THEN
      RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'session list: agent must be 1 to 200 characters';
    END IF;
    IF p_agent_match = 'prefix' AND sessions.session_directory_search_query(p_agent) IS NULL THEN
      RAISE EXCEPTION USING ERRCODE = '22023',
        MESSAGE = 'session list: agent prefix needs at least 3 meaningful characters';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM sessions.session_directory_catalog_rollout AS r
                    WHERE r.singleton AND r.completed_at IS NOT NULL) THEN
      RAISE EXCEPTION USING ERRCODE = '0A000',
        MESSAGE = 'session list: agent_filter_not_ready: the directory catalog backfill is not complete';
    END IF;
  END IF;
  IF p_project_contains IS NOT NULL THEN
    v_project := btrim(p_project_contains);
    IF v_project = '' OR char_length(v_project) > 200 THEN
      RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'session list: project_contains must be 1 to 200 characters';
    END IF;
  END IF;
  IF (p_last_ts_after IS NOT NULL AND p_last_ts_before IS NOT NULL AND p_last_ts_after > p_last_ts_before)
     OR (p_first_ts_after IS NOT NULL AND p_first_ts_before IS NOT NULL AND p_first_ts_after > p_first_ts_before) THEN
    RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'session list: an after bound is later than its before bound';
  END IF;
  v_has_cursor := p_cursor_last_activity_at IS NOT NULL OR p_cursor_session_id IS NOT NULL
    OR p_cursor_harness IS NOT NULL;
  IF v_has_cursor AND (p_cursor_last_activity_at IS NULL OR p_cursor_session_id IS NULL
       OR p_cursor_harness IS NULL) THEN
    RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'session list: cursor is incomplete';
  END IF;

  v_sql := sessions.session_directory_list_sql(
      coalesce(cardinality(v_sources), 0), v_project IS NOT NULL, coalesce(cardinality(v_users), 0),
      v_agent IS NOT NULL, p_last_ts_after IS NOT NULL, p_last_ts_before IS NOT NULL,
      p_first_ts_after IS NOT NULL, p_first_ts_before IS NOT NULL, p_session_ids IS NOT NULL,
      v_has_cursor, v_not_sources IS NOT NULL);
  v_agent_arg := v_agent;

  IF v_agent IS NOT NULL AND p_agent_match = 'prefix' THEN
    -- The prefix as a LIKE pattern: \, % and _ in the name match themselves.
    v_agent_arg := replace(replace(replace(v_agent, '\', '\\'), '%', '\%'), '_', '\_') || '%';
    -- Candidate budget, as search_session_directory's: an ordered walk of the tenant's
    -- text_pattern_ops agent index that stops after 5001 entries, never a table scan, a
    -- bitmap of every match or a sort. More than 5000 is refused (54000) before the page.
    v_enable_seqscan := current_setting('enable_seqscan');
    v_enable_bitmapscan := current_setting('enable_bitmapscan');
    v_enable_sort := current_setting('enable_sort');
    PERFORM set_config('enable_seqscan', 'off', true), set_config('enable_bitmapscan', 'off', true),
            set_config('enable_sort', 'off', true);
    EXECUTE 'SELECT count(*) FROM (SELECT 1 FROM sessions.session_directory_agents AS a'
      || ' WHERE a.org_id = $1 AND a.workspace_id = $2'
      || ' AND a.agent_name_normalized LIKE $3 ESCAPE ''\'''
      || ' ORDER BY a.agent_name_normalized USING ~<~ LIMIT 5001) AS c'
      INTO v_candidates
      USING v_org, p_workspace_id, v_agent_arg;
    PERFORM set_config('enable_seqscan', v_enable_seqscan, true),
            set_config('enable_bitmapscan', v_enable_bitmapscan, true),
            set_config('enable_sort', v_enable_sort, true);
    IF v_candidates > 5000 THEN
      RAISE EXCEPTION USING ERRCODE = '54000',
        MESSAGE = 'session list: agent_prefix_too_broad: this agent prefix matches more than 5000 agent rows',
        HINT = 'Use a longer agent prefix, or p_agent_match => ''exact''.';
    END IF;
    -- The exact membership predicate of session_directory_list_sql (20261101050000), as a
    -- prefix. Refuses rather than run an unfiltered page if that text ever changes.
    IF strpos(v_sql, 'a.agent_name_normalized = $6)') = 0 THEN
      RAISE EXCEPTION USING ERRCODE = 'XX000', MESSAGE = 'session list: agent membership predicate not found';
    END IF;
    v_sql := replace(v_sql, 'a.agent_name_normalized = $6)', 'a.agent_name_normalized LIKE $6 ESCAPE ''\'')');
  END IF;

  RETURN QUERY EXECUTE v_sql
  USING v_org, p_workspace_id, v_sources,
        CASE WHEN v_project IS NULL THEN NULL
             ELSE '%' || replace(replace(replace(v_project, '\', '\\'), '%', '\%'), '_', '\_') || '%' END,
        v_users, v_agent_arg, p_last_ts_after, p_last_ts_before, p_first_ts_after, p_first_ts_before,
        p_cursor_last_activity_at, p_cursor_session_id, p_cursor_harness, p_limit + 1,
        p_session_harnesses, p_session_ids, v_not_sources;
END
