  RAISE EXCEPTION USING ERRCODE='55000',MESSAGE='generation overlap: requires the original creator of the lazy ingest fence and no prior overlap objects';END IF;
END $overlap_creator$;

CREATE TABLE sessions.ingest_generation_overlap_windows(
 window_id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 from_generation text NOT NULL CHECK(from_generation~'^[0-9a-f]{64}$'),
 to_generation text NOT NULL CHECK(to_generation~'^[0-9a-f]{64}$'),
 admit_during_apply boolean NOT NULL,
 approval_sha256 text NOT NULL CHECK(approval_sha256~'^[0-9a-f]{64}$'),
 opened_by text NOT NULL,
 opened_at timestamptz NOT NULL,
 expires_at timestamptz NOT NULL,
 closed_at timestamptz,
 closed_reason text CHECK(closed_reason IN('rebind','owner','expired')),
 CHECK(from_generation<>to_generation),
 CHECK(expires_at>opened_at AND expires_at<=opened_at+interval '4 hours'),
 CHECK((closed_at IS NULL)=(closed_reason IS NULL)),
 CHECK(closed_at IS NULL OR closed_at>=opened_at)
);
-- At most one open window at a time.
CREATE UNIQUE INDEX ingest_generation_overlap_one_open ON sessions.ingest_generation_overlap_windows((true)) WHERE closed_at IS NULL;
