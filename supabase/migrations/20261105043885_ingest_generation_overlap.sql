  OR to_regprocedure('sessions.ingest_generation_overlap_open(jsonb)') IS NOT NULL
  OR to_regprocedure('sessions.ingest_generation_overlap_close(jsonb)') IS NOT NULL
  OR to_regprocedure('sessions.ingest_generation_overlap_admits(text,text,text)') IS NOT NULL
