-- SLOT 043885 (zero-503 schema windows), assigned by the registry keeper: between the landed 043880 and the
-- unlanded 043890, so it applies next. Design: docs/design/zero-503-schema-windows.md.
--
-- Bounded generation overlap for the ingest generation fence.
--
-- Before this migration every buffered ingest RPC requires the caller's generation to EQUAL the readiness
-- marker's PASS generation (sessions.ingest_require_generation, 20261104050000:58-66), and the lazy custody
-- guard requires the custody policy and the org admission to equal it too (sessions.ingest_lazy_guard,
-- 20261104055000:423-439). The migrator writes the marker 'pending' for the NEW generation before its first
-- step (src/hoopdb/migrate.ts MARKER_PENDING_SQL) and 'pass' only after phase 2, and the policy/admissions
-- move only at the owner rebind (src/hoopdb/ingest-generation-rebind.ts). So from the pending write until
-- the rebind EVERY upload is refused with 55000: the outage this migration removes.
--
-- What it adds (all owner-only; no runtime role gains any privilege):
--   sessions.ingest_generation_overlap_windows   append-only record of owner-opened windows (from -> to,
--                                                bounded expiry <= 4 h, at most one open, never reopened).
--   sessions.ingest_generation_overlap_open(p)   owner only (current_user = function owner, 42501 otherwise),
--                                                under the migrator advisory lock; requires marker PASS for
--                                                `from`, the lazy policy at `from`, `to` <> `from`, `to` never
--                                                a retired generation (no downgrade), explicit hex64 values.
--   sessions.ingest_generation_overlap_close(p)  owner only; closes the matching open window (reason owner or
--                                                rebind). The rebind closes it in its own transaction.
--   sessions.ingest_generation_overlap_retired   append-only record of every generation the custody policy
--                                                left; a trigger on sessions.ingest_lazy_policy writes it and
--                                                refuses setting the policy to a retired generation (no
--                                                downgrade, for the rebind and every other policy write).
--   sessions.ingest_generation_overlap_admits(g, marker_gen, marker_status)
--                                                owner-only helper: true only for an open, unexpired window
--                                                whose from = g and whose to = the marker's generation, with
--                                                the marker 'pass' (or 'pending' when the owner opted into
--                                                admitDuringApply), and only for the two runtime ingest roles
--                                                (bulls96_session_ingest, bulls96_babysitter_retention).
--
-- What it replaces (same signature, owner and ACL kept; CREATE OR REPLACE):
--   sessions.ingest_require_generation(text)  exact PASS equality as before, OR the window's `from`.
--   sessions.ingest_lazy_guard(text)          policy generation = PASS generation as before, OR the window's
--                                             `from`; the org admission must equal the policy generation
--                                             (identical to before when no window is open).
-- With NO open window both functions are exactly as strict as before. The window admits exactly ONE extra
-- generation (the previous PASS), never the unverified pending one, never a wildcard. Every other fence
-- (caller == policy generation in ingest_lazy_begin and ingest_lazy_attempt, the claim's sticky
-- schema_generation, privacy seals, custody clock, epochs, contiguity/ledger checks) is unchanged.
--
-- Additive and old-caller compatible: it creates two tables, six owner-only functions and one trigger on
-- sessions.ingest_lazy_policy, and replaces two
-- owner-only helpers with bodies that reduce to the old predicate while no window exists. Applying it
-- still moves generation() and so still has the pre-existing (one-time) window of its own; see the design
-- doc's bootstrap section. Code only; applying it to any real database needs Khaliq's explicit OK.
-- Down path: supabase/rollbacks/20261105043885_ingest_generation_overlap.down.sql (generated by
-- scripts/sessions-function-boundary/lanes/ingest-generation-overlap.ts).
SET LOCAL lock_timeout='5s';

