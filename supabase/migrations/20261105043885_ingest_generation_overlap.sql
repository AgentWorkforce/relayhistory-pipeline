-- Append-only: a row is never deleted, and only its close (closed_at/closed_reason, once, from NULL) changes.
-- The expiry, generations and approval binding can never be edited (no extension, no retarget).
CREATE FUNCTION sessions.ingest_generation_overlap_immutable() RETURNS trigger
LANGUAGE plpgsql SET search_path=pg_catalog,pg_temp AS $overlap_immutable$
BEGIN
 IF TG_OP<>'UPDATE' THEN RAISE EXCEPTION USING ERRCODE='55000',MESSAGE='generation overlap: windows are append-only';END IF;
 IF OLD.closed_at IS NOT NULL OR NEW.closed_at IS NULL
  OR NEW.window_id IS DISTINCT FROM OLD.window_id OR NEW.from_generation IS DISTINCT FROM OLD.from_generation
  OR NEW.to_generation IS DISTINCT FROM OLD.to_generation OR NEW.admit_during_apply IS DISTINCT FROM OLD.admit_during_apply
  OR NEW.approval_sha256 IS DISTINCT FROM OLD.approval_sha256 OR NEW.opened_by IS DISTINCT FROM OLD.opened_by
  OR NEW.opened_at IS DISTINCT FROM OLD.opened_at OR NEW.expires_at IS DISTINCT FROM OLD.expires_at THEN
  RAISE EXCEPTION USING ERRCODE='55000',MESSAGE='generation overlap: windows are append-only';END IF;
 RETURN NEW;
END $overlap_immutable$;
CREATE TRIGGER ingest_generation_overlap_immutable BEFORE UPDATE OR DELETE ON sessions.ingest_generation_overlap_windows
 FOR EACH ROW EXECUTE FUNCTION sessions.ingest_generation_overlap_immutable();

-- No downgrade, enforced where the authority lives: every generation the custody policy leaves (a rebind, or
-- any other owner write through ingest_lazy_policy_set) is recorded here, append-only, and the policy can never
-- be set to a recorded generation again. Since the caller generation must equal the policy generation
-- (ingest_lazy_begin / ingest_lazy_attempt), a retired generation can never be admitted again, whatever the
-- readiness marker says and whether or not a window was ever opened, expired or closed.
CREATE TABLE sessions.ingest_generation_overlap_retired(
 generation text PRIMARY KEY CHECK(generation~'^[0-9a-f]{64}$'),
 successor text CHECK(successor IS NULL OR (successor~'^[0-9a-f]{64}$' AND successor<>generation)),
 retired_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
