CREATE FUNCTION sessions.ingest_generation_overlap_policy_retire() RETURNS trigger
LANGUAGE plpgsql SET search_path=pg_catalog,pg_temp AS $policy_retire$
BEGIN
 IF TG_OP IN('INSERT','UPDATE') AND EXISTS(SELECT 1 FROM sessions.ingest_generation_overlap_retired WHERE generation=NEW.generation) THEN
  RAISE EXCEPTION USING ERRCODE='55000',MESSAGE='generation overlap: generation already retired';END IF;
 IF TG_OP='UPDATE' AND OLD.generation IS DISTINCT FROM NEW.generation THEN
  INSERT INTO sessions.ingest_generation_overlap_retired(generation,successor) VALUES(OLD.generation,NEW.generation) ON CONFLICT DO NOTHING;
 ELSIF TG_OP='DELETE' THEN
  INSERT INTO sessions.ingest_generation_overlap_retired(generation,successor) VALUES(OLD.generation,NULL) ON CONFLICT DO NOTHING;
  RETURN OLD;
 END IF;
 RETURN NEW;
END $policy_retire$;
CREATE TRIGGER ingest_generation_overlap_policy_retire BEFORE INSERT OR UPDATE OR DELETE ON sessions.ingest_lazy_policy
 FOR EACH ROW EXECUTE FUNCTION sessions.ingest_generation_overlap_policy_retire();

-- The one admission predicate. Owner-only invoker helper: callers are the two replaced fence helpers.
-- FOR SHARE on the window row: a close (UPDATE) waits for every in-flight admitted transaction, and once it
-- commits no transaction admitted by that window can start.
CREATE FUNCTION sessions.ingest_generation_overlap_admits(p_generation text,p_marker_generation text,p_marker_status text) RETURNS boolean
LANGUAGE plpgsql VOLATILE SET search_path=pg_catalog,pg_temp AS $overlap_admits$
BEGIN
 IF p_generation IS NULL OR p_generation!~'^[0-9a-f]{64}$' OR p_marker_generation IS NULL
  OR p_marker_status IS NULL OR p_marker_status NOT IN('pass','pending') OR p_generation=p_marker_generation THEN RETURN false;END IF;
 -- Runtime ingest roles only: owner/operator paths (seat initialize, policy set) stay on exact PASS.
 IF coalesce(nullif(current_setting('role',true),'none'),session_user::text) NOT IN('bulls96_session_ingest','bulls96_babysitter_retention')
 THEN RETURN false;END IF;
 PERFORM 1 FROM sessions.ingest_generation_overlap_windows w
  WHERE w.closed_at IS NULL AND w.expires_at>clock_timestamp()
   AND w.from_generation=p_generation AND w.to_generation=p_marker_generation
   AND(p_marker_status='pass' OR w.admit_during_apply) FOR SHARE;
 RETURN FOUND;
END $overlap_admits$;

CREATE FUNCTION sessions.ingest_generation_overlap_open(p jsonb) RETURNS jsonb
LANGUAGE plpgsql VOLATILE SET search_path=pg_catalog,pg_temp AS $overlap_open$
DECLARE v_from text;v_to text;v_appr text;v_ttl integer;v_admit boolean;v_mgen text;v_mstatus text;v_pol text;
 v_now timestamptz;w sessions.ingest_generation_overlap_windows%ROWTYPE;
BEGIN
 IF current_user<>(SELECT pg_get_userbyid(proowner) FROM pg_proc
  WHERE oid='sessions.ingest_generation_overlap_open(jsonb)'::regprocedure) THEN
  RAISE EXCEPTION USING ERRCODE='42501',MESSAGE='generation overlap: owner required';END IF;
 PERFORM sessions.ingest_exact_keys(p,ARRAY['from','to','ttlSeconds','admitDuringApply','approvalSha256']);
 v_from:=sessions.ingest_digest(p->'from');v_to:=sessions.ingest_digest(p->'to');v_appr:=sessions.ingest_digest(p->'approvalSha256');
 IF v_from=v_to THEN RAISE EXCEPTION USING ERRCODE='22023',MESSAGE='generation overlap: from and to must differ';END IF;
 IF jsonb_typeof(p->'ttlSeconds') IS DISTINCT FROM 'number' OR p->>'ttlSeconds'!~'^[1-9][0-9]{1,4}$'
  OR (p->>'ttlSeconds')::integer NOT BETWEEN 60 AND 14400 THEN
  RAISE EXCEPTION USING ERRCODE='22023',MESSAGE='generation overlap: ttlSeconds must be an integer from 60 to 14400';END IF;
 IF jsonb_typeof(p->'admitDuringApply') IS DISTINCT FROM 'boolean' THEN
  RAISE EXCEPTION USING ERRCODE='22023',MESSAGE='generation overlap: admitDuringApply must be a boolean';END IF;
 v_ttl:=(p->>'ttlSeconds')::integer;v_admit:=(p->>'admitDuringApply')::boolean;
 -- Serialize with the canonical migrator and the rebind (same advisory namespace).
 PERFORM pg_advisory_xact_lock(961996,1);
 SELECT generation,status INTO v_mgen,v_mstatus FROM sessions.__96bulls_role_validation
  WHERE name='session_directory_search_worker' FOR SHARE;
 IF v_mgen IS DISTINCT FROM v_from OR v_mstatus IS DISTINCT FROM 'pass' THEN
  RAISE EXCEPTION USING ERRCODE='55000',MESSAGE='generation overlap: readiness is not PASS for from';END IF;
 -- Exactly one lazy custody policy, at from: the window only exists for the lazy-current path (missing = refusal).
 SELECT generation INTO v_pol FROM sessions.ingest_lazy_policy WHERE singleton FOR SHARE;
 IF NOT FOUND OR v_pol IS DISTINCT FROM v_from THEN
  RAISE EXCEPTION USING ERRCODE='55000',MESSAGE='generation overlap: custody policy is not at from';END IF;
 -- No downgrade: neither end may be a retired generation (the policy record above), and a generation that was
 -- ever a window's `from` is never a window's `to`.
 IF EXISTS(SELECT 1 FROM sessions.ingest_generation_overlap_retired WHERE generation IN(v_from,v_to))
  OR EXISTS(SELECT 1 FROM sessions.ingest_generation_overlap_windows WHERE from_generation=v_to) THEN
  RAISE EXCEPTION USING ERRCODE='55000',MESSAGE='generation overlap: generation already retired';END IF;
 v_now:=clock_timestamp();
 UPDATE sessions.ingest_generation_overlap_windows SET closed_at=v_now,closed_reason='expired'
  WHERE closed_at IS NULL AND expires_at<=v_now;
 IF EXISTS(SELECT 1 FROM sessions.ingest_generation_overlap_windows WHERE closed_at IS NULL) THEN
  RAISE EXCEPTION USING ERRCODE='55000',MESSAGE='generation overlap: a window is already open';END IF;
 INSERT INTO sessions.ingest_generation_overlap_windows(from_generation,to_generation,admit_during_apply,approval_sha256,opened_by,opened_at,expires_at)
  VALUES(v_from,v_to,v_admit,v_appr,session_user::text,v_now,v_now+make_interval(secs=>v_ttl)) RETURNING * INTO w;
 RETURN jsonb_build_object('windowId',w.window_id::text,'from',w.from_generation,'to',w.to_generation,
  'admitDuringApply',w.admit_during_apply,'openedAt',w.opened_at,'expiresAt',w.expires_at);
END $overlap_open$;

CREATE FUNCTION sessions.ingest_generation_overlap_close(p jsonb) RETURNS jsonb
LANGUAGE plpgsql VOLATILE SET search_path=pg_catalog,pg_temp AS $overlap_close$
DECLARE v_from text;v_to text;v_reason text;v_mgen text;v_mstatus text;v_pol text;w sessions.ingest_generation_overlap_windows%ROWTYPE;
BEGIN
 IF current_user<>(SELECT pg_get_userbyid(proowner) FROM pg_proc
  WHERE oid='sessions.ingest_generation_overlap_close(jsonb)'::regprocedure) THEN
  RAISE EXCEPTION USING ERRCODE='42501',MESSAGE='generation overlap: owner required';END IF;
 PERFORM sessions.ingest_exact_keys(p,ARRAY['from','to','reason']);
 v_from:=sessions.ingest_digest(p->'from');v_to:=sessions.ingest_digest(p->'to');v_reason:=p->>'reason';
 IF jsonb_typeof(p->'reason') IS DISTINCT FROM 'string' OR v_reason NOT IN('owner','rebind') THEN
  RAISE EXCEPTION USING ERRCODE='22023',MESSAGE='generation overlap: reason must be owner or rebind';END IF;
 PERFORM pg_advisory_xact_lock(961996,1);
 IF v_reason='rebind' THEN
  SELECT generation,status INTO v_mgen,v_mstatus FROM sessions.__96bulls_role_validation
   WHERE name='session_directory_search_worker' FOR SHARE;
  SELECT generation INTO v_pol FROM sessions.ingest_lazy_policy WHERE singleton FOR SHARE;
  IF v_mgen IS DISTINCT FROM v_to OR v_mstatus IS DISTINCT FROM 'pass' OR v_pol IS DISTINCT FROM v_to THEN
   RAISE EXCEPTION USING ERRCODE='55000',MESSAGE='generation overlap: rebind close requires PASS and policy at to';END IF;
 END IF;
 -- Waits for every in-flight transaction the window admitted (they hold the row FOR SHARE).
 SELECT * INTO w FROM sessions.ingest_generation_overlap_windows WHERE closed_at IS NULL FOR UPDATE;
 IF NOT FOUND THEN RETURN jsonb_build_object('closed',false);END IF;
 IF w.from_generation<>v_from OR w.to_generation<>v_to THEN
  RAISE EXCEPTION USING ERRCODE='55000',MESSAGE='generation overlap: open window does not match';END IF;
 UPDATE sessions.ingest_generation_overlap_windows SET closed_at=clock_timestamp(),
  closed_reason=CASE WHEN expires_at<=clock_timestamp() THEN 'expired' ELSE v_reason END
  WHERE window_id=w.window_id RETURNING * INTO w;
 RETURN jsonb_build_object('closed',true,'windowId',w.window_id::text,'reason',w.closed_reason,'closedAt',w.closed_at);
END $overlap_close$;

-- Replaces 20261104050000:58-66. Identical result AND identical locking while no window is open: the exact
-- PASS match still takes the marker row FOR SHARE (so a later pending write waits for it). A transaction
-- admitted through the window holds the WINDOW row FOR SHARE instead and never locks the marker, so the
-- migrator's own marker writes (pending, phase-2 PASS) never wait on, or deadlock with, live uploads.
CREATE OR REPLACE FUNCTION sessions.ingest_require_generation(p_expected text) RETURNS void
LANGUAGE plpgsql VOLATILE SET search_path=pg_catalog,pg_temp AS $generation$
DECLARE v_gen text;v_status text;
BEGIN
 IF p_expected IS NULL OR p_expected!~'^[0-9a-f]{64}$'
 THEN RAISE EXCEPTION USING ERRCODE='22023',MESSAGE='session ingest: generation required';END IF;
 PERFORM 1 FROM sessions.__96bulls_role_validation WHERE name='session_directory_search_worker'
  AND generation=p_expected AND status='pass' FOR SHARE;
 IF FOUND THEN RETURN;END IF;
 SELECT generation,status INTO v_gen,v_status FROM sessions.__96bulls_role_validation
  WHERE name='session_directory_search_worker';
 IF sessions.ingest_generation_overlap_admits(p_expected,v_gen,v_status) THEN RETURN;END IF;
 RAISE EXCEPTION USING ERRCODE='55000',MESSAGE='session ingest: generation not ready';
END $generation$;

-- Replaces 20261104055000:423-439. Identical result and locking while no window is open (the marker is read
-- FOR SHARE only when PASS, as before; the admission then equals the PASS generation through the policy).
-- Through the window the marker is read without a lock (see ingest_require_generation above).
CREATE OR REPLACE FUNCTION sessions.ingest_lazy_guard(p_org text) RETURNS void
LANGUAGE plpgsql VOLATILE SET search_path=pg_catalog,pg_temp AS $lazy_guard$
DECLARE pol sessions.ingest_lazy_policy%ROWTYPE;c sessions.ingest_receipt_seat_clock%ROWTYPE;v_gen text;v_pass text;v_mgen text;v_mstatus text;
BEGIN
 SELECT generation INTO v_pass FROM sessions.__96bulls_role_validation
  WHERE name='session_directory_search_worker' AND status='pass' FOR SHARE;
 SELECT * INTO STRICT pol FROM sessions.ingest_lazy_policy WHERE singleton FOR SHARE;
 SELECT * INTO STRICT c FROM sessions.ingest_receipt_seat_clock WHERE singleton;
 IF v_pass IS NOT NULL AND pol.generation=v_pass THEN v_gen:=v_pass;
 ELSE
  SELECT generation,status INTO v_mgen,v_mstatus FROM sessions.__96bulls_role_validation
   WHERE name='session_directory_search_worker';
  IF sessions.ingest_generation_overlap_admits(pol.generation,v_mgen,v_mstatus) THEN v_gen:=pol.generation;END IF;
 END IF;
 IF v_gen IS NULL OR pol.generation<>v_gen OR pol.valid_until<=clock_timestamp()
  OR c.source_identity_sha256<>pol.source_identity_sha256 OR c.control_epoch<>pol.control_epoch
  OR c.baseline->>'sourceProofSha256' IS DISTINCT FROM pol.source_proof_sha256 THEN
  RAISE EXCEPTION USING ERRCODE='55000',MESSAGE='session ingest: current custody policy unavailable';END IF;
 PERFORM 1 FROM sessions.ingest_buffer_admission WHERE org_id=p_org AND schema_generation=v_gen
  AND control_epoch=pol.control_epoch AND privacy_baseline_sha256=pol.privacy_baseline_sha256
  AND retention_contract_sha256=pol.retention_contract_sha256 AND valid_until>clock_timestamp() FOR SHARE;
 IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE='55000',MESSAGE='session ingest: buffered admission closed';END IF;
END $lazy_guard$;

