-- SLOT 044080. Ingest claim sessions: a per-(claim, source, session) side table derived from
-- sessions.ingest_claim_attempts.records, its single-row policy and its writer trigger. PR 1 of 2: INERT.
--
-- Why: the owner buffered readers (sessions.buffered_sessions_for and friends, 043700/043860) find a
-- session's claims by scanning ingest_claim_attempts with a jsonb containment on records
-- (a.records @> [{source, session_id}]), which no index serves per tenant. This side table holds exactly the
-- distinct (source, session_id) pairs of each claim's records, keyed by claim, with the tenant columns copied
-- from the claim, so PR 2 can serve those lookups from a btree. PR 1 only creates and fills it; no reader
-- uses it yet.
--
-- Where records is written: once, at INSERT, by sessions.ingest_claim_batch_mode (latest body 043850); the
-- only later rewrite is the owner-only retirement (038000), which sets records to NULL once and for good.
-- So the writer trigger runs AFTER INSERT OR UPDATE OF records on ingest_claim_attempts: on INSERT it adds
-- the claim's distinct pairs; on UPDATE it also deletes the claim's side rows whose pair is no longer present
-- (all of them on retirement). An element that is not an object, or whose source or session_id is not a
-- JSON string, is skipped; the trigger never raises on record content, so it cannot break a claim.
--
-- Inert: sessions.ingest_claim_sessions_policy has one row, write_enabled=false. While it is false (or the
-- row is absent) the trigger returns before touching anything. Enabling it, and running the backfill
-- (scripts/backfill-ingest-claim-sessions.ts), are owner operator steps in
-- docs/handoffs/ingest-claim-sessions-044080/operator-packet.md. The side table is complete only once the
-- policy's backfill_complete_at is set, which the CHECK allows only while write_enabled; any write_enabled
-- change clears the cursor and completion (claim tokens are random uuids, so a cursor walk is complete only
-- if the writer was on before the walk started). Turning the writer on takes SHARE on ingest_claim_attempts
-- inside the policy UPDATE (statement-level, before the policy tuple is locked), so it waits for every in-flight claim transaction whose trigger may have read
-- write_enabled=false; a non-read-committed claim reads the policy FOR SHARE (a policy change after its
-- snapshot fails it with 40001 instead of silently skipping).
--
-- accepted_at is the claim's batch committed_at when that batch is committed at the time the side row is
-- written, else NULL. The claim precedes the batch commit, so trigger-written rows normally carry NULL and
-- the backfill fills it for batches committed by then; it is a sort hint only. Readers must keep joining
-- sessions.ingest_batches for commit authority (as the buffered readers do today).
--
-- Grants: as sessions.ingest_claim_attempts (030000): RLS on with no policy, every default grantee
-- stripped, owner only. The buffered readers are SECURITY DEFINER, so no runtime role needs a grant.
-- Transactional-migrator safe: plain CREATE INDEX on a new, empty table; no CONCURRENTLY.
-- Down path: supabase/rollbacks/20261105044080_ingest_claim_sessions.down.sql (generated by
-- scripts/sessions-function-boundary/lanes/ingest-claim-sessions.ts).
-- Code only: applying this to any real database needs Khaliq's separate, explicit OK.
SET LOCAL lock_timeout='5s';

DO $claim_sessions_creator$
DECLARE me oid;
BEGIN
 SELECT oid INTO STRICT me FROM pg_roles WHERE rolname=current_user;
 IF (SELECT count(*) FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace
   WHERE n.nspname='sessions' AND c.relkind='r' AND c.relname IN('ingest_claim_attempts','ingest_batches')
    AND c.relowner=me)<>2
  OR to_regclass('sessions.ingest_claim_sessions') IS NOT NULL
  OR to_regclass('sessions.ingest_claim_sessions_policy') IS NOT NULL
  OR to_regprocedure('sessions.ingest_claim_sessions_sync()') IS NOT NULL
  OR to_regprocedure('sessions.ingest_claim_sessions_policy_guard()') IS NOT NULL THEN
  RAISE EXCEPTION USING ERRCODE='55000',MESSAGE='ingest claim sessions: requires the owner of the claim tables and no prior claim-session objects';END IF;
END $claim_sessions_creator$;

CREATE TABLE sessions.ingest_claim_sessions(
 claim_token uuid NOT NULL REFERENCES sessions.ingest_claim_attempts(claim_token) ON DELETE CASCADE,
 source text NOT NULL,
 session_id text NOT NULL,
 org_id text NOT NULL,
 workspace_id text NOT NULL,
 user_id text NOT NULL,
 origin_id text NOT NULL,
 batch_id text NOT NULL,
 digest text NOT NULL,
 reset_epoch bigint,
 accepted_at timestamptz,
 PRIMARY KEY(claim_token,source,session_id)
);
CREATE INDEX ingest_claim_sessions_session_idx
 ON sessions.ingest_claim_sessions(org_id,workspace_id,user_id,source,session_id);
CREATE INDEX ingest_claim_sessions_accepted_idx
 ON sessions.ingest_claim_sessions(org_id,workspace_id,user_id,accepted_at DESC NULLS LAST,session_id,source);

CREATE TABLE sessions.ingest_claim_sessions_policy(
 singleton boolean PRIMARY KEY DEFAULT true CHECK(singleton),
 write_enabled boolean NOT NULL DEFAULT false,
 backfill_complete_at timestamptz,
 backfill_cursor text CHECK(backfill_cursor IS NULL OR backfill_cursor~'^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'),
 updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
 CHECK(backfill_complete_at IS NULL OR write_enabled)
);
INSERT INTO sessions.ingest_claim_sessions_policy(singleton,write_enabled) VALUES(true,false);

