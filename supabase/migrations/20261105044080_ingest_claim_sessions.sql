-- Default privileges may have granted the new tables to another role at creation: strip every non-owner grantee.
DO $claim_sessions_acl$
DECLARE v_table regclass;v_grantee text;
BEGIN
 FOREACH v_table IN ARRAY ARRAY['sessions.ingest_claim_sessions'::regclass,'sessions.ingest_claim_sessions_policy'::regclass] LOOP
  FOR v_grantee IN
   SELECT DISTINCT r.rolname FROM pg_class AS c
    CROSS JOIN LATERAL aclexplode(coalesce(c.relacl,acldefault('r',c.relowner))) AS a
    JOIN pg_roles AS r ON r.oid=a.grantee
   WHERE c.oid=v_table AND a.grantee<>c.relowner
  LOOP
   EXECUTE format('REVOKE ALL ON %s FROM %I',v_table,v_grantee);
  END LOOP;
 END LOOP;
END $claim_sessions_acl$;

-- The policy row is never deleted (rollback drops the table instead), and any write_enabled change restarts
-- the backfill: cursor and completion are cleared. Turning the writer ON first waits for every in-flight claim
-- transaction (SHARE conflicts with their ROW EXCLUSIVE), so none can commit a claim its trigger skipped
-- after this UPDATE commits; a backfill started after that commit therefore sees every claim the trigger missed.
-- The statement-level firing takes that SHARE lock before the UPDATE locks the policy tuple: otherwise a
-- non-read-committed claim already holding ROW EXCLUSIVE and waiting on the row FOR SHARE would deadlock with
-- the enabler. The row-level LOCK stays as the fallback for a statement that raced a concurrent disable.
CREATE FUNCTION sessions.ingest_claim_sessions_policy_guard() RETURNS trigger
LANGUAGE plpgsql VOLATILE SET search_path=pg_catalog,pg_temp AS $claim_sessions_policy$
BEGIN
 IF TG_LEVEL='STATEMENT' THEN
  IF EXISTS(SELECT 1 FROM sessions.ingest_claim_sessions_policy AS p WHERE NOT p.write_enabled) THEN
   LOCK TABLE sessions.ingest_claim_attempts IN SHARE MODE;
  END IF;
  RETURN NULL;
 END IF;
 IF TG_OP<>'UPDATE' THEN RAISE EXCEPTION USING ERRCODE='55000',MESSAGE='ingest claim sessions: the policy row is never deleted';END IF;
 IF NEW.write_enabled IS DISTINCT FROM OLD.write_enabled THEN
  NEW.backfill_cursor:=NULL;NEW.backfill_complete_at:=NULL;
  IF NEW.write_enabled THEN LOCK TABLE sessions.ingest_claim_attempts IN SHARE MODE;END IF;
 END IF;
 NEW.updated_at:=clock_timestamp();
 RETURN NEW;
END $claim_sessions_policy$;
CREATE TRIGGER ingest_claim_sessions_policy_guard BEFORE UPDATE OR DELETE ON sessions.ingest_claim_sessions_policy
 FOR EACH ROW EXECUTE FUNCTION sessions.ingest_claim_sessions_policy_guard();
CREATE TRIGGER ingest_claim_sessions_policy_lock BEFORE UPDATE OF write_enabled ON sessions.ingest_claim_sessions_policy
 FOR EACH STATEMENT EXECUTE FUNCTION sessions.ingest_claim_sessions_policy_guard();

-- The writer. Does nothing unless the policy row says write_enabled. Never raises on record content.
CREATE FUNCTION sessions.ingest_claim_sessions_sync() RETURNS trigger
LANGUAGE plpgsql VOLATILE SET search_path=pg_catalog,pg_temp AS $claim_sessions_sync$
DECLARE v_enabled boolean;v_records jsonb;
BEGIN
 IF current_setting('transaction_isolation')='read committed' THEN
  SELECT p.write_enabled INTO v_enabled FROM sessions.ingest_claim_sessions_policy AS p WHERE p.singleton;
 ELSE
  SELECT p.write_enabled INTO v_enabled FROM sessions.ingest_claim_sessions_policy AS p WHERE p.singleton FOR SHARE;
 END IF;
 IF NOT coalesce(v_enabled,false) THEN RETURN NULL;END IF;
 v_records:=CASE WHEN jsonb_typeof(NEW.records)='array' THEN NEW.records ELSE '[]'::jsonb END;
 IF TG_OP='UPDATE' THEN
  DELETE FROM sessions.ingest_claim_sessions AS s
   WHERE s.claim_token=NEW.claim_token
     AND NOT EXISTS(SELECT 1 FROM jsonb_array_elements(v_records) AS e(v)
      WHERE jsonb_typeof(e.v)='object' AND e.v->'source'=to_jsonb(s.source) AND e.v->'session_id'=to_jsonb(s.session_id));
 END IF;
 INSERT INTO sessions.ingest_claim_sessions(claim_token,source,session_id,org_id,workspace_id,user_id,origin_id,batch_id,digest,reset_epoch,accepted_at)
 SELECT DISTINCT NEW.claim_token,e.v->>'source',e.v->>'session_id',NEW.org_id,NEW.workspace_id,NEW.user_id,NEW.origin_id,NEW.batch_id,
        NEW.digest,NEW.reset_epoch,
        (SELECT b.committed_at FROM sessions.ingest_batches AS b
          WHERE b.org_id=NEW.org_id AND b.workspace_id=NEW.workspace_id AND b.origin_id=NEW.origin_id AND b.batch_id=NEW.batch_id
            AND b.state='committed')
   FROM jsonb_array_elements(v_records) AS e(v)
  WHERE jsonb_typeof(e.v)='object' AND jsonb_typeof(e.v->'source')='string' AND jsonb_typeof(e.v->'session_id')='string'
 ON CONFLICT(claim_token,source,session_id) DO NOTHING;
 RETURN NULL;
END $claim_sessions_sync$;
CREATE TRIGGER ingest_claim_sessions_sync AFTER INSERT OR UPDATE OF records ON sessions.ingest_claim_attempts
 FOR EACH ROW EXECUTE FUNCTION sessions.ingest_claim_sessions_sync();

